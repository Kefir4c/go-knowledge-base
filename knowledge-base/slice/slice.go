//1. ЧТО ТАКОЕ СЛАЙС.
/*
ЧТО ЭТО:
- Слайс — это динамический массив с удобным API для работы с последовательностями.
- Состоит из 3 полей:
  • Указатель на данные (data)
  • Длина (len) — текущее количество элементов
  • Емкость (cap) — сколько элементов может вместить без выделения новой памяти

ПОЧЕМУ ЭТО ВАЖНО:
- Слайсы — основной способ работы с последовательностями в Go (массивы используются редко).
- Понимание структуры слайса позволяет избежать «неприятных сюрпризов» (например, неожиданного изменения данных).

ПРИМЕР БАЗОВОГО СЛАЙСА:
*/
func demBasicSlice() {
	// Создание через литерал
	numbers := []int{1, 2, 3}

	// Создание через make
	// make([]T, len, cap) - cap можно опустить
	names := make([]string, 3, 5)
	namesv2 := make([]string, 0)

	fmt.Printf("Numbers: len=%d, cap=%d\n", len(numbers), cap(numbers))
	fmt.Printf("Names: len=%d, cap=%d\n", len(names), cap(names))
	fmt.Printf("namesv2: len=%d, cap=%d\n", len(namesv2), cap(namesv2))

}

// 2. ДЛИНА И ЕМКОСТЬ
/*
ЗАЧЕМ ЭТО НУЖНО ЗНАТЬ:
- len — текущее количество элементов (сколько реально в слайсе).
- cap — сколько элементов может вместить слайс без выделения новой памяти.

КЛЮЧЕВЫЕ НЮАНСЫ:
- Если `len == cap`, то следующее добавление через `append` вызовет выделение новой памяти.
- При изменении элемента через индекс меняются данные в исходном слайсе (потому что данные общие!).

ПРИМЕР С ДЛИНОЙ И ЕМКОСТЬЮ:
*/

func demLenCap() {
	// Слайс с cap > len
	s := make([]int, 2, 5)
	fmt.Printf("Initial: len=%d, cap=%d\n", len(s), cap(s))

	// Добавление элементов через append
	s = append(s, 10)
	fmt.Printf("After append: len=%d, cap=%d\n", len(s), cap(s)) // len=3, cap=5

	// Изменение через индекс
	s[0] = 100
	fmt.Println("s[0] =", s[0]) // 100

	// Два слайса могут ссылаться на одни данные!
	other := s[:2]
	other[0] = 200
	fmt.Println("s[0] after change =", s[0])
}

// 3. APPEND И MAKE
/*
КАК РАБОТАЕТ APPEND:
- Если `len < cap` → добавляет элемент в существующую память.
- Если `len == cap` → выделяет новую память, копирует данные и увеличивает емкость.

КАК РАБОТАЕТ MAKE:
- `make([]T, len, cap)` — выделяет память под `cap` элементов, устанавливает `len` и `cap`.
- Если `cap` не указан → `cap = len`.

ПОЧЕМУ ЭТО ВАЖНО:
- Неправильное использование `make` → лишние выделения памяти → падение производительности.
- `append` **не изменяет исходный слайс** (всегда возвращает новый слайс с обновленными данными).

ПРИМЕР С APPEND И MAKE:
*/
func demAppMake() {
	//Плохой способ (лишнее выделение памяти)
	s := []int{}
	for i := 0; i < 1000; i++ {
		s = append(s, i) // удваивает емкость (cap = cap * 2)
	}

	// Хороший способ (предварительное выделение памяти)
	s = make([]int, 0, 1000) // Выделяем память на 1000 элементов
	for i := 0; i < 1000; i++ {
		s = append(s, i) // Нет копирования → O(n)
	}

	// Важно: make возвращает слайс с нулевыми значениями!
	zeroSlice := make([]int, 5) // [0, 0, 0, 0, 0]
	fmt.Println("Zero slice:", zeroSlice)
}

// 4. GROWSLICE И КЭШ

/*
КАК РАБОТАЕТ GROWSLICE (внутренний механизм роста):
- Если `cap < 1024` → удваивает емкость (cap = cap * 2).
- Если `cap >= 1024` → увеличивает на 25% (cap = cap + cap/4).

ПОЧЕМУ ЭТО ВАЖНО:
- При росте слайса происходит копирование данных → дорого для больших слайсов.
- Понимание алгоритма позволяет предсказать, когда произойдет копирование.

ПРИМЕР С GROWSLICE:
*/
func demAppendMake() {
	// Проверим, как растет слайс
	s := make([]int, 0, 1)
	capacities := []int{}

	for i := 0; i < 20; i++ {
		s = append(s, i)
		capacities = append(capacities, cap(s))
	}

	fmt.Println("Capacities:", capacities)
}

// 5. КАК РАБОТАЕТ ДОСТУП ПО ИНДЕКСУ С ИСПОЛЬЗОВАНИЕМ КЭША
/*
ПОЧЕМУ ПОСЛЕДОВАТЕЛЬНЫЙ ОБХОД БЫСТРЕЕ:
- CPU загружает данные в кэш блоками по 64 байта (cache lines).
- При последовательном обходе (i++) все данные уже в кэше → быстрее.

ПРИМЕР С КЭШЕМ:
*/
func demCacheSlice() {
	const size = 2000
	matrix := make([][]int, size)

	// Инициализируем матрицу
	for i := 0; i < size; i++ {
		matrix[i] = make([]int, size)
	}

	// Быстрый обход (последовательный)
	start := time.Now()
	for i := 0; i < size; i++ {
		for j := 0; j < size; j++ {
			matrix[i][j] = 1
		}
	}
	fmt.Printf("Row-major: %v\n", time.Since(start))

	// Медленный обход (прыжки по памяти)
	start = time.Now()
	for j := 0; j < size; j++ {
		for i := 0; i < size; i++ {
			matrix[i][j] = 2
		}
	}
	fmt.Printf("Column-major: %v\n", time.Since(start))
}

// 6. ПАКЕТ SLICES
/*
### СТАНДАРТНЫЕ ОПЕРАЦИИ НА СЛАЙСАХ

• Что это: Встроенный пакет `slices` предоставляет функции для работы со слайсами.
• Зачем нужен: До Go 1.21 приходилось писать велосипеды (поиск, сортировка, сравнение).
• Главное преимущество: Типобезопасность + читаемость + производительность (без reflect!).

ОСНОВНЫЕ ФУНКЦИИ:
- slices.Contains(s, v)       → есть ли значение в слайсе?
- slices.Index(s, v)         → индекс первого вхождения (или -1)
- slices.Equal(a, b)         → равны ли два слайса?
- slices.Clone(s)            → создаёт независимую копию
- slices.Sort(s)             → сортирует in-place (только для упорядочиваемых типов)
- slices.Delete(s, i, j)     → удаляет элементы [i:j)
- slices.Insert(s, i, vs...) → вставляет элементы в позицию i
- slices.Compact(s)          → удаляет **последовательные** дубликаты

ВАЖНО:
- Все функции работают только со слайсами, не с массивами.
- Требуется Go ≥ 1.21 (`import "slices"`).
- Не использует рефлексию → быстрее аналогов из `golang.org/x/exp/slices`.

ПРИМЕРЫ:
*/
func demSlicesPackage() {
	nums := []int{3, 1, 4, 1, 5}

	// Поиск
	if slices.Contains(nums, 4) {
		fmt.Println("4 найдено!")
	}
	idx := slices.Index(nums, 1) // 1 (первое вхождение)
	fmt.Println("Вхождения:", idx)

	// Клонирование (безопасная копия)
	copyNums := slices.Clone(nums)
	copyNums[0] = 999
	fmt.Println("Оригинал не изменился:", nums[0]) // 3

	// Сравнение
	fmt.Println("Равны?", slices.Equal(nums, []int{3, 1, 4, 1, 5})) // true

	// Удаление (возвращает НОВЫЙ слайс!)
	withoutOnes := slices.Delete(nums, 1, 2)     // удаляем элемент под индексом 1
	fmt.Println("Без первого '1':", withoutOnes) // [3, 4, 1, 5]

	// Сортировка (in-place)
	slices.Sort(nums)
	fmt.Println("Отсортировано:", nums) // [1, 1, 3, 4, 5]
	// Compact — удаляет только соседние дубликаты!
	data := []string{"a", "a", "b", "c", "c", "c", "b"}
	compact := slices.Compact(data)
	fmt.Println(data)
	fmt.Println("После Compact:", compact) // ["a", "b", "c", "b"]

	// Чтобы удалить ВСЕ дубликаты — сначала сортируем:
	slices.Sort(data)
	allUnique := slices.Compact(data)
	fmt.Println("Все уникальные:", allUnique) // ["a", "b", "c"]
}

/*
#### slices.Clone vs copy — в чём разница?

| slices.Clone(s)                | copy(dst, src)                     |
|-------------------------------|------------------------------------|
| Создаёт НОВЫЙ слайс           | Копирует в СУЩЕСТВУЮЩИЙ dst        |
| Автоматически выделяет память | Требует предварительного make(dst) |
| Простота использования        | Больше контроля над памятью        |
| Подходит для любых размеров   | Быстрее для больших данных         |

Пример сравнения:
*/
func compCloneVsCopy() {
	src := []int{1, 2, 3, 4, 5}

	// Clone — просто и безопасно
	cloned := slices.Clone(src)
	cloned[0] = 999
	fmt.Println("Clone не влияет на оригинал:", src[0]) // 1

	// Copy — эффективно для больших данных
	dst := make([]int, len(src))
	n := copy(dst, src)
	fmt.Printf("Скопировано %d элементов\n", n) // 5
}

/*
Как писать свои генерик-функции для слайсов
Go позволяет создавать собственные функции с типобезопасностью через generics.
Пример: функция, которая фильтрует слайс по условию.
*/
func Filter[T any](s []T, fn func(T) bool) []T {
	var result []T
	for _, v := range s {
		if fn(v) {
			result = append(result, v)
		}
	}
	return result
}

func demonstrateCustomGeneric() {
	nums := []int{1, 2, 3, 4, 5, 6}
	evens := Filter(nums, func(n int) bool {
		return n%2 == 0
	})
	fmt.Println("Чётные числа:", evens) // [2 4 6]

	// Работает и со строками!
	words := []string{"go", "rust", "java", "python"}
	longWords := Filter(words, func(w string) bool {
		return len(w) > 3
	})
	fmt.Println("Длинные слова:", longWords) // [rust java python]
}

// 7. ВАЖНЫЕ ПРЕДУПРЕЖДЕНИЯ И BEST PRACTICES
/*
1. НИКОГДА не передавай слайс как указатель (например, *[]int) — это антипаттерн.
   Слайс и так содержит указатель на данные.

2. Будь осторожен с `s = s[:len(s)-1]` — может привести к утечке памяти.
   Если `cap` большой, а `len` маленький, данные не будут удалены.

3. Используй `copy` вместо `append` для копирования больших слайсов.
   `copy(dst, src)` работает быстрее, чем `append` для больших данных.

4. Предварительно выделяй память через `make` для больших слайсов.
   Это уменьшит количество выделений памяти в 2-3 раза.
*/

