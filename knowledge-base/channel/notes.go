package channel

import "fmt"

/*
CLOSE() — ЗАКРЫТИЕ КАНАЛОВ

ЧТО ЭТО:
close() — встроенная функция, которая закрывает канал, запрещая дальнейшие отправки
и сигнализируя читателям, что данные закончились.

ЗОЛОТОЕ ПРАВИЛО:
"Кто создал канал — тот и закрывает. И только один раз."

ЧТО БУДЕТ ПОСЛЕ close():
- Отправка (ch <- x) → PANIC: send on closed channel
- Повторный close(ch) → PANIC: close of closed channel
- Чтение (x, ok := <-ch) → ok == false, x == zero value типа
- Range по каналу → завершается после чтения всех данных

ПРОБЛЕМЫ БЕЗ close():
- Range по каналу будет ждать вечно → deadlock
- Читатели не узнают, что данные закончились
- Горутины могут никогда не завершиться → утечка памяти

КОГДА НУЖНО close():
- Когда читатель использует for range
- Когда нужно сигнализировать "больше данных не будет"
- Когда несколько читателей ждут данные

КОГДА НЕ НУЖНО close():
- Паттерн "один запрос — один ответ"
- Канал живет всё время работы программы
- Программа завершается (ОС всё очистит)
*/

func closeBasics() {
	// ПРИМЕР 1: Чтение из закрытого канала
	ch1 := make(chan int, 2)
	ch1 <- 10
	ch1 <- 20
	close(ch1)

	fmt.Println(<-ch1) // 10
	fmt.Println(<-ch1) // 20
	fmt.Println(<-ch1) // 0 (zero value)

	v, ok := <-ch1
	fmt.Println(v, ok) // 0, false

	// ПРИМЕР 2: Range с close (правильно)
	ch2 := make(chan int, 3)
	go func() {
		for i := 1; i <= 3; i++ {
			ch2 <- i
		}
		close(ch2) // ❗ БЕЗ ЭТОГО range НЕ ВЫЙДЕТ
	}()

	for v := range ch2 {
		fmt.Println(v) // 1, 2, 3
	}

	// ПРИМЕР 3: Паника при отправке в закрытый канал
	ch3 := make(chan int)
	close(ch3)
	// ch3 <- 42  // ❌ PANIC: send on closed channel

	// ПРИМЕР 4: Паника при двойном закрытии
	ch4 := make(chan int)
	close(ch4)
	// close(ch4)  // ❌ PANIC: close of closed channel

	// ПРИМЕР 5: Паника при закрытии nil канала
	var ch5 chan int
	// close(ch5)  // ❌ PANIC: close of nil channel
}

/*
ИДИОМА ПРОВЕРКИ ЗАКРЫТИЯ:

value, ok := <-ch
if !ok {
    fmt.Println("Канал закрыт, данных больше нет")
    return
}
fmt.Println("Получено:", value)
*/

func checkClose() {
	ch := make(chan int)
	close(ch)

	// Единственный безопасный способ проверить, закрыт ли канал
	v, ok := <-ch
	fmt.Printf("value: %v, ok: %v\n", v, ok) // value: 0, ok: false
}

/*
ОСНОВНЫЕ ОШИБКИ С close():

1. Отправить после close → panic
2. Закрыть повторно → panic
3. Закрыть nil → panic
4. Закрыть не тот канал (не создатель) → возможно, но антипаттерн
5. Забыть close перед range → deadlock
*/

func commonMistakes() {
	// ОШИБКА 1: Range без close → DEADLOCK
	ch := make(chan int, 3)
	go func() {
		for i := 0; i < 3; i++ {
			ch <- i
		}
		// ❌ ЗАБЫЛИ close(ch)
	}()

	// for v := range ch {  // ДЕДЛОК! будет ждать вечно
	//     fmt.Println(v)
	// }

	// ОШИБКА 2: Отправка в закрытый канал → PANIC
	ch2 := make(chan int)
	close(ch2)
	// ch2 <- 42  // PANIC!

	// ОШИБКА 3: Двойное закрытие → PANIC
	ch3 := make(chan int)
	close(ch3)
	// close(ch3)  // PANIC!
}

/*
КОГДА ИСПОЛЬЗУЕТСЯ НА ПРАКТИКЕ:

1. Паттерн "генератор" — канал создается и закрывается внутри функции
2. Fan-in — после слияния каналов, результирующий канал закрывается через WaitGroup
3. Worker Pool — канал задач закрывается после отправки всех задач
4. Pipeline — каждый этап закрывает свой выходной канал после обработки
*/

func practicalPatterns() {
	// ПАТТЕРН: Генератор сам закрывает канал
	gen := func(nums ...int) <-chan int {
		out := make(chan int)
		go func() {
			defer close(out) // ✅ закрываем внутри
			for _, n := range nums {
				out <- n
			}
		}()
		return out
	}

	for v := range gen(1, 2, 3, 4, 5) {
		fmt.Println(v)
	}
}

/*
ШПАРГАЛКА (что нужно помнить):

┌─────────────────────────────────────────────────────────────┐
│ close(ch)                                                   │
├─────────────────────────────────────────────────────────────┤
│ ✅ Читать можно (получим zero value)                        │
│ ❌ Писать нельзя (panic)                                    │
│ ❌ Дважды закрывать нельзя (panic)                          │
│ ❌ nil канал закрывать нельзя (panic)                       │
│ ✅ Нужен для for range                                      │
│ ✅ Нужен для сигнала "данные кончились"                     │
│ ❌ Не нужен для "один запрос → один ответ"                  │
└─────────────────────────────────────────────────────────────┘
*/

