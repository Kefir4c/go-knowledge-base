package _interface

import (
	"fmt"
	"unsafe"
)

/*
ЧАСТЫЕ ВОПРОСЫ ПО ИНТЕРФЕЙСАМ НА СОБЕСЕДОВАНИЯХ
*/

// Q: Что такое интерфейс в Go?
/*
   Интерфейс — это набор методов. Тип реализует интерфейс неявно,
   если реализует все его методы. Это основа полиморфизма в Go.
*/

// Q: Что такое пустой интерфейс?
/*
   interface{} (или any в Go 1.18+) — это интерфейс без методов.
   Может хранить значение любого типа. Занимает 16 байт на amd64
   (указатель на тип + указатель на данные).
*/

// Q: Почему сравнение interface{} с nil иногда даёт false, даже если значение nil?
/*
   Потому что интерфейс состоит из двух частей: (тип, значение).
   Если тип ≠ nil, то интерфейс ≠ nil, даже если значение = nil.

   Пример:
     var err error = nil
     var i interface{} = err
     fmt.Println(i == nil) // false
*/
func demonstrateNilTrap() {
	var err error = nil
	var i interface{} = err
	fmt.Println("i == nil:", i == nil) // false
}

// Q: Чем interface{} отличается от struct{}?
/*
   • interface{} — занимает 16 байт, может хранить любое значение.
   • struct{} — пустая структура, занимает 0 байт, используется как "заполнитель".
*/

// Q: Когда использовать generics, а когда interface{}?
/*
   • Generics — когда делаешь операции над значениями (Max, Filter, Map).
   • interface{} — когда просто хранишь/передаёшь без обработки (кэш, context.WithValue).
*/

// Q: Можно ли взять адрес элемента мапы? А поля интерфейса?
/*
   • &m["key"] — ошибка компиляции (элемент может переместиться при росте мапы).
   • &(v.Field) — нельзя, если v — interface{}, потому что интерфейс — это упакованное значение.
*/

// Q: Как проверить, реализует ли тип интерфейс?
/*
   Во время компиляции — присвоить переменной:
     var _ MyInterface = MyType{}
   Если компилируется — реализует.
*/

// Q: Что внутри интерфейса с методами?
/*
  Два указателя:
   • itab — таблица методов (для интерфейсов с методами)
   • data — указатель на данные
   → Всегда 16 байт на 64-битных системах.
*/
func demonstrateInterfaceSize() {
	var i interface{} = 42
	var s string = "hello"
	fmt.Printf("interface{} size: %d\n", unsafe.Sizeof(i)) // 16
	fmt.Printf("Stringer size: %d\n", unsafe.Sizeof(s))    // 16
}

// Q: Безопасны ли интерфейсы в горутинах?
/*
   Сам интерфейс — да (копируется по значению), но данные внутри — нет.
   Если несколько горутин изменяют объект, лежащий в интерфейсе — нужна синхронизация.
*/

func main() {
	demonstrateNilTrap()
	demonstrateInterfaceSize()
}
