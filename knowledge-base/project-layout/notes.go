package projectlayout

/*
NOTES (block 1):

1. Тонкий main: В main.go не должно быть бизнес-логики. Его задача — прочитать
   конфиг, проинициализировать зависимости (БД, логгер) и запустить сервис.

2. One Folder = One Package: В Go нельзя в одной папке иметь файлы с разными
   именами пакетов (исключение — пакет с постфиксом _test).

3. Имя папки == Имя пакета: Это стандарт. Если папка называется `auth`, то внутри
   файлы должны начинаться с `package auth`.

4. Файл go.mod: Создается командой `go mod init <name>`. Это сердце проекта,
   без него зависимости не подтянутся.
*/

/*
NOTES (block 2):

1. Semantic Import Versioning: В Go модулях версии v2+ должны отражаться в пути
   импорта (например, github.com/user/project/v2). Это боль, но это стандарт.

2. /pkg или не /pkg? На собесе скажи: "Я использую internal для всего, что
   не является публичным API, чтобы минимизировать поверхность атаки и
   связанность кода".

3. Минимальная версия: В go.mod всегда указана версия Go. Если твой код
   использует дженерики, там должно быть 1.18+. Если итераторы — 1.23+.

4. Git Tags: Версии в Go модулях привязаны к тегам в Git (v1.0.0).
   Без тега Go будет использовать псевдо-версию (хэш коммита).
*/

/*
NOTES (block 3):

1. Циклические зависимости: "Как решить проблему, если А нужен Б, а Б нужен А?"
   Ответ: Вынести общие интерфейсы в отдельный пакет (Domain) или использовать
   внедрение зависимостей через конструкторы.

2. DRY vs Decoupling: разработчик должен знать, что копирование кода (дублирование моделей
   для БД и для API) — это ХОРОШО, если это делает слои независимыми.
   Не пытайся использовать одну структуру и для JSON, и для таблицы в БД.

3. Инфраструктура как деталь: База данных, брокер очередей (Kafka) или
   HTTP-фреймворк (Gin/Echo) — это "детали реализации". Весь код должен
   быть написан так, чтобы их можно было заменить, поменяв только
   реализацию интерфейса в слое Repository или Transport.

4. Graceful Shutdown: На этом уровне важно показать, что проект умеет
   правильно закрываться. Логика закрытия БД и остановки серверов
   должна быть организована в main или через пакеты управления жизненным циклом.
*/

/*
NOTES (block 4):

1. Cognitive Load: "Хорошая структура проекта — та, в которой новый разработчик
   может найти нужный файл за 30 секунд без подсказок".

2. Monolith to Microservices: Структура должна позволять легко "отпочковать"
   часть internal пакета в отдельный микросервис, если он разросся.

3. CI/CD "Shift Left": Тесты должны быть встроены в структуру проекта так,
   чтобы их было легко запускать локально (через Makefile) точно так же,
   как они запускаются в облаке (Jenkins/GitLab CI).

4. Версионирование API: Если проект предоставляет API, структура должна
   поддерживать версии (например, /internal/transport/http/v1 и /v2).
*/
