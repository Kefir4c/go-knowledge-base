package sheduler

/*
NOTES (Block 1):

1. Автоматика: Тебе не нужно знать ID горутины или управлять жизненным циклом
   потоков ОС. Твоя задача — просто плодить g, а Go разберется.
2. Кооперативность vs Вытеснение: Планировщик сам решит, когда прервать
   горутину (например, если она работает слишком долго или делает сетевой запрос).
3. Динамика: Планировщик постоянно анализирует состояние системы. Если задач
   стало меньше, он может "припарковать" лишние потоки ОС, чтобы не тратить ресурсы.
4. Отсутствие приоритетов: В Go нельзя сказать "эта горутина важнее той".
   Все равны перед лицом планировщика. Это упрощает архитектуру и избегает
   ситуаций, когда "важные" задачи топят "второстепенные".
*/

/*
NOTES (Block 2):

1. LRQ vs GRQ: У каждого p есть локальная очередь (Local Run Queue) на 256 задач.
   Если в ней пусто, p лезет в Глобальную очередь (Global Run Queue) или
   ворует у соседей.
2. Сетевой Netpoller: Если горутина ждет данные из сети, она не занимает поток m.
   Она уходит в Netpoller (специальный поток), освобождая место для других.
   Когда данные пришли, планировщик возвращает g в очередь на исполнение.
3. Проблема 61-го шага: Планировщик проверяет глобальную очередь раз в 61 такт,
   чтобы задачи из неё не "голодали" (starvation).
4. Каналы vs Мьютексы:
   - Мьютексы эффективны, когда нужно просто защитить переменную.
   - Каналы идеальны для передачи управления и синхронизации логических этапов.
*/

/*
NOTES (Block 3):

1. Lock Contention (Борьба за замок): Это ситуация, когда горутины стоят в очереди
   к одному мьютексу. Чем меньше времени горутина проводит под замком, тем
   лучше работает планировщик.
2. Worker Pool vs Spawn: Не создавай горутину на каждый входящий HTTP-запрос,
   если их 100к в секунду. Используй пул или лимитеры.
3. sync.Map: Не используй её везде. Обычная мапа + RWMutex часто быстрее,
   если чтений и записей примерно поровну. sync.Map нужна только для
   специфических сценариев (read-heavy).
4. Прерывания: Помни, что планировщик может прервать твой код в любой момент.
   Никогда не полагайся на то, что одна горутина "успеет" быстрее другой без
   явной синхронизации.
*/

/*
NOTES (Block 4):

1. Spinning Threads: Если видишь в schedtrace много spinningthreads — это значит,
   что M ищут работу. Это нормально при пиковых нагрузках, но если это
   постоянно при пустой очереди — возможно, у тебя слишком много P.
2. Netpoller: Помни, что горутины, ждущие сеть, не отображаются в runqueue
   в schedtrace. Они "висят" в отдельном списке дескрипторов.
3. Throttling: В облаке (AWS/GCP) планировщик может "замирать", если ты превысил
   лимиты CPU. Всегда ставь GOMAXPROCS равным количеству CPU-лимитов.
4. GC Mark Assist: Если горутина слишком быстро выделяет память, планировщик
   может заставить её "помогать" мусорщику (Mark Assist). Твоя логика замрет.
   Вывод: меньше аллокаций = стабильнее планирование.
*/
