// 1. ПЛАНИРОВЩИК (SCHEDULER): АВТОМАТИЗАЦИЯ И УПРАВЛЕНИЕ
/*
ТЕОРЕТИЧЕСКАЯ СПРАВКА:

1. ЧТО ТАКОЕ ПЛАНИРОВЩИК:
   - Это часть рантайма Go, которая решает, какая горутина (g) будет
     выполняться на конкретном потоке (m) в данный момент времени.
   - В отличие от многих других языков, где ты сам управляешь пулами потоков,
     в Go планировщик работает "под капотом" полностью автоматически.

2. ПРИНЦИП "ЗАПУСТИЛ И ЗАБЫЛ":
   - Когда ты пишешь ключевое слово `go`, ты не просто запускаешь функцию,
     ты отдаешь её планировщику. Он сам выберет свободный процессор (p)
     и поставит задачу в очередь.

3. ОТСУТСТВИЕ РУЧНОГО УПРАВЛЕНИЯ:
   - У горутин нет ID, их нельзя "убить" снаружи, нельзя выставить им приоритет
     (priority). Это сделано специально, чтобы планировщик мог максимально
     эффективно балансировать нагрузку сам.
*/

// ПРИМЕР 1: Автоматическое распределение по всем ядрам (Parallelism)
/* Здесь мы видим, как планировщик автоматически задействует всё железо.
Нам не нужно знать, сколько ядер у процессора, Go сам "размажет" нагрузку.
*/
func exampleAutoScaling() {
	var wg sync.WaitGroup
	// Узнаем, сколько "рабочих мест" (P) планировщик создал автоматически
	numP := runtime.GOMAXPROCS(0)
	fmt.Printf("Планировщик автоматически настроен на %d потоков выполнения\n", numP)

	for i := 0; i < numP*2; i++ {
		wg.Add(1)
		go func(id int) {
			defer wg.Done()
			// Мы просто пишем код, а планировщик сам решает,
			// на каком физическом ядре запустить этот принт.
			fmt.Printf("Воркер %d работает на одном из %d процессоров\n", id, numP)
		}(i)
	}
	wg.Wait()
}

// ПРИМЕР 2: Автоматическое управление очередями (Queues)
/* Этот пример показывает, что планировщик сам жонглирует задачами.
Даже если мы запустим их по порядку, он сам определит, кто пойдет в локальную
очередь процессора, а кто чуть подождет.
*/
func exampleAutoQueue() {
	// Запускаем пачку горутин без пауз.
	// Планировщик сам распределит их по своим внутренним очередям (LRQ).
	fmt.Println("Рассылаем задачи планировщику...")
	for i := 1; i <= 10; i++ {
		go func(val int) {
			// Порядок вывода почти всегда будет "хаотичным", так как
			// планировщик оптимизирует выполнение под текущую нагрузку ядер.
			fmt.Printf("[%d] ", val)
		}(i)
	}

	// Даем планировщику закончить работу
	time.Sleep(50 * time.Millisecond)
	fmt.Println("\nВсе задачи распределены и выполнены автоматически.")
}

// ПРИМЕР 3: Автоматическое переключение при ожидании (Context Switching)
/* Самая крутая фишка автоматики: если горутина "тупит" (ждет таймер или сеть),
планировщик не ждет вместе с ней. Он мгновенно отдает ресурсы тем, кто готов работать.
*/
func exampleAutoSwitching() {
	var wg sync.WaitGroup
	wg.Add(2)

	// Горутина-лежебока
	go func() {
		defer wg.Done()
		fmt.Println("Горутина А: я заблокируюсь на 100мс...")
		// В этот момент планировщик автоматически снимет А с процессора
		time.Sleep(100 * time.Millisecond)
		fmt.Println("Горутина А: я снова в строю!")
	}()

	// Горутина-работяга
	go func() {
		defer wg.Done()
		// Пока А спит, планировщик отдаст все силы этой горутине
		fmt.Println("Горутина Б: пока А отдыхает, планировщик дал мне поработать!")
	}()

	wg.Wait()
}

// ПРИМЕР 4: Невидимость планировщика
/* Мы не можем "убить" или "приостановить" конкретную горутину.
Это доказывает, что планировщик полностью автономен. Единственное,
что мы можем — это попросить его уступить место другим.
*/
func exampleYield() {
	go func() {
		for i := 0; i < 3; i++ {
			fmt.Println("Горутина 1: работаю...")
			// Мы не управляем планировщиком, но можем вежливо "намекнуть",
			// что мы готовы уступить очередь (Gosched).
			runtime.Gosched()
		}
	}()

	go func() {
		for i := 0; i < 3; i++ {
			fmt.Println("Горутина 2: работаю...")
			runtime.Gosched()
		}
	}()

	time.Sleep(50 * time.Millisecond)
}

// 2. МЕХАНИКА РАСПРЕДЕЛЕНИЯ И СИНХРОНИЗАЦИЯ
/*
ТЕОРЕТИЧЕСКАЯ СПРАВКА:

1. WORK STEALING (Кража работы):
   Если один логический процессор (p) выполнил все свои задачи и его очередь
   пуста, он не идет спать. Он смотрит на рандмно работающую на очереди других p и "крадет" у
   них половину горутин. Это гарантирует, что все ядра CPU заняты делом.

2. СИНХРОНИЗАЦИЯ И ПЛАНИРОВЩИК:
   Когда горутина упирается в закрытый Mutex или пустой канал, она не делает
   "холостой" цикл. Планировщик переводит её в состояние ожидания (waiting),
   убирает из потока m и ставит на её место другую полезную задачу.

3. ПЕРЕМЕЩЕНИЕ МЕЖДУ P:
   Планировщик может остановить горутину на одном p и позже запустить её
   на совершенно другом p. Это нужно для балансировки нагрузки.
*/

// ПРИМЕР 1: Механизм Work Stealing (Визуализация идеи)
/* Напрямую "увидеть" кражу кода сложно, но мы можем создать ситуацию,
где задач очень много, и планировщик будет вынужден их перебрасывать.
*/

func exampleWorkStealing() {
	// Ограничимся 2 процессорами, чтобы проще было представить
	runtime.GOMAXPROCS(2)
	var wg sync.WaitGroup

	for i := 0; i < 100; i++ {
		wg.Add(1)
		go func(id int) {
			defer wg.Done()
			// Имитация нагрузки. Пока один P забит, второй P
			// будет "подворовывать" эти задачи себе.
			sum := 0
			for j := 0; j < 1000000; i++ {
				sum *= j
			}
		}(i)
	}
	wg.Wait()
	fmt.Println("Планировщик успешно распределил 100 задач между ядрами")
}

// ПРИМЕР 2: Синхронизация через Mutex (Влияние на планировщик)
/* Мьютекс — это не просто замок. Это сигнал планировщику:
"Я стою в очереди, отдай моё процессорное время кому-то другому".
*/
func exampleMutexScheduling() {
	var (
		count int
		mu    sync.Mutex
		wg    sync.WaitGroup
	)

	for i := 0; i < 10; i++ {
		wg.Add(1)
		go func(id int) {
			defer wg.Done()
			mu.Lock() // Если занято, планировщик "припаркует" горутину
			count++
			fmt.Printf("Горутина %d обновила счетчик\n", id)
			time.Sleep(10 * time.Millisecond) // Держим замок
			mu.Unlock()                       // Сигнал планировщику: "Следующий может просыпаться"
		}(i)
	}
	wg.Wait()
}

// ПРИМЕР 3: Каналы как инструмент управления очередностью
/* Каналы позволяют нам явно сказать планировщику, в какой последовательности
запускать части кода, не блокируя при этом системные потоки ОС.
*/
func exampleChannelCoordination() {
	step1 := make(chan struct{})
	step2 := make(chan struct{})

	go func() {
		fmt.Println("Этап 1: Подготовка данных...")
		time.Sleep(50 * time.Millisecond)
		close(step1) // Разблокирует следующую горутину
	}()

	go func() {
		<-step1 // Ждем, пока планировщик нас "разбудит" по сигналу из канала
		fmt.Println("Этап 2: Обработка данных...")
		close(step2)
	}()

	<-step2
	fmt.Println("Все этапы завершены автоматически")
}

// ПРИМЕР 4: Перемещение горутины между P (Locality)
/* Планировщик старается сохранять "сродство" (Affinity), но если нужно,
он легко перебросит g на другое ядро. Мы можем это увидеть через GOMAXPROCS.
*/
func exampleRelocation() {
	// По умолчанию горутина может проснуться на любом ядре после сна
	for i := 0; i < 3; i++ {
		go func(id int) {
			fmt.Printf("G%d начала работу\n", id)
			time.Sleep(100 * time.Millisecond)
			// После Sleep планировщик заново ищет свободный P для этой горутины
			fmt.Printf("G%d закончила работу (возможно, уже на другом ядре)\n", id)
		}(i)
	}
	time.Sleep(200 * time.Millisecond)
}

// 3. ОПТИМИЗАЦИЯ ПЛАНИРОВЩИКА И КОНКУРЕНТНЫЕ СТРУКТУРЫ
/*
ТЕОРЕТИЧЕСКАЯ СПРАВКА:

1. БЛОКИРУЮЩИЕ ОПЕРАЦИИ:
   - Бывают двух видов: User-level (каналы, мьютексы) и System-level (файлы, сеть, системные вызовы).
   - Системные блокировки самые опасные: они заставляют планировщик плодить
     новые потоки m, что ест память и время на переключение контекста ОС.

2. УПРАВЛЕНИЕ КОЛИЧЕСТВОМ ГОРУТИН:
   - "Бесконечные" горутины — это миф. Каждая g занимает минимум 2 КБ.
     Если их 1 000 000, то это 2 ГБ только на стеки.
     Оптимизация заключается в использовании Worker Pool, чтобы не перегружать планировщик.

3. КОНКУРЕНТНЫЕ СТРУКТУРЫ:
   - Стандартные мапы в Go не потокобезопасны. Для высокой нагрузки
     используются sync.Map или шардирование (разделение мапы на части).
*/

// ПРИМЕР 1: Оптимизация через Worker Pool
/* Зачем: Если мы на каждый чих будем создавать горутину, планировщик
устанет их переключать. Worker Pool ограничивает количество "работяг",
делая нагрузку предсказуемой.
*/
func exampleWorkerPool() {
	const (
		numJobs    = 15
		numWorkers = 3 // Ограничиваем параллельность
	)
	var wg sync.WaitGroup

	jobs := make(chan int, numJobs)
	results := make(chan int, numJobs)

	for w := 1; w <= numWorkers; w++ {
		wg.Add(1)
		go func(workerID int) {
			defer wg.Done()
			for j := range jobs {
				// Воркер берет задачу, планировщик спокоен
				fmt.Printf("Воркер %d обрабатывает задачу %d\n", workerID, j)
				time.Sleep(time.Millisecond * 10)
				results <- j * 2
			}
		}(w)
	}

	for j := 1; j <= numJobs; j++ {
		results <- j
	}
	close(jobs)
	wg.Wait()
	fmt.Println("Все задачи обработаны ограниченным пулом воркеров")
}

// ПРИМЕР 2: Устранение системных блокировок и управление ожиданиями
/* Проблема: Блокирующие вызовы (System Calls) "крадут" потоки ОС у планировщика.
Решение: Использовать неблокирующий ввод-вывод (через сетевой Netpoller) или
жестко ограничивать время ожидания через Context, чтобы горутина не висела вечно.
*/
func exampleAvoidBlocking() {
	// Создаем контекст с таймаутом. Это лучший способ не дать
	// блокирующей операции "подвесить" горутину навсегда.
	ctx, cancel := context.WithTimeout(context.Background(), 50*time.Millisecond)
	defer cancel()

	var wg sync.WaitGroup
	wg.Add(1)

	go func(ctx context.Context) {
		defer wg.Done()

		// Канал для имитации получения данных из блокирующего источника (БД/Файл)
		resCh := make(chan string, 1)

		go func() {
			// Имитируем тяжелый системный вызов или долгий запрос
			time.Sleep(100 * time.Millisecond)
			resCh <- "Данные из БД"
		}()

		// ПРАВИЛЬНЫЙ ПОДХОД: Ждем либо данные, либо отмену по таймауту
		select {
		case res := <-resCh:
			fmt.Println("Успех:", res)
		case <-ctx.Done():
			// Планировщик освободит ресурсы этой горутины, так как мы выходим
			fmt.Println("Ошибка: блокировка длилась слишком долго, выходим по таймауту")
		}
	}(ctx)

	wg.Wait()
}

// ДОПОЛНИТЕЛЬНО: ПРИМЕР 2.1: Использование буферизированных каналов для разблокировки
/* Если канал без буфера, горутина-отправитель будет стоять и ждать "за руку"
горутину-получателя. Это скрытая блокировка. Буфер позволяет планировщику
двигаться дальше.
*/
func exampleBufferedUnlock() {
	// Канал с буфером на 10 элементов
	// Отправитель не заблокируется, пока не заполнит все 10 слотов
	ch := make(chan int, 10)

	go func() {
		for i := 0; i < 10; i++ {
			ch <- i // Работает мгновенно, поток M не простаивает
		}
		close(ch)
	}()

	for v := range ch {
		fmt.Print(v, " ")
	}
	fmt.Println("\nБуферизация помогла избежать лишних переключений контекста")
}

// ПРИМЕР 3: Безопасный доступ через sync.Map
/* Зачем: sync.Map оптимизирована для случаев, когда ключи один раз пишутся,
а потом только читаются, или когда горутины работают с разными ключами.
Она минимизирует блокировки планировщика (lock contention).
*/
func exampleSyncMap() {
	var (
		sm sync.Map
		wg sync.WaitGroup
	)

	for i := 0; i < 5; i++ {
		wg.Add(1)
		go func(n int) {
			defer wg.Done()
			sm.Store(n, n*n)
		}(i)
	}
	wg.Wait()
	sm.Range(func(key, value any) bool {
		fmt.Printf("Ключ: %v, Значение: %v\n", key, value)
		return true
	})
}

// ПРИМЕР 4: Шардирование мапы (Advanced Optimization)
/* Зачем: Даже sync.Map может тормозить под жуткой нагрузкой.
Экспертный подход — создать слайс из обычных мап, каждая со своим мьютексом.
Это в разы снижает вероятность того, что две горутины "столкнутся" на одном замке.
*/
func exampleMapSharding() {
	const shardsCount = 8
	type shard struct {
		mu sync.Mutex
		m  map[int]string
	}

	// Создаем 8 независимых корзин
	shards := make([]*shard, shardsCount)
	for i := 0; i < shardsCount; i++ {
		shards[i] = &shard{m: make(map[int]string)}
	}

	set := func(key int, val string) {
		// Выбираем корзину на основе ключа
		s := shards[key%shardsCount]
		s.mu.Lock()
		s.m[key] = val
		s.mu.Unlock()
	}

	set(10, "Go")
	set(21, "Scheduler")
	fmt.Println("Данные распределены по шардам для уменьшения блокировок")
}

// 4. ЭКСПЕРТНОЕ УПРАВЛЕНИЕ И ТЮНИНГ ПЛАНИРОВЩИКА
/*
ТЕОРЕТИЧЕСКАЯ СПРАВКА:

1. GODEBUG (schedtrace):
   Это «рентген» для планировщика. Установив переменную окружения GODEBUG="schedtrace=1000",
   ты заставляешь Go каждую секунду выводить в лог состояние всех P, M и G.
   Это единственный способ увидеть Global Run Queue (GRQ) и кражу задач в реальном времени.

2. ДИНАМИКА GOMAXPROCS:
   Это не просто «количество ядер». Это количество логических процессоров (P),
   которые могут одновременно выполнять код. Если P слишком много — растет overhead на переключение.
   Если слишком мало — не используем железо.

3. ПАТТЕРНЫ НАГРУЗКИ:
   - CPU-bound: Задачи, которые грузят процессор. Здесь важно не плодить лишних горутин.
   - IO-bound: Задачи, которые ждут (сеть, диск). Здесь горутин может быть в разы больше, чем ядер.
*/

// ПРИМЕР 1: Практический разбор GODEBUG=schedtrace (Диагностика планировщика)
/* Что это дает: Ты видишь, не "голодают" ли горутины и насколько эффективно
работает Work Stealing.
Команда запуска: GODEBUG=schedtrace=1000 ./my_app
*/
func exampleSchedtraceTheory() {
	// Представь, что мы видим в консоли вот такую строку раз в секунду:
	// SCHED 1000ms: gomaxprocs=4 idleprocs=0 threads=6 spinningthreads=1 idlethreads=2 runqueue=120 [30 20 40 30]

	/* ЭКСПЕРТНЫЙ РАЗБОР ЛОГА:
	1. gomaxprocs=4: У нас 4 логических процессора (P).
	2. runqueue=120: Это Глобальная очередь (GRQ). В ней 120 горутин ждут своего часа.
	   Это "тревожный звоночек" — задачи не успевают распределяться по локальным очередям.
	3. [30 20 40 30]: Это Локальные очереди (LRQ) для каждого P.
	   Суммарно 120 в локальных + 120 в глобальной = 240 горутин на выполнении.
	4. spinningthreads=1: Один поток M активно ищет работу (вор). Это хорошо, значит
	   система готова мгновенно подхватить новую задачу.

	ЧТО ДЕЛАТЬ:
	- Если runqueue постоянно растет, а idleprocs всегда 0 -> приложению не хватает CPU.
	- Если очереди пустые, но threads растет -> горутины блокируются в системных вызовах (CGO, файлы).
	*/
	fmt.Println("Инструмент GODEBUG позволяет увидеть перекос нагрузки между ядрами CPU")
}

// ПРИМЕР 2: Тонкая настройка GOMAXPROCS и борьба с Throttling в K8s
/* Проблема: В Kubernetes мы задаем лимиты, например, "cpu: 2". Но физический сервер
имеет 64 ядра. Go по умолчанию увидит 64 ядра и создаст 64 потока (P).
Результат: CFS Throttling. ОС будет "штрафовать" приложение за то, что оно
пытается использовать 64 потока там, где разрешено время только для двух.
*/
func exampleMaxProcsTuning() {
	// 1. Узнаем, сколько ядер видит рантайм изначально
	initialP := runtime.GOMAXPROCS(0)
	fmt.Printf("Рантайм видит %d ядер физического узла\n", initialP)

	// 2. Реальный кейс: ручная установка под лимиты контейнера.
	// В проде лучше использовать библиотеку "uber-go/automaxprocs",
	// которая делает это автоматически, читая cgroups.

	// Допустим, мы выделили контейнеру 4 ядра.
	renderLimit := 4
	runtime.GOMAXPROCS(renderLimit)

	// 3. Почему это важно:
	// Когда GOMAXPROCS == CPU Limit, планировщик Go не плодит лишние очереди.
	// Это уменьшает количество переключений контекста и "укладывает" работу
	// приложения в выделенные ОС временные кванты.

	fmt.Printf("Настройка изменена на %d P. Теперь планировщик не конфликтует с лимитами K8s\n", runtime.GOMAXPROCS(0))
}

// ПРИМЕР 3: Распределение нагрузки (Load Shedding)
/* Экспертный подход: если горутин в очереди слишком много, мы начинаем
отбрасывать новые задачи, чтобы не уронить весь планировщик.
*/
func exampleLoadShedding() {
	const maxQueueSize = 100
	queue := make(chan int, maxQueueSize)

	addTask := func(id int) bool {
		select {
		case queue <- id:
			return true // Задача принята
		default:
			// Очередь полна. Вместо того чтобы плодить горутины и
			// забивать планировщик, мы сразу отвечаем "Busy".
			return false
		}
	}

	for i := 0; i < 110; i++ {
		if !addTask(i) {
			// На 101-й задаче мы увидим это сообщение
			fmt.Printf("Задача %d отброшена: планировщик перегружен!\n", i)
		}
	}
}

// ПРИМЕР 4: Управление Garbage Collector через планировщик
/* GC работает в своих горутинах и "крадет" время у твоих.
Мы можем регулировать, насколько агрессивно он это делает.
*/
func exampleGCTuning() {
	// GOGC определяет процент роста кучи перед следующим запуском GC.
	// По умолчанию 100. Если поставить 50 — GC будет чаще, но куча меньше.
	debug.SetGCPercent(200) // Реже запускаем GC, даем планировщику больше времени на логику

	fmt.Println("GC настроен на более редкую очистку для повышения CPU throughput")
}

// ПРИМЕР 5: Проектирование под CPU Cache (Affinity)
/* Чтобы планировщик не гонял g между ядрами (теряя L1/L2 кэш),
высоконагруженные воркеры должны работать долго и не блокироваться по пустякам.
*/
func exampleWorkerAffinity() {
	var wg sync.WaitGroup
	pCount := runtime.GOMAXPROCS(0)

	for i := 0; i < pCount; i++ {
		wg.Add(1)
		go func(id int) {
			defer wg.Done()
			// Воркер работает долго, обрабатывая пачки данных.
			// Планировщик видит, что P занят полезной работой и не перебрасывает G.
			for j := 0; j < 100; j++ {
				// Обработка данных без лишних Sleep и Lock
				_ = id * j
			}
		}(i)
	}
	wg.Wait()
}

// ПРИМЕР 6: Управление распределением (Work Stealing vs Global Queue)
/* Как эксперт, ты должен понимать разницу. Горутины в глобальной очереди
проверяются редко (раз в 61 тик). Если ты "завалишь" GRQ, задержки (latency) вырастут.
*/
func exampleLoadBalancingExpert() {
	// Чтобы горутины попадали в локальные очереди (LRQ) и работали быстро:
	// Нужно запускать их из уже работающих горутин, а не из одной главной.

	var wg sync.WaitGroup
	for i := 0; i < 10; i++ {
		wg.Add(1)
		go func(parentID int) { // Эта G попадет в GRQ или LRQ первого свободного P
			defer wg.Done()

			// Порождаем дочерние задачи
			for j := 0; j < 5; j++ {
				go func(childID int) {
					// Эти G с большой вероятностью попадут в ЛОКАЛЬНУЮ очередь текущего P.
					// Это быстрее, так как не требует глобальных блокировок.
					_ = childID
				}(j)
			}
		}(i)
	}
	wg.Wait()
}
