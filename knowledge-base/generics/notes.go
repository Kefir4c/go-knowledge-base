package generics

//Часть теории:
// Junior :
/*
- Дженерики работают на этапе КОМПИЛЯЦИИ (в отличие от интерфейсов).
- Type Inference: В большинстве случаев [T] писать при вызове не нужно, Go поймет сам.
- Zero Value: Нельзя просто вернуть nil, если T — это int. Используй 'var zero T'.
- Методы: Нельзя объявлять новые параметры типа в методах структуры (только те, что у самой структуры).
*/

// Junior+ Level
/*
1. Почему sort.Slice — это "старый стиль":
   Он принимает interface{}, что заставляет Go использовать рефлексию.
   slices.Sort напрямую работает с типами, что в разы эффективнее.

2. Когда использовать дженерик-методы:
   Помни, что методы не могут вводить НОВЫЕ типы.
   func (s Stack[T]) Push[V any](v V) — ОШИБКА.
   Метод может использовать только те типы, которые определены в самой структуре.

3. Пакет 'cmp':
   Это лучший друг дженериков. Ограничение cmp.Ordered позволяет
   сразу использовать операторы сравнения (<, >, ==).

4. Почему [T comparable] нельзя заменить на [T any] в мапах?
   - Потому что ключи мапы должны поддерживать операцию сравнения (==),
     чтобы Go мог вычислить хэш и найти бакет. any включает слайсы и мапы,
     которые нельзя сравнивать, поэтому они не могут быть ключами.

5. Пакет 'slices' — это мастхэв:
   - slices.Delete, slices.Insert, slices.Replace — забудь про страшные конструкции
     с append(a[:i], a[j:]...). Теперь всё это делается одной типизированной функцией.
*/

// Middle level
/*
1. ~Тильда: Обязательна, если хочешь, чтобы твоя библиотека поддерживала
   user-defined типы (type MyString string).
2. comparable: Это не просто интерфейс, это магическое слово для компилятора,
   разрешающее использовать == и !=.
3. GC Pressure: Дженерики помогают уменьшить аллокации, так как
   избегают "boxing-а" (упаковки в интерфейс interface{}).
4. Ограничение методов: В Go всё еще нельзя объявить новый параметр типа
   в методе структуры. Только на уровне самой структуры или функции.
*/

// Senior Level
/*
1. GCShape (Pointer Erasure):
   Go оптимизирует код: `func F[*int]` и `func F[*string]` будут использовать
   одну и ту же скомпилированную функцию, так как для GC это просто "указатель".
   Это предотвращает раздувание (binary bloating).

2. Inlining:
   Короткие дженерик-функции отлично инлайнятся компилятором, что делает их
   такими же быстрыми, как если бы вы написали их вручную для каждого типа.

3. Библиотечный дизайн:
   При создании библиотек (как `lo` или `samber/do`) важно экспортировать не только
   функции, но и сами Constraints (интерфейсы-ограничения), чтобы пользователи
   могли расширять вашу логику.

4. Динамический выбор:
   Senior знает: если количество типов ограничено и известно заранее (например,
   только 3 вида DTO), иногда проще и понятнее использовать `switch v := any(x).(type)`.
*/
