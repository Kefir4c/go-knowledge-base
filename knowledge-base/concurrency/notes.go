package concurrency

/*
NOTES (Block 1):

1. Главная горутина: Если main() завершается, рантайм Go НЕ ждет
   остальные горутины. Программа просто схлопывается.

2. Panic в горутине: Если одна горутина паникует и не восстанавливается
   через recover(), "падает" все приложение целиком.

3. Небуферизированный канал: Это "рандеву". Отправитель и получатель
   должны встретиться одновременно. Если никто не читает, отправитель
   стоит и ждет вечно (это называется Goroutine Leak).

4. Zero value каналов:
   - Чтение из nil-канала -> вечная блокировка.
   - Запись в nil-канал -> вечная блокировка.
   - Закрытие nil-канала -> ПАНИКА.
   - Запись в закрытый канал -> ПАНИКА.
   - Чтение из закрытого канала -> вернет zero value типа и ok=false.
*/

/*
NOTES (Block 2):

1. Mutex Copying: НИКОГДА не копируй структуру, содержащую мьютекс.
   Это приведет к копированию состояния "замка". Передавай такие
   объекты только по указателю.

2. Deadlock: Если горутина 1 ждет горутину 2, а горутина 2 ждет 1 —
   программа зависнет. Go Runtime умеет определять простые дедлоки
   и "ронять" приложение с ошибкой fatal error: all goroutines are asleep - deadlock!

3. Work Stealing (Планировщик): Если у одного процессора (P) закончились горутины,
   он "крадет" половину очереди у другого процессора. Это база эффективности Go.

4. Преemptive Scheduling: С Go 1.14 планировщик стал вытесняющим.
   Горутина больше не может "завесить" поток бесконечным циклом (например, for{}),
   рантайм принудительно её прервет, чтобы дать поработать другим.
*/

/*
NOTES (Block 3):

1. Backpressure: Если входных задач больше, чем воркеры могут обработать,
   нужно либо увеличивать пул, либо возвращать ошибку клиенту (429 Too Many Requests),
   иначе память переполнится.

2. Graceful Shutdown: Как остановить воркеры?
   Закрыть канал jobs -> воркеры доделают текущие задачи и выйдут из цикла range.

3. Накладные расходы: Не делайте Worker Pool для слишком простых задач
   (например, сложение двух чисел). Время на пересылку данных через каналы
   будет больше, чем само вычисление.

4. pprof и Graphviz: Команда `web` в pprof визуализирует граф вызовов.
   Это лучший способ найти "горячие" места, где программа тормозит.
*/

/*
NOTES (Block 4):

1. Work Stealing & Handoff: Если горутина блокируется на I/O, P (процессор)
   отдает свой поток M в системный вызов и берет новый M из кэша (или создает),
   чтобы продолжать крутить другие G.

2. Context Values: Не используй ctx.WithValue для передачи параметров функции.
   Это только для сквозных данных: TraceID, UserID из JWT, Logger.

3. Lock-free алгоритмы: На атомиках можно строить очереди и деревья без
   мьютексов. Это сложно в отладке, но дает колоссальный прирост на
   высоконагруженных участках (см. реализацию каналов в Go).

4. GC & Stack: Помни, что при копировании стека все указатели на данные в стеке
   должны быть обновлены. Go делает это магически, но это причина, почему
   нельзя передавать указатели из Go в C-код без предосторожностей.
*/
