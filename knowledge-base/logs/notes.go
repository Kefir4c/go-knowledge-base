package logs

/*
NOTES ПО БЛОКУ 1:
- Потокобезопасность: Стандартный логгер использует sync.Mutex. Это значит,
  что если 100 горутин начнут писать в один логгер, сообщения не перемешаются
  в кашу, а выстроятся в очередь.
- Форматирование: log.Printf позволяет использовать глаголы форматирования (%s, %v, %+v),
  что критично при отладке структур и интерфейсов.
- os.Stderr: По умолчанию стандартный логгер пишет в поток ошибок (stderr),
  а не в обычный вывод (stdout). Это важно для разделения потоков в Linux.
*/

/*
NOTES (Самое важное по Блоку 2):
1. io.MultiWriter — мастхэв для локальной разработки (видишь логи в терминале и хранишь в файле).
2. Ротация — стандартный пакет log её НЕ делает. На собесе обязательно скажи про lumberjack.
3. ID горутины — не пытайся его получить через runtime на продакшене. Это медленно и ломает
   абстракцию. Используй context и TraceID.
4. Ошибка новичка: Открывать файл на каждую запись лога. Правильно: открыть один раз при старте
   и передать дескриптор логгеру.
5. Философия Go: Создатели языка (Rob Pike) намеренно не дали доступ к GID,
  чтобы программисты не использовали Thread Local Storage (TLS). Это поощряет
  явную передачу зависимостей через параметры и контекст.
6. Производительность: runtime.Stack — дорогая операция. Если вызывать её в
  каждом логе, приложение ляжет под нагрузкой.
7. Middleware: В реальных HTTP-серверах TraceID генерируется в самом начале
  запроса (в middleware) и сохраняется в контексте.
*/

/*
NOTES (Самое важное по Блоку 3):
1. Zap Sugar vs Logger:
   - Logger (как в примере) — типизированный, максимально быстрый (zap.Int, zap.String).
   - SugaredLogger — позволяет писать удобно (как Printf), но чуть медленнее.
   На собесе говори: "Использую Logger для критичных путей и Sugar для конфигов/стартов".

2. Sampling (Сэмплирование): Zap умеет выкидывать дублирующиеся логи (например,
   если ошибка в цикле сыпется 1000 раз в секунду). Это спасает диск.

3. Централизация:
   - [App (JSON)] -> [Stdout] -> [Vector/Fluentd] -> [Loki/Elastic]
   Никогда не пиши логи в файлы внутри контейнера Docker — это антипаттерн.

4. Как гуглить ошибку в Kibana: Просто вбиваешь `trace_id: "gen-123"` и видишь
   ВСЮ цепочку от прихода HTTP-запроса до запроса в базу.
================================================================
*/

/*
================================================================
NOTES (Самое важное по Блоку 4):
1. Zero-Allocation: На сеньор-позициях могут спросить, почему `zap.String` лучше,
   чем `zap.Any`. Ответ: `zap.Any` использует рефлексию и аллоцирует память в куче,
   а типизированные поля пишут напрямую в буфер энкодера.

2. Sidecar vs In-app forwarding: Обсуди на собесе, что лучше слать логи в Stdout
   (чтобы их забирал Fluent-bit/Logstash), чем слать их из приложения напрямую
   в Elasticsearch по HTTP (это создаст лишнюю нагрузку на сетевой стек приложения).

3. Log Triage: Уровни логов должны быть согласованы во всей компании.
   - WARN: Требует внимания, но сервис работает.
   - ERROR: Требует немедленного алерта в Slack/PagerDuty.

4. Correlation: Логи без TraceID в распределенной системе — это мусор.
   Каждый входящий запрос обязан порождать TraceID, который пробрасывается
   во все внутренние вызовы и БД.
================================================================
*/
