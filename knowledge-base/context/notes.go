package context

import (
	"context"
	"fmt"
	"time"
)

/*
1. ФУНДАМЕНТ
----------------------------------------------------------------
- СТРУКТУРА: Дерево. Родитель (Background) -> Дети. Отмена родителя каскадно отменяет всех детей.
- IMMUTABILITY: Контекст неизменяем. Функции With... возвращают копию.
- DONE(): Канал `<-chan struct{}`. Закрывается при отмене. Основной сигнал для выхода.
- ПРАВИЛО: Контекст всегда первый аргумент: func Do(ctx context.Context, ...).
- BACKGROUND vs TODO: Технически идентичны. TODO — это маркер "заглушка".
*/

// ПРИМЕР JUNIOR: Базовая проверка отмены
func juniorCheck(ctx context.Context) {
	select {
	case <-ctx.Done():
		// Контекст закрыт -> выходим, чтобы не плодить утечки
		return
	default:
		// Работаем дальше
	}
}

/*
2. УПРАВЛЕНИЕ ЖИЗНЕННЫМ ЦИКЛОМ
----------------------------------------------------------------
- DEFER CANCEL(): Обязателен! Освобождает ресурсы таймера. Без него — Context Leak.
- VALUE: Только для сквозных ID (TraceID, RequestID). Не для параметров функций!
- ЛИНЕЙНЫЙ ПОИСК: Поиск Value идет вверх по дереву O(N). Не делать дерево слишком глубоким.
- ПРИВАТНЫЕ КЛЮЧИ: Всегда создавай свой тип для ключей, чтобы избежать коллизий.
*/

// ПРИМЕР MIDDLE: Правильные ключи и WithoutCancel
type contextKey int

const requestIDKey contextKey = 1

func middleBestPractice(ctx context.Context) {
	// 1. Извлечение с проверкой типа (безопасно)
	reqID, ok := ctx.Value(requestIDKey).(string)
	if !ok {
		reqID = "unknown"
	}

	// 2. Фоновая задача (Go 1.21+): не умирает вместе с основным запросом
	// Но сохраняет RequestID для логов
	detachedCtx := context.WithoutCancel(ctx)
	go func(c context.Context) {
		fmt.Printf("Logging for ID: %s in background\n", reqID)
	}(detachedCtx)
}

/*
3. ЭКСПЕРТИЗА И ВЫСОКИЕ НАГРУЗКИ
----------------------------------------------------------------
- PROPAGATION: Передача через HTTP/gRPC заголовки (Metadata).
- DOUBLE CHECK SELECT: Защита от рандома в select при одновременной отмене и данных.
- WITHCANCELCAUSE (1.20+): Передача конкретной ошибки в cancel (почему отменили?).
- CONTEXT В СТРУКТУРАХ: Табу (кроме http.Request). Ломает логику жизненного цикла.
- GC PRESSURE: Миллионы контекстов в сек = нагрузка на Garbage Collector.
*/

// ПРИМЕР SENIOR: Double Check Select (Паттерн для Highload)
func seniorSafety(ctx context.Context, dataCh <-chan int) {
	for {
		select {
		case <-ctx.Done():
			return
		case val := <-dataCh:
			// ВАЖНО: Если данные пришли в ту же наносекунду, что и отмена,
			// select может выбрать кейс с данными. Делаем вторую проверку.
			select {
			case <-ctx.Done():
				return
			default:
			}
			fmt.Println("Processing safely:", val)
		}
	}
}

/*
          КОГДА И КАКОЙ МЕТОД ВЫБИРАТЬ (Cheat Sheet)

1. context.WithCancel(parent)
----------------------------------------------------------------
КОГДА: Когда ты сам контролируешь завершение процесса.
ПРИМЕРЫ:
 - Закрытие воркеров при остановке приложения (Graceful Shutdown).
 - Пользователь нажал кнопку "Отмена" на фронтенде.
 - Ты запустил 5 горутин искать файл, первая нашла — остальные отменяешь вручную.

2. context.WithTimeout(parent, duration)
----------------------------------------------------------------
КОГДА: Когда у тебя есть жесткий лимит на время выполнения (SLA).
ПРИМЕРЫ:
 - Внешний запрос к API (ждем не больше 2 секунд).
 - Сложный расчет, который не имеет смысла, если длится дольше 500мс.
 - "Мягкое" ограничение времени жизни запроса в микросервисе.

3. context.WithDeadline(parent, time.Time)
----------------------------------------------------------------
КОГДА: Когда работа должна быть завершена строго к определенному моменту.
ПРИМЕРЫ:
 - Бронирование билетов: "успеть до 15:00", иначе бронь слетит.
 - Работа по расписанию: "выполняй задачу, пока не наступит конец рабочего дня".
 - Технически WithTimeout — это обертка над WithDeadline (Timeout просто прибавляет
   длительность к текущему времени).

4. context.WithValue(parent, key, val)
----------------------------------------------------------------
КОГДА: Только для передачи неявных, "сквозных" данных.
ПРИМЕРЫ:
 - RequestID / TraceID (для логирования).
 - Данные авторизации (текущий пользователь, если это Middleware).
 - Информация о локали (язык пользователя для перевода ошибок).

5. context.WithoutCancel(parent) (Go 1.21+)
----------------------------------------------------------------
КОГДА: Когда нужно сделать что-то важное в фоне, но "прикрываясь" данными родителя.
ПРИМЕРЫ:
 - Основной HTTP-запрос завершен (или отменен клиентом), но нам НУЖНО
   дописать критичный лог или отправить метрику в Prometheus, используя TraceID
   из исходного контекста.
*/

// ПРИМЕР: Комбинирование (Timeout + Value)
func exampleChoosing(parent context.Context) {
	// 1. Сначала добавляем метаданные (RequestId)
	ctxWithValue := context.WithValue(parent, requestIDKey, "abc-123")

	// 2. Сверху накладываем ограничение по времени
	// Теперь ctx имеет и ID, и умрет через 2 секунды
	ctx, cancel := context.WithTimeout(ctxWithValue, 2*time.Second)
	defer cancel()

	_ = ctx
}

/*
================================================================
🎓 ВОПРОСЫ, НА КОТОРЫХ ВАЛЯТ (Чек-лист):
================================================================
1. Можно ли оживить отмененный контекст?
   - Нет. Только создать новый от Background.

2. Что будет, если вызвать cancel() дважды?
   - Ничего. Второй вызов игнорируется.

3. Безопасно ли использовать один ctx в 100 горутинах?
   - Да. Контекст потокобезопасен (Thread-safe).

4. В чем разница между Deadline и Timeout?
   - Timeout — через сколько времени (3с).
   - Deadline — в какое конкретное время (15:00:05).
================================================================
*/
