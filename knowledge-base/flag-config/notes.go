package flagconfig

/*
NOTES (Block 1):
1. Валидация на лету: В методе Set() кастомного флага можно прописать любую логику.
   Если Set вернет ошибку, flag.Parse() выведет её и остановит программу.
2. Флаг-детектор: Как понять, был ли флаг реально передан или мы видим дефолтное значение?
   Используй flag.Visit(func(f *flag.Flag) { ... }), он проходит только по установленным флагам.
3. Разница -flag и --flag: В Go оба варианта валидны. Также работает -flag=value и -flag value
   (кроме булевых флагов, там только через "=").
4. Терминатор аргументов: Если запустить `./app -port=80 -- extra_arg`, то `--`
   говорит парсеру: "всё, что дальше — не флаги, а чистые аргументы (Args)".
*/

/*
NOTES (Block 2):
1. 12-Factor App: Твердо знай правило — конфигурация хранится в среде (Environment).
   Никаких паролей в config.yaml, только через ENV!
2. Viper Live Reload: viper.WatchConfig() позволяет приложению узнавать об изменениях
   в YAML файле без перезагрузки. Это киллер-фича для тяжелых сервисов.
3. Разные форматы:
   - JSON: Быстрый, строгий, но нельзя писать комментарии.
   - YAML: Красивый, иерархичный, поддерживает комментарии (лучший выбор для людей).
   - TOML: Часто используется в инструментах на Go (например, в самом Go модуле).
*/

/*
NOTES (Block 3):
1. Fail-Fast vs Defaults:  мы предпочитаем Fail-Fast. Если
критический параметр (например, DB_URL) не задан, приложение должно
упасть с четкой ошибкой при старте, а не пытаться работать на дефолтах.

2. Secret Masking: При логировании конфига на старте (для отладки)
обязательно делай маскировку.Никогда не пиши Password или Token
в лог в открытом виде.

3. Concurrency: Если ты используешь WatchConfig, помни, что чтение
конфига может произойти одновременно с его записью из горутины
-наблюдателя. Используй atomic.Value или sync.RWMutex для хранения
объекта конфигурации.

4. K8s ConfigMaps: Упомяни, что в Kubernetes WatchConfig работает с
ConfigMap. Когда ты обновляешь ConfigMap, файл в поде обновляется
через некоторое время (симлинк), и Viper это подхватывает.
*/

/*
NOTES (Block 4):

1. External Secret Operator (ESO): В Kubernetes модно использовать ESO.
   Он берет секрет из Vault и превращает его в обычный K8s Secret.
   Твое приложение даже не знает про Vault, оно просто читает ENV.

2. Feature Toggles: Настройки можно использовать как флаги фич.
   Через Consul можно включить новую функциональность на 5% пользователей
   без деплоя, просто поменяв `false` на `true` в ключе.

3. Теневое перекрытие (Shadowing): Будь осторожен с `AutomaticEnv()`.
   Если у тебя в YAML поле `database.url`, а в ENV есть `DATABASE_URL`,
   Viper должен знать, как их связать (Replacer).

4. Грейсфул-деградация: Что если Consul упал?
   Экспертный подход: Приложение должно иметь локальный "кэш" конфига
   (последний удачный запуск) и запускаться на нем, если удаленный сервер недоступен.
*/
