// 1. ПАМЯТЬ, УКАЗАТЕЛИ И РОЛЬ GC
/*
ТЕОРЕТИЧЕСКАЯ СПРАВКА:

1. ЗАЧЕМ НУЖНО УПРАВЛЕНИЕ ПАМЯТЬЮ?
   Программа постоянно запрашивает место у ОС для хранения данных. Если память
   не освобождать, приложение съест всю RAM и упадет (OOM).
   В Go за это отвечает Garbage Collector (GC).

2. РОЛЬ GC В GO:
   - Автоматизация: Тебе не нужно писать free() или delete.
   - Безопасность: Предотвращает ошибки "висячих указателей" (когда память удалена, а указатель остался).
   - Фоновая работа: GC работает параллельно с твоим кодом, стараясь не мешать выполнению.

3. СТЕК И КУЧА (Коротко):
   - Стек (Stack): Быстрая память для локальных переменных. Очищается сама.
   - Куча (Heap): Глобальная память для объектов, которые должны жить долго.
     Именно здесь работает GC.
*/

// ПРИМЕР 1: Работа с указателями (Основы аллокации)
/* Указатель — это адрес в памяти. В Go мы можем явно создавать объекты
в куче через new или через взятие адреса &.
*/
func examplePointers() {
	// 1. Создание через new (выделяет память и возвращает указатель)
	p := new(int) // Выделено 8 байт (на 64-бит системах)
	*p = 42       // Разыменовываем: записываем значение по адресу

	// 2. Взятие адреса существующей переменной
	val := 100
	ptr := &val // ptr теперь хранит адрес переменной val

	fmt.Printf("Значение p: %v, Значение ptr: %v\n", *p, *ptr)

	// После завершения функции, если на эти данные больше никто не ссылается,
	// GC со временем их "уберет".
}

// ПРИМЕР 2: Передача по указателю vs По значению
/* Это критично для GC. Передавая указатель, ты не копируешь объект,
но можешь заставить его "сбежать" в кучу (Escape Analysis).
*/
type largeStruct struct {
	data [1024]int // Большая структура
}

func updateStruct(ls *largeStruct) {
	ls.data[0] = 777 // Работаем напрямую с оригиналом в памяти
}

func exampleMemorySharing() {
	obj := &largeStruct{} // Аллокация в куче
	updateStruct(obj)
	fmt.Println("Первый элемент изменен:", obj.data[0])
}

// ПРИМЕР 3: Когда GC вступает в игру? (Unreachable Objects)
/* Объект становится "мусором", когда на него больше нет ссылок из
"корневых" точек (стеки горутин, глобальные переменные).
*/
func exampleGarbageCreation() {
	for i := 0; i < 3; i++ {
		// В каждой итерации создается новый слайс
		// Как только итерация закончена, старый слайс становится недоступен
		data := make([]byte, 10*1024*1024) // 10 MB
		_ = data[0]

		// В этот момент старый массив на 10МБ готов к удалению мусорщиком.
		// GC сам решит, когда именно его почистить (обычно когда куча вырастет).
	}
	fmt.Println("Цикл завершен, 30 МБ данных стали кандидатами на удаление.")
}

// ПРИМЕР 4: Слайсы и нижележащие массивы (Скрытые ссылки)
/* Это классика на собеседованиях. Даже если ты обрезал слайс,
нижележащий массив остается в памяти, пока на него есть хоть одна ссылка.
*/
func exampleSliceMemory() {
	// Создаем огромный массив в памяти
	workData := make([]int, 1_000_000)

	// Берем маленькую часть
	// Несмотря на то, что result маленький, весь миллион int будет висеть в куче,
	// так как result ссылается на тот же нижележащий массив.
	result := workData[:3]

	fmt.Printf("Длина: %d, Капасити: %d\n", len(result), cap(result))

	// ПРАВИЛЬНЫЙ ПОДХОД: Если нам нужны только эти 3 элемента, их надо скопировать,
	// чтобы GC смог удалить массив на миллион элементов.
	cleanResult := make([]int, 3)
	copy(cleanResult, result)
}

// ПРИМЕР 5: "Обнуление" указателей (Manual Nulling)
/* В Go не нужно удалять объекты, но иногда нужно "обнулить" указатель,
чтобы GC понял: данные больше не нужны. Особенно это важно в долгоживущих структурах.
*/
type cache struct {
	items map[string]*largeStruct
}

func (c *cache) remove(key string) {
	// Если мы просто удалим из мапы — это ок.
	// Но если у нас есть указатель в переменной, его надо занулить.
	delete(c.items, key)

	// Теперь ссылка на объект потеряна, и при следующем цикле GC очистит память.
}

// ПРИМЕР 6: Создание объектов через конструкторы (Escape Analysis Intro)
/* Важно понимать: когда ты возвращаешь указатель из функции,
переменная "сбегает" в кучу. Если возвращаешь значение — остается на стеке.
*/
func createInHeap() *int {
	x := 10
	return &x // x "улетает" в кучу, потому что будет нужна вне этой функции
}

func stayOnStack() int {
	y := 20
	return y // y копируется, оригинал умирает вместе со стеком функции. GC тут не нужен.
}

func exampleEscapeSelection() {
	ptr := createInHeap() // Тут работает GC
	val := stayOnStack()  // Тут GC не нужен (профит!)
	fmt.Println(*ptr, val)
}

// 2. АЛГОРИТМЫ GC, UNSAFE И ПРОФИЛИРОВАНИЕ
/*
ТЕОРЕТИЧЕСКАЯ СПРАВКА:

1. КОНЦЕПЦИЯ GC В GO:
   - Go НЕ использует поколения (Generational GC). Почему? Потому что Escape Analysis
     уже на этапе компиляции убирает короткоживущие объекты на стек. В кучу попадает
     только то, что реально должно там быть.
   - Алгоритм: Concurrent Mark & Sweep (Параллельная пометка и очистка).
   - Tri-color Marking: Объекты делятся на Белые (кандидаты на удаление),
     Серые (под надзором) и Черные (точно живые).

2. STOP-THE-WORLD (STW):
   - Это короткие паузы, когда планировщик останавливает все горутины.
   - В Go их две: в начале пометки (Stack Scan) и в конце (Mark Termination).
   - Цель Go — держать STW меньше 1 миллисекунды.

3. ПАКЕТ UNSAFE:
   - Позволяет обходить систему типов и работать с сырыми адресами памяти.
   - Используется для экстремальной оптимизации или стыковки с C-кодом.
*/

// ПРИМЕР 1: Визуализация Tri-color Marking (Логика "Маляра")
/* Чтобы понять алгоритм, представь, что мы вручную проходим по объектам.
GC делает это параллельно с мутатором (твоим кодом).
*/
func exampleTriColorLogic() {
	type object struct {
		name  string
		links []*object
	}

	// 1. БЕЛЫЙ ЭТАП: Все объекты изначально белые (неизвестные).
	obj2 := &object{name: "Объект 2"}
	obj1 := &object{name: "Объект 1 (Корень)", links: []*object{obj2}}

	// 2. СЕРЫЙ ЭТАП: GC находит "Корни" (стек, глобальные переменные).
	// obj1 попадает в серый список — его нужно проверить.
	grayList := []*object{obj1}
	fmt.Println("GC: Нашел корень, добавил в серый список:", obj1.name)

	// 3. ЧЕРНЫЙ ЭТАП: Сканируем серые объекты.
	for len(grayList) > 0 {
		curr := grayList[0]
		grayList = grayList[1:]
		fmt.Printf("Сканирую %s, крашу его в ЧЕРНЫЙ\n", curr.name)

		for _, link := range curr.links {
			fmt.Printf("-> Нашел ссылку на %s, крашу его в СЕРЫЙ\n", link.name)
			grayList = append(grayList, link)
		}
	}
	// 4. ФИНАЛ: obj3 остался БЕЛЫМ.
	// На него нет ссылок от живых (черных) объектов.
	fmt.Println("Результат: Объект 3 будет удален при Sweep (очистке).")
}

// ПРИМЕР 2: Пакет Unsafe (Взлом системы типов)
/* С помощью unsafe можно, например, прочитать приватные поля или
преобразовать []byte в string без копирования (аллокации).
*/
func exampleUnsafePointer() {
	s := "Hello Word"

	// Превращаем строку в слайс байт без выделения новой памяти (Zero-copy)
	// Внимание: это опасно, так как строки в Go иммутабельны!
	b := unsafe.Slice(unsafe.StringData(s), len(s))
	fmt.Printf("Тип: %T, Значение: %s\n", b, string(b))

	// Пример доступа по смещению (арифметика указателей)
	type user struct {
		id   int
		age  int32
		name string
	}
	u := user{
		id:   1,
		age:  18,
		name: "Petr",
	}

	// Получаем указатель на поле Age, зная смещение
	agePtr := (*int32)(unsafe.Pointer(uintptr(unsafe.Pointer(&u)) + unsafe.Offsetof(u.age)))
	fmt.Println("Возраст через unsafe:", *agePtr)
}

// ПРИМЕР 3: Боевой профилинг памяти (Как ловить утечки)
/*
Тут мы создаем "плохой" код, который копит данные в глобальной переменной,
и учимся сохранять отчет, который потом открывается через `go tool pprof`.
*/
var globalLeak []string // Глобальные переменные — главный источник утечек

func exampleMemProfiling() {
	// Создаем файл для записи профиля кучи (heap)
	f, err := os.Create("heap.pprof")
	if err != nil {
		panic(err)
	}
	defer f.Close()
	fmt.Println("Начинаю имитацию утечки памяти...")

	// Имитируем работу сервиса, который "забывает" чистить кэш
	for i := 0; i < 200; i++ {
		data := fmt.Sprintf("Data-chuck-%d", i)
		globalLeak = append(globalLeak, data)

		if i%200 == 0 {
			// runtime.MemStats позволяет смотреть статистику прямо из кода
			var m runtime.MemStats
			runtime.ReadMemStats(&m)
			fmt.Printf("HeapAlloc: %v KB\n", m.HeapAlloc/1024)
		}
	}

	// Важно: вызываем GC перед снятием профиля, чтобы увидеть только
	// те объекты, которые реально живы и не могут быть удалены.
	runtime.GC()

	if err := pprof.WriteHeapProfile(f); err != nil {
		fmt.Println("Не удалось записать профиль:", err)
	}

	fmt.Println("\nГотово! Теперь в терминале введи:")
	fmt.Println("go tool pprof -http=:8080 heap.pprof")
	fmt.Println("И посмотри вкладку 'Source' или 'Graph' — там будет видно globalLeak.")
}

// ПРИМЕР 4: runtime.KeepAlive
/* Иногда GC слишком умный. Если ты работаешь с unsafe или CGO, GC может решить,
что объект тебе больше не нужен, и удалит его ПРЯМО во время работы функции.
KeepAlive приказывает GC не трогать объект до этой точки.
*/
func exampleKeepAlive() {
	type File struct {
		d int
	}
	f := &File{
		10,
	}
	ptr := unsafe.Pointer(f) // Берем адрес

	// ... долгая работа с ptr ..
	_ = ptr

	runtime.KeepAlive(f) // Гарантируем, что f не будет удален до этого момента
}

// ПРИМЕР 5: runtime.SetFinalizer (Ловушка для мусора)
/*
Это "последнее желание" объекта. Функция выполнится, когда GC решит удалить объект.
Полезно для логирования утечек или закрытия ресурсов, которые забыл закрыть прогер.
*/
func exampleFinalizer() {
	type databaseConn struct {
		ID string
	}

	conn := &databaseConn{ID: "MySQL-Primary"}

	// Устанавливаем финализатор
	runtime.SetFinalizer(conn, func(c *databaseConn) {
		fmt.Printf("!!! ВНИМАНИЕ: Объект %s удален из памяти GC. Проверь, был ли он закрыт явно!\n", c.ID)
	})

	fmt.Println("Объект создан, обнуляем ссылку...")
	conn = nil // Теперь объект доступен для GC

	// Принудительно запускаем GC для демонстрации (в проде так не делай!)
	runtime.GC()

	// Даем время горутине финализатора отработать
	time.Sleep(100 * time.Millisecond)
}

// 3. ОПТИМИЗАЦИЯ ПАМЯТИ И ТЮНИНГ RUNTIME
/*
ТЕОРЕТИЧЕСКАЯ СПРАВКА:

1. ПРИНЦИП "ZERO ALLOCATION":
   Самый быстрый GC — тот, который не запускается. Оптимизация в Go всегда
   идет по пути уменьшения количества объектов в куче.

2. SYNC.POOL:
   Это кэш для временных объектов. Вместо того чтобы выбрасывать объект в мусор
   и создавать новый, мы переиспользуем его. Это критично для объектов типа
   []byte (буферы) или структур, которые нужны на миллисекунды.

3. GODEBUG gctrace:
   Переменная GODEBUG=gctrace=1 заставляет рантайм выводить подробную статистику
   о каждом цикле GC. Это позволяет понять: приложение тормозит из-за нехватки
   памяти или из-за слишком частого сканирования.
*/

// ПРИМЕР 1: Оптимизация через sync.Pool
/* Представь сервис, который обрабатывает тысячи запросов в секунду.
Без пула на каждый запрос создается новый буфер, который GC должен потом удалить.
*/
func exampleSyncPool() {
	// Создаем пул буферов
	bufPool := sync.Pool{New: func() interface{} {
		fmt.Println("--- Аллокация нового буфера (New) ---")
		return new(bytes.Buffer)
	}}

	processRequest := func(data string) {
		// Берем буфер из пула (если там есть — вернет готовый, если нет — создаст новый)
		b := bufPool.Get().(*bytes.Buffer)

		// Обязательно очищаем перед использованием!
		b.Reset()
		b.WriteString(data)
		fmt.Println("Обработка:", b.String())

		// Возвращаем буфер обратно в пул для следующей горутины
		bufPool.Put(b)
	}

	for i := 0; i < 5; i++ {
		processRequest(fmt.Sprintf("Request-%d", i))
	}
	// В логах ты увидишь "Аллокация" только 1-2 раза, остальное — переиспользование.
}

// ПРИМЕР 2: Глубокий анализ GODEBUG=gctrace=1
/*
Зачем это нужно: Когда сервис "лагает" (высокий p99), gctrace покажет,
не виноват ли мусорщик.
Запуск: GODEBUG=gctrace=1 ./app
*/
func exampleGCTraceExplanation() {
	// Представьте реальный лог в консоли:
	// gc 1405 @12.340s 3%: 0.015+1.2+0.020 ms clock, 0.12+1.2/2.5/5.0+0.16 ms cpu, 400->410->200 MB, 420 MB goal, 8 P

	/* ЭКСПЕРТНЫЙ РАЗБОР:
	1. "3%": Это CPU Profile мусорщика. Если тут выше 10-15%, твоё приложение
	   занимается не бизнесом, а уборкой. Нужно резать аллокации.
	2. "0.015+1.2+0.020 ms clock":
	   - 0.015: STW пауза (Stack Scan).
	   - 1.2: Параллельная пометка (код работает!).
	   - 0.020: STW пауза (Mark Termination).
	   Суммарно STW тут всего 0.035ms — это идеал.
	3. "400->410->200 MB":
	   - 400: Куча перед началом цикла.
	   - 410: Куча в момент завершения пометки.
	   - 200: Живая память (то, что осталось после Sweep).
	   Тут видно, что мы очистили 210 MB. Если вторая цифра (410) постоянно
	   растет и не падает после GC — у тебя утечка.
	4. "420 MB goal": Следующий GC запустится, когда куча достигнет 420 MB (согласно GOGC).
	*/
	fmt.Println("gctrace позволяет понять, успевает ли GC за темпами аллокаций приложения.")
}

// ПРИМЕР 3: Глубокое управление runtime и его влияние на CPU
/* Задача: Понять, как GOMAXPROCS физически ограничивает параллелизм
и как отслеживать состояние рантайма в реальном времени.
*/
func exampleRuntimeControl() {
	// 1. Динамическое изменение количества P (логических процессоров)
	originalProcs := runtime.GOMAXPROCS(1) // Ограничиваем до 1 ядра
	fmt.Printf("GOMAXPROCS изменен с %d на 1. Проверяем нагрузку...\n", originalProcs)

	const iterations = 100_000_000
	var wg sync.WaitGroup

	// Функция-воркер (CPU-bound задача)
	worker := func(id int) {
		defer wg.Done()
		start := time.Now()
		count := 0
		for i := 0; i < iterations; i++ {
			count += i
		}
		fmt.Printf("Воркер %d завершен за %v\n", id, time.Since(start))
	}

	// Запускаем 4 горутины на 1 ядре
	// Они будут работать КОНКУРЕНТНО (по очереди), но не ПАРАЛЛЕЛЬНО.
	wg.Add(4)
	fmt.Println("Запуск 4-х воркеров на 1 процессоре:")
	for i := 1; i <= 4; i++ {
		go worker(i)
	}
	wg.Wait()

	// 2. Возвращаем мощь всех ядер
	runtime.GOMAXPROCS(runtime.NumCPU())
	fmt.Printf("\nGOMAXPROCS изменен на %d. Повторяем запуск:\n", runtime.NumCPU())

	wg.Add(4)
	for i := 1; i <= 4; i++ {
		go worker(i)
	}
	wg.Wait()

	// 3. Чтение метрик рантайма (MemStats)
	// Это то, что обычно отправляют в Prometheus/Grafana
	var m runtime.MemStats
	runtime.ReadMemStats(&m)
	fmt.Printf("\n--- Итоговая статистика рантайма ---\n")
	fmt.Printf("Всего горутин: %d\n", runtime.NumGoroutine())
	fmt.Printf("Память в куче (Alloc): %v MB\n", m.Alloc/1024/1024)
	fmt.Printf("Количество вызовов GC: %v\n", m.NumGC)
}

// ПРИМЕР 4: Оптимизация аллокаций (Zero-copy и эффективный рантайм)
/* Самый частый мусор создается при конвертации []byte <-> string.
В Go 1.22+ есть оптимизации, но их надо понимать.
*/
func exampleAvoidAlloc() {
	// 1. КОНВЕРТАЦИЯ В ЦИКЛЕ (ПЛОХО)
	// Каждая итерация создает новую строку в куче
	payload := []byte("important data")
	for i := 0; i < 100; i++ {
		_ = string(payload)
	}

	// 2. ИСПОЛЬЗОВАНИЕ ТИПОВ-ОБЕРТОК (ХОРОШО)
	// Например, работаем напрямую с байтами через bytes.Buffer или strings.Builder
	var builder strings.Builder
	builder.Write(payload)
	_ = builder.String() // Аллокация только один раз в конце

	// 3. OPTIMIZATION TIP (MAPS):
	// В Go есть спец. оптимизация: m[string(keyBytes)] не делает аллокацию строки,
	// если это используется только для поиска в мапе!
	m := make(map[string]int)
	key := []byte("user_1")
	_ = m[string(key)]

	// 4. ПЕРЕДАЧА ПО УКАЗАТЕЛЮ В ИНТЕРФЕЙС
	// interface{} (any) — это всегда аллокация, если данные больше 8 байт.
	// Чтобы избежать этого, передавай указатель.
	var anyVal any = &payload // Указатель на слайс весит 8 байт и влезает в интерфейс без кучи
	_ = anyVal
}

// 4. ЭКСПЕРТНЫЙ ТЮНИНГ RUNTIME И GC
/*
В этом блоке мы переходим от "как это работает" к "как этим управлять, когда всё горит".
Мы разберем:
- Борьбу с GC CPU Starvation (когда GC ест все ресурсы).
- Использование runtime/metrics для глубокого мониторинга (современный подход).
- Ручное управление планировщиком для высоконагруженных систем.
*/

// ПРИМЕР 1: Симуляция и решение проблемы "GC CPU Starvation"
/* Проблема: Если аллокаций слишком много, мусорщик начинает Mark Assist
(заставляет рабочие горутины помогать ему). Бизнес-логика тормозит.
*/
func exampleGCCPUControl() {
	// 1. Настраиваем GOMEMLIMIT и GOGC для экстремальных условий
	// Отключаем стандартный GOGC, чтобы управлять только через лимит памяти
	debug.SetGCPercent(-1)
	debug.SetMemoryLimit(200 * 1024 * 1024) // 200MB лимит
	fmt.Println("--- Старт тяжелой нагрузки на кучу ---")

	stop := make(chan struct{})
	go func() {
		for {
			select {
			case <-stop:
				return
			default:
				// Генерируем огромный поток мусора
				_ = make([]byte, 10*1024*1024) // 10MB каждые пару мс
				time.Sleep(1 * time.Millisecond)
			}
		}
	}()

	// Мониторим нагрузку через runtime/metrics (Go 1.16+)
	// Это точнее и быстрее, чем ReadMemStats
	sample := make([]metrics.Sample, 2)
	sample[0].Name = "/gc/cpu/fraction:seconds" // Процент CPU на сборку
	sample[1].Name = "/memory/classes/heap/objects:bytes"

	for i := 0; i < 5; i++ {
		time.Sleep(500 * time.Millisecond)
		metrics.Read(sample)

		cpuUsage := sample[0].Value.Float64()
		heapSize := sample[0].Value.Uint64() / 1024 / 1024

		fmt.Printf("[%d] GC CPU usage: %.2f%% | Heap: %d MB\n", i, cpuUsage*100, heapSize)
		// Если cpuUsage > 0.25 (25%), значит мы в критической зоне Mark Assist
	}
	close(stop)
}

// ПРИМЕР 2: Тонкая настройка планировщика (LockOSThread)
/* Задача: Когда нам нужна максимальная предсказуемость (например, работа с графикой
или real-time аудио), мы привязываем горутину к конкретному системному потоку (M).
*/
func exampleThreadPinning() {
	var wg sync.WaitGroup
	wg.Add(1)

	go func() {
		defer wg.Done()

		// Привязываем эту горутину к текущему потоку ОС
		// Теперь планировщик не будет перекидывать её между ядрами (P)
		runtime.LockOSThread()
		defer runtime.UnlockOSThread()

		// Теперь эта горутина - "хозяин" потока. Это снижает Cache Misses
		// и Latency, так как контекст не переключается.
		fmt.Println("Горутина залочена на потоке ОС. Идеально для CGO или Low-latency.")

		// Делаем что-то очень быстрое
		for i := 0; i < 10000000; i++ {
		}
	}()
	wg.Wait()
}

// ПРИМЕР 3: Анализ фрагментации и Garbage Collection "Pacing"
/* Мы можем заставить GC быть менее агрессивным, если понимаем,
что у нас есть свободная память, но мы хотим сэкономить CPU.
*/
func exampleGCPacing() {
	// Устанавливаем GOGC в 500 (запуск GC при росте кучи в 5 раз)
	// Это уменьшит количество пауз STW в 5 раз ценой RAM.
	old := debug.SetGCPercent(500)
	defer debug.SetGCPercent(old)

	// Читаем параметры планировщика
	fmt.Printf("Количество ядер: %d\n", runtime.NumCPU())
	fmt.Printf("Активных горутин: %d\n", runtime.NumGoroutine())

	// Принудительное возвращение памяти ОС (Scavenging)
	// В Go 1.12+ это происходит плавно, но иногда нужно "подтолкнуть"
	debug.FreeOSMemory()
	fmt.Println("Память принудительно возвращена ОС.")
}

// ПРИМЕР 4: Анализ фрагментации памяти
/* Задача: Показать разницу между тем, сколько памяти "реально занято данными"
и сколько "удерживается рантаймом" из-за фрагментации или резерва.
*/
func exampleFragmentation() {
	var m runtime.MemStats

	fmt.Println("--- Анализ фрагментации ---")

	// 1. Создаем "дырявую" память
	const count = 100_000
	data := make([]*int, count)
	for i := 0; i < count; i++ {
		v := i
		data[i] = &v // Аллоцируем маленькие int в куче
	}

	// Удаляем каждый второй элемент, создавая дыры (фрагментацию)
	for i := 0; i < count; i += 2 {
		data[i] = nil
	}

	// Принудительно запускаем GC, чтобы очистить "каждый второй"
	runtime.GC()
	runtime.ReadMemStats(&m)

	// HeapAlloc - сколько памяти занимают живые объекты
	// HeapSys - сколько памяти рантайм взял у ОС под кучу
	fmt.Printf("Живых данных в куче: %v MB\n", m.HeapAlloc/1024/1024)
	fmt.Printf("Всего памяти у ОС (HeapSys): %v MB\n", m.HeapSys/1024/1024)

	fragmentation := float64(m.HeapSys-m.HeapAlloc) / float64(m.HeapSys) * 100
	fmt.Printf("Виртуальная фрагментация/резерв: %.2f%%\n", fragmentation)

	// Если этот процент растет со временем - у тебя "течет" не память, а фрагменты.
}

// ПРИМЕР 6: Системный мониторинг через ReadMemStats (PauseNS)
/* Задача: Показать, как измерить задержки (Latency), вносимые сборщиком мусора.
 */
func exampleGCPauseTracking() {
	var m runtime.MemStats
	runtime.ReadMemStats(&m)

	fmt.Println("\n--- Анализ пауз GC ---")

	// PauseNs - это циклическое окно последних 256 пауз GC в наносекундах
	// Посчитаем среднюю паузу за последнее время

	var totalPause uint64
	count := 0
	for i := 0; i < 256; i++ {
		if m.PauseNs[i] > 0 {
			totalPause += m.PauseNs[i]
			count++
		}
	}

	if count > 0 {
		avg := totalPause / uint64(count)
		fmt.Printf("Средняя пауза STW: %v микросекунд\n", avg/1000)
		fmt.Printf("Последняя пауза: %v микросекунд\n", m.PauseNs[(m.NumGC+255)%256]/1000)
	} else {
		fmt.Println("GC еще не запускался.")
	}
}
