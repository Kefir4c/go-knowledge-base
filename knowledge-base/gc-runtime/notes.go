package gc_runtime

/*
NOTES (block 1):

1. Указатели в Go безопасны: Ты не можешь заниматься "арифметикой указателей"
   (прибавлять +1 к адресу), как в C. Это защищает память от повреждения.
2. nil: Нулевое значение для указателя. Всегда проверяй на nil перед
   разыменованием (*p), иначе получишь панику (panic).
3. GC не мгновенен: Он не удаляет объект сразу, как только ты перестал им
   пользоваться. Он делает это циклами.
4. Значение vs Указатель:
   - Маленькие структуры (до 64 байт) лучше копировать (по значению).
   - Большие структуры или те, что нужно менять, передавай по указателю.
*/

/*
NOTES (block 2):

1. Почему нет Поколений (Generational GC)?
   В Java объекты часто живут недолго. В Go Escape Analysis выносит такие объекты на стек.
   Те, что попали в кучу, обычно живут долго. Смысла делить их на поколения меньше.
2. Write Barrier: Во время работы GC горутины продолжают менять ссылки. Чтобы маляр
   не пропустил новый объект, используется Write Barrier — он перехватывает запись
   ссылки и красит объект в серый, если идет пометка.
3. Cgo : При работе с C памятью GC не управляет ею.
   Тебе нужно вручную вызывать free() в C-коде, иначе будет утечка, которую
   pprof даже не увидит (потому что это вне кучи Go).
4. OOM Killer: Если ты видишь, что процесс падает по памяти, а pprof показывает
   мало — ищи утечки в CGO или слишком большое количество горутин (каждая ест стек).
*/
/*
NOTES (block 3):

1. Scavenger: В Go есть фоновый поток, который возвращает свободную память ОС.
   Это происходит не сразу, а постепенно. Не пугайся, если в мониторинге
   RSS (память процесса) не падает мгновенно после GC.
2. Forced GC: runtime.GC() блокирует вызывающую горутину до конца очистки.
   Никогда не вызывай это в обработчиках HTTP-запросов.
3. GOGC=off: Можно полностью выключить GC. Это полезно для короткоживущих
   CLI-утилит: они отработают на 20% быстрее, а память всё равно вернется ОС после выхода.
4. Выравнивание структур (Alignment): Если в структуре поля идут вперемешку
   (bool, int64, bool), она будет занимать больше места из-за паддинга.
   Группируй типы по размеру — это экономит место в куче и кэш CPU.
5. sync.Pool и GC: Помни, что объекты в sync.Pool могут быть удалены мусорщиком
   в любой момент (обычно между циклами GC). Пул не гарантирует хранение.
6. MemStats vs GCTrace: ReadMemStats дает мгновенный снимок, а gctrace показывает
   динамику. Для отладки "заиканий" (latency spikes) используй gctrace.
7. GOMEMLIMIT (1.19+): Обязательно упоминай его вместе с GOGC. Это лучший способ
   предотвратить OOM (Out Of Memory) в облаке, не жертвуя производительностью.
8. Finalizers и С-код: Если используешь CGO, GC не очистит память C.
   SetFinalizer поможет автоматизировать очистку, но лучше делать это явно.
*/

/*
NOTES (block 4):

1. Провал в производительности из-за "Large Objects":
   Объекты > 32KB аллоцируются в куче напрямую, минуя кэши P (mcache).
   Это медленнее. Если твой сервис работает с большими JSON, старайся их стримить,
   а не десериализовать целиком.

2. Стек vs Куча (Глубокий инсайт):
   Каждая горутина начинает со стека 2KB. Если стек растет, рантайм создает новый
   кусок памяти и КОПИРУЕТ туда старый стек. Если у тебя миллион горутин с
   глубокой рекурсией — это вызовет колоссальную нагрузку на копирование памяти.

3. runtime.MemProfileRate:
   По умолчанию Go сэмплирует одну аллокацию на 512KB. Если тебе нужно найти
   мелкие, но частые аллокации — выкручивай этот параметр в 1 (но это замедлит приложение).

4. GOMEMLIMIT + Garbage Collection Cycle:
   Если памяти мало, Go будет игнорировать GOGC и запускать сборку постоянно,
   пытаясь выжить в лимите. Это называется "GC Thrashing". Если видишь это в логах —
   лимит выставлен слишком жестко.
*/
