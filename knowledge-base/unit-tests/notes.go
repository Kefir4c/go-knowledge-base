package unit_tests

/*
NOTES (block 1):

1. Файлы тестов: *_test.go. Функции: TestXxx(t *testing.T). Запуск: go test -v.

2. t.Error vs t.Fatal:
   - Error: тест провален, НО выполнение продолжается (для нескольких проверок)
   - Fatal: тест провален, выполнение ПРЕРЫВАЕТСЯ (для критических проверок, например, nil)

3. Table-Driven Tests — золотой стандарт в Go:
   Слайс структур с входными данными и ожидаемым результатом + t.Run для каждого кейса.
   Легко добавлять новые кейсы и видно все граничные случаи.

4. t.Helper() — помечает функцию как вспомогательную. Ошибка будет указывать на строку вызова, а не на внутренность хелпера.

5. Пропуск тестов: if testing.Short() { t.Skip("skip in short mode") }
   Запуск: go test -short

6. Команды:
   go test              — запуск тестов в текущей папке
   go test -v           — подробный вывод
   go test -run=TestAdd — запуск конкретного теста
   go test -cover       — показать покрытие кода
   go test -race        — детектор гонок данных (ОБЯЗАТЕЛЬНО в CI)
   go test ./...        — все тесты проекта
*/

/*
NOTES (block 2):

1. Три типа тестовых сценариев: happy path (основной), edge cases (границы), error path (ошибки).
   Все три должны быть покрыты.

2. Изоляция — главный принцип unit-тестов:
   - Нет глобальных переменных
   - Каждый тест создаёт свои моки и данные
   - Тесты не должны влиять друг на друга

3. Мокирование зависимостей (UserRepository, EmailValidator) позволяет тестировать
   бизнес-логику без реальной БД или внешних API.

4. При проверке ошибок нужно проверить: что ошибка есть, её тип/текст, и что полезные данные = nil.
   Используй errors.Is для проверки вложенных ошибок.

5. Table-driven tests — стандарт для проверки множества кейсов.
   Каждый кейс должен иметь осмысленное имя, описывающее сценарий.

6. Тесты — это документация. Читая test name, должно быть понятно, что проверяется.
   "TestCreateUser_InvalidEmail" лучше чем "TestCreateUser2".

7. Не тестируй внутренности реализации (приватные поля, внутренние функции).
   Тестируй публичный API. Это даёт свободу рефакторинга.
*/

/*
NOTES (block 3):

1. Организация тестов: файлы *_test.go лежат РЯДОМ с тестируемым кодом.
   Пакет service_test — для чёрного ящика (только публичный API).

2. Покрытие: go test -cover (процент), -coverprofile (файл), -html (браузер).
   70-80% — хорошая цель. 100% не гарантирует отсутствие багов.

3. Мок vs Фейк vs Стаб:
   - Мок: проверяет, что метод вызван (с какими параметрами)
   - Фейк: упрощённая рабочая реализация (БД в памяти)
   - Стаб: просто возвращает заданное значение

4. Table-driven tests — стандарт. Добавляй setup функцию внутрь таблицы,
   если для разных кейсов нужна разная подготовка данных.

5. Golden files (testdata/*.golden) — для больших ожидаемых результатов.
   Не храни огромные JSON в коде теста.

6. testdata директория игнорируется компилятором, но доступна в тестах.
   Отлично для JSON, CSV, бинарных файлов.

7. Setup/teardown через вспомогательные функции с t.Helper() и defer cleanup.
   Не используй глобальные переменные для хранения состояния тестов.
*/

/*
NOTES (BLOCK 4):

1. tdd цикл: красный (падающий тест) → зелёный (минимальный код) → рефакторинг.
   tdd проектирует архитектуру, а не просто проверяет код.

2. сложные сценарии должны включать: панику, конкурентность, таймауты, отмену контекста.
   всегда проверяй не только happy path, но и ошибки зависимостей.

3. бенчмарки: go test -bench=. -benchmem.
   важны не только ns/op, но и allocs/op — много аллокаций = нагрузка на gc.

4. профилирование: go test -cpuprofile=cpu.out + go tool pprof -http=:8080 cpu.out.
   flat — время функции без вложенных, cum — с вложенными.

5. ci/cd обязательные шаги: go vet, go test -race, go test -cover, staticcheck.
   порог покрытия 70% — хорошая практика.

6. флаг -race обязательно включать в ci. гонки данных — критичные баги.
   никогда не деплой без прогона с -race.

7. при тестировании конкурентности используй sync.WaitGroup и atomic.
   никогда не используй time.Sleep для синхронизации.

8. бенчмарки запускай с -count=10 для усреднения (шум от cpu не даёт точных значений).
   храни историю бенчмарков, чтобы отслеживать деградацию производительности.
*/
