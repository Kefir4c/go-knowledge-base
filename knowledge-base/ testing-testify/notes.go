package _testing_testify

/*
NOTES:

1. Error vs Fatal:
   - t.Errorf: Тест зафейлен, но идем дальше (удобно для табличных тестов).
   - t.Fatalf: Тест зафейлен, выходим немедленно (удобно для Setup части).

2. White-box vs Black-box:
   - package mypkg: Тестируем приватные поля (белый ящик).
   - package mypkg_test: Тестируем только публичный API (черный ящик). Профи выбирают этот вариант.

3. Race Detector:
   Всегда упоминай флаг `-race`. Это мастхэв для проверки гонок данных в горутинах.

4. Тестирование из коробки:
   В Go не нужны внешние либы для базы. Тулчейн `go test` закрывает все вопросы.
*/

/*
NOTES:

1. Assert vs Require:
   - `assert`: "Я хотел бы, чтобы это было так". Логирует ошибку, идет дальше.
   - `require`: "Это обязано быть так, иначе всё упадет". Стопает тест (t.FailNow).
     Используй require для проверок err и nil-указателей.

2. Почему Testify — стандарт?
   - Читаемость: Код превращается в плоский список утверждений.
   - Диффы: Если упадет сравнение огромной мапы, Testify покажет конкретный ключ и разницу в значениях.

3. Пирамида тестирования:
   - Юниты: 80% кода. Быстрые, без внешних связей.
   - Интеграция: 15% кода. Проверка SQL, миграций, конфигов.
   - E2E: 5% кода. Весь путь пользователя.

4. t.Helper():
   - Всегда пиши его в своих кастомных функциях проверки, чтобы отчет об ошибке указывал на место вызова, а не на внутренности хелпера.
*/

/*
NOTES:

1. Интерфейсы — это база:
   Если ты не выделил зависимости в интерфейсы (как UserRepo), ты не сможешь
   подсунуть мок в сервис. Тестируемость кода закладывается на этапе архитектуры.

2. Пакет _test:
   Всегда старайся писать `package something_test`. Это заставляет тебя думать
   как пользователь твоей библиотеки, а не как разработчик кишок.

3. AssertExpectations:
   В моках это критично. Если ты настроил .On(...), но метод не вызвался —
   тест должен упасть. Без этого вызова мок — просто бесполезный стаб.

4. Suite vs Classic:
   Используй Suite для тяжелых тестов (БД, API), где есть Setup/Teardown.
   Для простой бизнес-логики обычные TestXxx функции остаются более идиоматичными.
*/

/*
NOTES:

1. TDD — это дизайн, а не тест:
   Если код сложно покрыть тестом до написания — значит, в архитектуре слишком
   много зависимостей. TDD принуждает к декомпозиции.

2. pprof и утечки:
   На собесе: "Как найти узкое место?". Ответ: "Используем `go tool pprof`.
   Снимаем профиль CPU для поиска медленного кода и Heap для поиска утечек памяти".

3. CI/CD Pipeline:
   Тесты должны запускаться с флагом `-race`. Если гонка данных проскочила в прод
   — это косяк всей системы тестирования.

4. Бенчмарки:
   Важна не только скорость (ns/op), но и аллокации (allocs/op).
   Много аллокаций = частые паузы Garbage Collector'а (GC).

5. Testify Mock .Run():
   Используй .Run() только если нужно имитировать сложную логику зависимости,
   например, изменение переданного по указателю объекта.
*/
