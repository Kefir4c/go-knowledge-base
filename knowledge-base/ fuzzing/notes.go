package _fuzzing

/*
NOTES (BLOCK 1):

1. фазз-тестирование (fuzzing) — подача случайных/некорректных данных для поиска скрытых ошибок.
   от обычных тестов отличается автоматической генерацией входных данных.

2. какие ошибки находит: паника (index out of range, nil pointer), бесконечные циклы,
   утечки памяти, deadlock, уязвимости безопасности.

3. преимущество фаззинга: находит баги, о которых ты даже не думал.
   невозможно вручную предугадать все граничные случаи.

4. где лучше всего применять: парсеры, декодеры, сетевые протоколы,
   функции работающие с []byte или string.

5. в go фаззинг появился в версии 1.18 (февраль 2022) — нативная поддержка в пакете testing.

6. структура фазз-теста: func FuzzXxx(f *testing.F) { f.Add(seed); f.Fuzz(func(t *testing.T, data ...) {}) }

7. запуск: go test -fuzz=FuzzXxx -fuzztime=30s.

8. найденные ошибки сохраняются в testdata/fuzz/ и воспроизводятся через go test -run=FuzzXxx/seed#0.

9. важное ограничение: фаззинг не подходит для бизнес-правил с чёткими ограничениями
   (например, "скидка не может быть больше 100%").

10. свойство (property) — это инвариант, который должен всегда выполняться.
    например: reverse(reverse(x)) == x.
*/

/*
NOTES (BLOCK 2):

1. go-fuzz — библиотека Дмитрия Вьюкова (2015), была стандартом до go 1.18.
   сейчас рекомендуется нативный fuzz, но go-fuzz нужна для старых проектов.

2. сигнатура go-fuzz: func Fuzz(data []byte) int.
   возвращает 1 (интересные данные), 0 (нейтральные), -1 (игнорировать).

3. ошибки передаются через panic. найденные крашеры лежат в workdir/crashers/.

4. вывод go-fuzz: workers (параллелизм), corpus (размер корпуса), crashers (ошибки), cover (покрытие).

5. установка: go-fuzz-build (компиляция), go-fuzz (запуск), флаги -procs и -http.

6. go-fuzz умеет только []byte, нативный fuzz — любые типы (int, string, []byte).

7. в ci/cd обычно используют нативный fuzz, так как он встроен в go test.
*/

/*
NOTES (BLOCK 3):

1. настройка фаззинга: -fuzztime (время), -parallel (воркеры), -keepfuzzing.
   в коде: t.Skip() для больших данных, testing.Short() для CI.

2. интерпретация результатов: execs (скорость), new interesting (новые пути).
   чем выше скорость (execs/sec), тем эффективнее фаззинг.

3. оптимизация: убирай лишние аллокации, используй t.Skip() для больших данных,
   не делай тяжёлых операций в фазз-функции.

4. seed corpus должен включать: граничные значения (0, пустые данные),
   правильные данные, заведомо неверные данные.

5. найденные кейсы лежат в testdata/fuzz/ИмяФаззТеста/.
   для воспроизведения: go test -run=ИмяФаззТеста/имя_кейса.

6. в CI запускай короткий фаззинг (1-5 минут) с флагом -short=0.
   долгий фаззинг запускай отдельно (nightly job).

7. при анализе крашеров смотри: длину данных, конкретные байты, вызвавшие ошибку.
   обычно это переполнения длины или неожиданные значения.
*/

/*
NOTES (BLOCK 4):

1. как работает фаззер: замеряет покрытие кода (coverage guidance).
   новые пути выполнения = интересные данные = добавляются в корпус.

2. что ищут фаззингом: buffer overflow, integer overflow, nil pointer, DoS,
   memory leak, injection уязвимости.

3. дифференциальный фаззинг: сравниваем две реализации (свою и эталонную).
   отлично подходит для парсеров и декодеров.

4. stateful фаззинг: для протоколов с состоянием (TCP, HTTP).
   нужно сохранять состояние между вызовами.

5. CI/CD стратегия: PR (30 сек), nightly (2 часа), релиз (8+ часов).
   используй теги +build для разделения.

6. кастомный фаззер: когда нужны структурированные данные (SQL, JSON).
   или когда нужен FSM для мутаций.

7. регрессионный фаззинг: храни все найденные крашеры в testdata/.
   запускай их при каждом CI прогоне.

8. безопасность: фаззинг находит критические уязвимости лучше статического анализа.
   особенно эффективен для CVE поиска в парсерах и протоколах.
*/
