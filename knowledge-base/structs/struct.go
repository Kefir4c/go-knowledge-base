func (u User) Greet() string {
	return "Привет" + u.Name
}

func (u User) SetAge(age int) {
	u.Age = age
}

func demReceivers() {
	u := User{Name: "Anna"}
	fmt.Printf(u.Greet())

	u.SetAge(25)
	fmt.Println("Age:", u.Age)
}

/*
ВАЖНЫЕ ОТЛИЧИЯ РЕСИВЕРОВ:

| Тип ресивера | Пример          | Может менять исходный объект | Автоматическое разыменование|
|--------------|---------------  |----------------------------- |-----------------------------|
| Значение     | `func (u User)` | Нет                          | Нет                         |
| Указатель    | `func (u *User)`| Да                           | Да                          |

ПРИМЕР С РАЗНИЦЕЙ:
*/
type Counter struct {
	value int
}

// Метод с ресивером-значением (меняет копию)
func (c Counter) Increment() {
	c.value++ // Меняет копию, не влияет на исходный объект
}

// Метод с ресивером-указателем (меняем исходный объект)
func (c *Counter) IncrementPtr() {
	c.value++
}

func demReceiverDifference() {
	c := Counter{}
	c.Increment()
	fmt.Println("After Increment():", c.value) // 0 (не изменилось)

	c.IncrementPtr()
	fmt.Println("After IncrementPtr():", c.value) // 1 (изменилось)
}

/*
ПРИВАТНЫЕ ПОЛЯ:
ЧТО ЭТО:
- Поля с маленькой буквы (например, `name`) недоступны из других пакетов.
- Это механизм инкапсуляции в Go (аналог private в других языках).

ПОЧЕМУ ЭТО ВАЖНО:
- Защищает внутреннее состояние структуры от несанкционированного доступа.
- Позволяет контролировать, как данные изменяются.
- Обеспечивает валидацию данных перед установкой.

ПРИМЕР ПРИВАТНЫХ ПОЛЕЙ:
*/

type UserProfile struct {
	name string
	age  int
}

// Конструктор
func NewUserProfile(name string, age int) *UserProfile {
	return &UserProfile{
		name: name,
		age:  age,
	}
}

// Геттеры
func (u *UserProfile) GetAge() int {
	return u.age
}
func (u *UserProfile) GetName() string {
	return u.name
}

// Сеттеры
func (u *UserProfile) SetAge(age int) {
	if age >= 0 {
		u.age = age
	}
}

func demPrivateFields() {
	// Создаем объект через конструктор
	user := NewUserProfile("Петр", 35)

	// Доступ к приватным полям только через методы
	fmt.Printf("User: %s, %d years old\n", user.GetName(), user.GetAge())

	// Изменение через сеттеры
	user.SetAge(36)
	fmt.Printf("Updated age: %d\n", user.GetAge())

	// Попытка прямого доступа вызовет ошибку компиляции
	//fmt.Println(user.name) // ОШИБКА: name is not exported
}

