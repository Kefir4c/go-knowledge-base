// 3. ПУСТЫЕ СТРУКТУРЫ
/*
ЧТО ЭТО:
- `struct{}` — это структура без полей.
- Занимает 0 байт в памяти (`unsafe.Sizeof(struct{}{}) == 0`).
- Но при этом каждый экземпляр ссылается на один и тот же адрес в памяти.
  (даже если создать 10 пустых структур, они будут ссылаться на один адрес)
- В пустые структуры невозможно записать или прочитать данные из них


ЗАЧЕМ НУЖНО:
1. Множества (sets) — когда нужно хранить уникальные ключи без значений.
2. Сигналы в каналах — когда нужно уведомить о событии без передачи данных.
3. Экономия памяти — в больших коллекциях разница критична.

ПОЧЕМУ ИМЕННО struct{}, А НЕ interface{}?
- `interface{}` даже в nil-состоянии занимает **16 байт** (2 указателя: тип + данные).
- `struct{}` занимает 0 байт → идеален как "заполнитель".

ПРИМЕР 1: МНОЖЕСТВО URL-ОВ
*/

func demSetWithStruct() {
	seed := make(map[string]struct{})
	url := "https://kefir.com"

	seed[url] = struct{}{}
	if _, exists := seed[url]; exists {
		fmt.Println("URL уже обработан")
	}
}

func demSignalChannel() {
	done := make(chan struct{})

	go func() {
		// Делаем полезную работу
		time.Sleep(100 * time.Millisecond)
		done <- struct{}{}
	}()
	<-done
	fmt.Println("Работа завершена")
}

/*
ПОЧЕМУ ЭТО ЭФФЕКТИВНО?
- При миллионе URL в множестве:
  • `map[string]bool` → +1 МБ памяти (1 байт на запись)
  • `map[string]struct{}` → +0 байт
- В каналах: нет аллокации данных → меньше давления на GC

ВАЖНО:
- Нельзя использовать `interface{}` вместо `struct{}` для этих целей — он тяжёлый.
- `struct{}` — идиоматичный способ реализации множеств и сигналов в Go.
*/

// 4. ВЫРАВНИВАНИЕ ПАМЯТИ (MEMORY ALIGNMENT)

/*
ПОЧЕМУ ВЫРАВНИВАНИЕ ВАЖНО?

Современные процессоры (особенно amd64) не могут эффективно читать данные,
которые начинаются на "некратных" адресах. Например:
- Переменная типа `int64` (8 байт) должна начинаться с адреса, кратного 8.
- Если она начинается с адреса 9 → CPU делает два обращения к памяти вместо одного!

Это называется **memory alignment requirement**.

КАК GO РЕАЛИЗУЕТ ВЫРАВНИВАНИЕ?

 1. **Padding (отступы)**
    Go автоматически вставляет "пустые" байты между полями структуры,
    чтобы каждое поле начиналось с выровненного адреса.

 2. **Выравнивание всей структуры**
    Размер всей структуры округляется до кратного её **максимальному выравниванию**.
    Например: если есть `int64` (выравнивание = 8), то размер структуры будет кратен 8.

 3. **Правило упаковки**
    Чтобы минимизировать padding, поля нужно сортировать **от самых больших к самым маленьким**.

ПРИМЕР ПЛОХОЙ УПАКОВКИ:
*/
type BadStruct struct {
	a bool // 1 байт → адрес 0
	// [7 байт PADDING] → чтобы b начался с адреса 8 (кратно 8)
	b int64 // 8 байт → адрес 8
	c bool  // 1 байт → адрес 16
	// [7 байт PADDING] → чтобы размер был кратен 8 (макс. выравнивание = 8)
}

// Итого: 1 + 7 + 8 + 1 + 7 = 24 байта

/*
ПРИМЕР ХОРОШЕЙ УПАКОВКИ:
*/
type GoodStruct struct {
	b int64 // 8 байт → адрес 8
	a bool  // 1 байт → адрес 9
	c bool  // 1 байт → адрес 10
	// [6 байт PADDING] → только в конце, чтобы размер был кратен 8
}

// Итого: 8 + 1 + 1 + 6 = 16 байт

/*
КАК ПРОВЕРИТЬ ВЫРАВНИВАНИЕ?

Используй `unsafe.Alignof()` и `unsafe.Offsetof()`:
*/
func demAlignmentDetails() {
	var s GoodStruct
	fmt.Printf("Alignof(s.b): %d\n", unsafe.Alignof(s.b))   // 8
	fmt.Printf("Offsetof(s.a): %d\n", unsafe.Offsetof(s.a)) // 8
	fmt.Printf("Sizeof(s): %d\n", unsafe.Sizeof(s))         // 16
}

/*
ПОЧЕМУ ЭТО КРИТИЧНО ДЛЯ ПРОИЗВОДИТЕЛЬНОСТИ?

1. **Меньше памяти** → больше объектов в кэше CPU → меньше cache misses.
2. **Быстрее чтение/запись** → CPU делает одно обращение вместо двух.
3. **Меньше давления на GC** → меньше аллокаций → меньше пауз.

ПРАКТИЧЕСКИЙ ПРИМЕР:
Представь, что у тебя 1_000_000 объектов `BadStruct` vs `GoodStruct`:
- BadStruct: 24 МБ
- GoodStruct: 16 МБ
→ Экономия **8 МБ RAM** без изменения логики!
*/

func main() {
	demStartedBasicStruct()
	demEmbedding()
	demNameConfig()
	demReceivers()
	demReceiverDifference()
	demPrivateFields()
	demSetWithStruct()
	demSignalChannel()
	demAlignmentDetails()
}
