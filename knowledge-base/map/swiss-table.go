// 1. ЧТО ТАКОЕ SWISS TABLE В GO 1.24?

/*
НАЧИНАЯ С GO 1.24, МАПЫ ПОЛНОСТЬЮ ИСПОЛЬЗУЮТ SWISS TABLE —
это официальная реализация по умолчанию (не эксперимент!).

ОСНОВНЫЕ ОСОБЕННОСТИ:
- Используется открытая адресация (open addressing)
- Данные хранятся в группах (groups) по 8 слотов
- Поиск оптимизирован под cache-friendly layout
- Нет больше "бакетов" и цепочек

ПОЧЕМУ ЭТО ВАЖНО:
- На 15–30% быстрее при чтении
- На 20–25% меньше потребление памяти
- Лучшая локальность кэша → меньше cache misses
- Прозрачно для разработчика — никаких изменений в коде не нужно
*/

// 2. ВНУТРЕННЕЕ УСТРОЙСТВО: ГРУППЫ И CONTROL BYTES

/*
КАК УСТРОЕНА МАПА В ПАМЯТИ:

1. hmap — заголовок мапы
   - count: количество элементов
   - B: степень двойки → 2^B = количество групп
   - buckets: указатель на непрерывный блок групп

2. Группа (group) — основная единица хранения
   - Состоит из 8 слотов (key-value пар)
   - Имеет 8 байт метаданных (control bytes) в начале

3. Control bytes — метаданные для быстрого поиска
   - Каждый байт = 7 бит topHash + 1 бит флага
   - Флаги:
     • 0b10000000 → EMPTY (слот пуст)
     • 0b01111111 → TOMBSTONE (слот удалён)
     • Любое другое → FULL (слот занят)

СТРУКТУРА ГРУППЫ В ПАМЯТИ:

+-----------------------------+
| Control bytes (8 байт)      |
+-----------------------------+
| Key 0                       |
| Key 1                       |
| ...                         |
| Key 7                       |
+-----------------------------+
| Value 0                     |
| Value 1                     |
| ...                         |
| Value 7                     |
+-----------------------------+

ПОЧЕМУ ЭТО ЭФФЕКТИВНЕЕ?
- Все данные последовательны в памяти → лучше локальность кэша
- Control bytes выровнены → CPU может сравнить 8 байт за одну инструкцию
- Нет прыжков по памяти → нет cache misses
*/

// 3. КАК РАБОТАЕТ ПОИСК КЛЮЧА?

/*
АЛГОРИТМ ПОИСКА В SWISS TABLE:

1. Вычисляется хеш ключа → получаем full hash
2. Из full hash берётся:
   - topHash (старшие 7 бит) → для быстрого сравнения
   - group index = hash & (2^B - 1) → номер первой группы

3. Поиск в группе:
   - Сравниваем topHash с 8 control bytes
   - Если совпадение → проверяем реальный ключ (на случай коллизии)

4. При коллизии — **линейное пробирование по группам**:
   - Переходим к следующей группе (group + 1)
   - Повторяем поиск, пока не найдём ключ или пустой слот

ПРИМЕР:
- Ищем ключ "user123"
- Хеш → group 42
- Сравниваем 8 control bytes → нашли совпадение в слоте 3
- Проверили ключ → совпадает! Возвращаем значение

ПОЧЕМУ БЫСТРЕЕ?
- В 95% случаев поиск завершается в одной группе
- Вся группа помещается в одну cache line (64 байта)
- Нет выделения памяти, нет цепочек
*/

// 4. РОСТ МАПЫ

/*
РОСТ ПРОИСХОДИТ ПОСТЕПЕННО:

1. Когда load factor превышает ~81% (6.5/8), мапа решает расти.
2. Количество групп удваивается (2^B → 2^(B+1)).
3. Элементы мигрируют лениво: только при чтении/записи.
4. Это исключает резкие паузы и делает поведение предсказуемым.

РЕКОМЕНДАЦИЯ:
- Всегда используй `make(map[K]V, size)` с правильной ёмкостью,
  чтобы минимизировать количество операций роста.
*/

// 5. ТРЕБОВАНИЯ К КЛЮЧАМ И ПОВЕДЕНИЕ

/*
ТРЕБОВАНИЯ К КЛЮЧАМ:
- Ключ должен быть comparable (==, != работают)
- Нельзя использовать: slice, map, func как ключи

ПОВЕДЕНИЕ МАПЫ В GO 1.24:
- Неупорядочена — порядок итерации случаен
- Не потокобезопасна — нужен mutex или sync.Map
- nil-мапа → паника при записи
*/

func demonstrateMapBasics() {
	// Валидная мапа
	m := make(map[string]int)
	m["key"] = 42

	// Невалидный ключ — ошибка компиляции
	// m2 := map[[]string]int{} // запрещено

	// Nil-мапа — паника
	// var m3 map[string]int
	// m3["key"] = 1 // panic: assignment to entry in nil map
}

// 6. ПОДВОДНЫЕ КАМНИ

/*
1. Удаление не освобождает память
   - После `delete(m, key)` слот помечается как TOMBSTONE
   - Чтобы сбросить — создай новую мапу: `m = make(map[K]V)`

2. Итерация неупорядочена
   - Порядок зависит от хеша и расположения в группах
   - Никогда не полагайся на порядок!

3. Нельзя брать адрес элемента мапы
   - `&m["key"]` — ошибка компиляции
   - Потому что элемент может переместиться при росте мапы
*/

// 7. ПРАКТИЧЕСКИЙ ПРИМЕР

func demonstrateSwissTableInAction() {
	m := make(map[int]string, 1000)
	// Заполнение
	for i := 0; i < 1000; i++ {
		m[i] = fmt.Sprintf("value_%d", i)
	}

	// Чтение — теперь быстрее благодаря локальности кэша
	for i := 0; i < 1000; i++ {
		_ = m[i]
	}

	// Размер заголовка мапы (не включает данные!)
	fmt.Printf("Size of map header: %d bytes\n", unsafe.Sizeof(m))
}

