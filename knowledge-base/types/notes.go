package main

import (
	"fmt"
	"unsafe"
)

/*
### uintptr: УКАЗАТЕЛЬ КАК ЧИСЛО

• Что это: Беззнаковое целое число, достаточно большое, чтобы хранить адрес памяти.
• Размер: Зависит от архитектуры — 4 байта на 32-битных системах, 8 байт на 64-битных.
• Не является указателем! Это просто число, которое *может* представлять адрес.

ЗАЧЕМ НУЖЕН?
- Работа с низкоуровневой памятью (через пакет `unsafe`)
- Взаимодействие с C-кодом (cgo)
- Системное программирование (драйверы, рантайм)

ВАЖНО:
- Нельзя разыменовать `uintptr` напрямую (в отличие от `*T`)
- Использование `unsafe.Pointer` + `uintptr` обходит правила безопасности Go
- Такой код НЕПОРТИРУЕМ и может сломаться при сборке мусора!

Пример:
*/

func demonstrateUintptr() {
	x := 34
	// Получаем указатель
	ptr := &x

	// Преобразуем указатель в uintptr (адрес как число)
	addr := uintptr(unsafe.Pointer(ptr))
	fmt.Printf("Адрес x в виде числа: %d (0x%x)\n", addr, addr)

	backPtr := (*int)(unsafe.Pointer(addr))
	fmt.Printf("Значение по восстановленному указателю: %d\n", *backPtr)

	// Проверка размера
	fmt.Printf("Размер uintptr: %d байт\n", unsafe.Sizeof(addr)) // 8 на 64-битной машине

}

/*
### НЕИЗМЕНЯЕМЫЕ ТИПЫ (IMMUTABLE TYPES)

• Что это: Тип, значение которого **нельзя изменить после создания**.
• Зачем нужно: Безопасность, предсказуемость, потокобезопасность (concurrency-safe).
• Как в Go: Через **контроль конструктора** + использование неизменяемых базовых типов (например, string).

ОСОБЕННОСТИ:
- В Go нет ключевого слова `const` для значений времени выполнения → иммутабельность достигается через дизайн.
- `string` сам по себе неизменяем → идеальная основа для immutable-типов.
- Все изменения требуют **создания нового значения**, а не модификации старого.

ПРИМЕР: Неизменяемый UserID
*/
type UserID string

// NewUserID — единственный способ создать валидный UserID
func NewUserID(id string) UserID {
	if id == "" {
		panic("UserID cannot be empty")
	}
	// Можно добавить валидацию: только латиница, длина и т.д.
	return UserID(id)
}

// String() — безопасный способ "прочитать" значение
func (u UserID) String() string {
	return string(u)
}

// ❌ НЕЛЬЗЯ:
// - Изменить содержимое: u[0] = 'X' → ошибка (строки immutable!)
// - Присвоить строку напрямую без NewUserID (если функция ожидает UserID)
// - Создать пустой UserID (если NewUserID запрещает это)

func demonstrateImmutability() {
	id := NewUserID("user_123")
	fmt.Println("ID:", id.String())

	// Попытка изменить — невозможна:
	// id[0] = 'A' // ← compile error: cannot assign to id[0]

	// Единственный легальный способ — создать новый:
	newID := NewUserID("user_456")
	fmt.Println("New ID:", newID.String())
}

func main() {
	demonstrateUintptr()
}
