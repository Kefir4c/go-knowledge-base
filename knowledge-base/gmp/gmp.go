// 2. МЕХАНИКА GMP И ИНСТРУМЕНТЫ СИНХРОНИЗАЦИИ
/*
ТЕОРЕТИЧЕСКАЯ СПРАВКА:

1. РОЛЬ GMP В РЕСУРСАХ:
   - Аллокация памяти: gmp тесно связан с tcmalloc (аллокатором Go). Каждому p
     выделяется свой кэш памяти (mcache), чтобы горутины могли хватать память
     без глобальных блокировок.
   - Планирование: p (processor) решает, какую g запустить следующей, используя
     локальную очередь (LRQ), что сохраняет данные в L1/L2 кэшах процессора.

2. СРЕДСТВА СИНХРОНИЗАЦИИ:
   - Mutex (sync.Mutex): Блокировка "в лоб". Используем для коротких операций
     внутри одной структуры (обновить счетчик, записать в мапу).
   - Channels: Передача владения. Если логика сложная и многоступенчатая — каналы лучше.
   - WaitGroup: Ожидание группы горутин.
   - Once (sync.Once): Гарантия выполнения кода ровно один раз (например, синглтон).
*/

// ПРИМЕР 1: Защита данных через мьютекс (sync.Mutex)
/* Если 1000 горутин начнут писать в одну мапу без мьютекса — будет fatal error:
concurrent map writes. Мьютекс делает операцию атомарной для других горутин.
*/
func exampleMutexUsage() {
	var (
		mu sync.Mutex
		wg sync.WaitGroup
	)
	cache := make(map[int]int)

	for i := 0; i < 100000; i++ {
		wg.Add(1)
		go func(n int) {
			defer wg.Done()
			mu.Lock()
			cache[n] = n * 10
			mu.Unlock()
		}(i)
	}
	wg.Wait()
	fmt.Println("Мапа успешно заполнена, размер:", len(cache))
}

// ПРИМЕР 2: Чтение и запись (sync.RWMutex)
/* Когда читателей много, а писателей мало, обычный Mutex тормозит систему.
RWMutex позволяет одновременно читать многим горутинам, но блокирует всех для записи.
*/
func exampleRWMutex() {
	var (
		rw   sync.RWMutex
		data int
	)

	// Горутины-читатели (могут работать одновременно)
	for i := 0; i < 5; i++ {
		go func() {
			rw.RLock()
			_ = data
			rw.Unlock()
		}()
	}

	rw.Lock()
	data = 42
	rw.Unlock()
}

// ПРИМЕР 3: Синхронизация через каналы (Передача владения)
/* Вместо того чтобы делить память через мьютекс, мы передаем данные.
Тот, кто получил данные из канала, становится их временным "хозяином".
*/
func exampleChannelSync() {
	signal := make(chan struct{}) // Пустая структура не занимает памяти

	go func() {
		fmt.Println("Горутина: выполняю работу...")
		time.Sleep(100 * time.Millisecond)
		close(signal)
	}()

	<-signal // Ждем сигнала завершения
	fmt.Println("Main: работа закончена, идем дальше")
}

// ПРИМЕР 4: Атомарные операции (sync/atomic)
/* Для простых чисел atomic быстрее мьютекса, так как работает на уровне
инструкций процессора без участия планировщика Go.
*/
func exampleAtomic() {
	var counter int64
	var wg sync.WaitGroup

	for i := 0; i < 1000; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			atomic.AddInt64(&counter, 1) // Безопасный инкремент
		}()
	}
	wg.Wait()
	fmt.Println("Результат atomic:", atomic.LoadInt64(&counter))
}

// ПРИМЕР 6: Ленивая инициализация (sync.Once)
/* Полезно для создания подключения к БД или логгеру,
чтобы гарантировать: код выполнится 1 раз, сколько бы горутин его ни вызвали.
*/
func exampleOnce() {
	var once sync.Once
	initialize := func() {
		fmt.Println("Инициализация выполнена!")
	}

	for i := 0; i < 10; i++ {
		go func() {
			once.Do(initialize) // Выполнится только при первом вызове
		}()
	}
	time.Sleep(50 * time.Millisecond)
}

