// ПРИМЕР 7: Анализ через Runtime Trace (Визуализация работы GMP)
/* Зачем это нужно: pprof показывает "КТО" ест ресурсы, а trace показывает "КОГДА" и "ПОЧЕМУ".
Он визуализирует блокировки, кражу работы (Work Stealing) и паузы мусорщика (STW).
*/
func exampleTrace() {
	// 1. Создаем файл для записи трассировки
	f, err := os.Create("app.trace")
	if err != nil {
		log.Fatalf("не удалось создать файл: %v", err)
	}
	defer f.Close()

	// 2. Запускаем сбор данных планировщика
	if err := trace.Start(f); err != nil {
		log.Fatalf("не удалось запустить трейс: %v", err)
	}
	// Останавливаем сбор в конце функции
	defer trace.Stop()

	// 3. Имитируем сложную многозадачную работу
	var wg sync.WaitGroup
	for i := 0; i < 10; i++ {
		wg.Add(1)
		go func(id int) {
			defer wg.Done()
			// Интенсивные вычисления и работа с каналами
			sum := 0
			for j := 0; j < 1000000; j++ {
				sum += j
			}
			time.Sleep(10 * time.Millisecond)
			fmt.Printf("Воркер %d закончил\n", id)
		}(i)
	}
	wg.Wait()

	fmt.Println("Данные записаны в app.trace")
	fmt.Println("Для анализа введи команду: go tool trace app.trace")
}

// 4. ЭКСПЕРТНЫЙ GMP: СТРАТЕГИИ, ДЕДЛОКИ И HIGH-PERFORMANCE (GRADE 4 - ARCHITECT)
/*
ТЕОРЕТИЧЕСКАЯ СПРАВКА:

1. СТРАТЕГИИ ПЛАНИРОВАНИЯ (Stealing vs Spinning):
   - Spinning Threads: Чтобы не тратить время на "просыпание" потока от ОС (это долго),
     Go держит некоторые m в состоянии "вращения" (spinning). Они активно ищут g
     в очередях, потребляя немного CPU, но гарантируя мгновенный подхват задачи.
   - Affinity (Сродство): Планировщик старается запустить g на том же p, где она
     была раньше, чтобы не вымывать L1/L2 кэши процессора.

2. ДЕДЛОКИ (Deadlocks) И ИХ ВИДЫ:
   - Глобальный дедлок: Все g спят, никто не может разбудить — рантайм это видит и падает.
   - Локальный дедлок (Leak): Группа g зависла, но остальные работают. Рантайм это НЕ видит.

3. LOCK-FREE АЛГОРИТМЫ:
   - Использование atomic вместо Mutex там, где это возможно. Это исключает саму
     возможность дедлока, так как нет захвата ресурса.
*/

// ПРИМЕР 1: Асинхронное вытеснение (Async Preemption)
/* Как это работает: До Go 1.14 планировщик ждал, пока горутина сама вызовет функцию (точку планирования).
Если был цикл for { i++ }, поток зависал.
Теперь рантайм посылает потоку m сигнал ОС (SIGURG). Обработчик сигнала видит:
"так, эта g работает больше 10мс", сохраняет её состояние и принудительно отдает поток другой g.
*/

func exampleAsyncPreemption() {
	// Создаем "жадную" горутину, которая не делает системных вызовов
	go func() {
		fmt.Println("Жадная горутина запущена на одном из P")
		var i uint64
		for {
			i++ // Чистый цикл, нет точек планирования
		}
	}()

	// Если бы не асинхронное вытеснение, эта горутина никогда бы не получила время
	go func() {
		for i := 0; i < 5; i++ {
			time.Sleep(10 * time.Millisecond)
			fmt.Println("Вторая горутина: я всё еще получаю время CPU!")
		}
	}()

	time.Sleep(100 * time.Millisecond)
}

// ПРИМЕР 2: Выравнивание кэша и False Sharing (Оптимизация под CPU)
/* Как это работает: Процессор читает память не по байту, а "линиями" по 64 байта.
Если две разные горутины на разных ядрах меняют две переменные, лежащие в одной линии,
процессору приходится постоянно синхронизировать кэши ядер. Это дико тормозит систему.
Мы добавляем "пустышку" (padding), чтобы разнести переменные по разным линиям.
*/
func exampleCacheAlignment() {
	// Плохая структура: a и b попадут в одну кэш-линию
	type badCounter struct {
		a uint64 // 8 байт
		b uint64 // 8 байт
	}

	// Хорошая структура: между a и b "пропасть" в 56 байт
	type goodCounter struct {
		a uint64
		_ [56]byte // Паддинг до размера 64 байта (размер кэш-линии)
		b uint64
	}

	var gc goodCounter
	fmt.Printf("Размер оптимизированной структуры: %d байт\n", unsafe.Sizeof(gc))
	fmt.Printf("Адрес A: %p, Адрес B: %p (разница 64 байта)\n", &gc.a, &gc.b)
}

// ПРИМЕР 4: Высокопроизводительный Lock-Free стек на Atomic
/* Вместо мьютекса используем CAS (Compare-And-Swap).
Никаких блокировок, только чистые инструкции процессора.
*/
func exampleLockFree() {
	var head unsafe.Pointer // Указатель на верхушку стека

	type node struct {
		value int
		next  unsafe.Pointer
	}

	push := func(v int) {
		n := &node{value: v}
		for {
			old := atomic.LoadPointer(&head)
			n.next = old
			// Пытаемся заменить head на новый узел, если head не изменился
			if atomic.CompareAndSwapPointer(&head, old, unsafe.Pointer(n)) {
				return
			}
			// Если не вышло (другая G успела раньше) — идем на новый круг
		}
	}

	go push(10)
	go push(20)
}

// ПРИМЕР 3: Сторожевой таймер для утечек (Leak Watchdog)
/* Как это работает: В проде нельзя просто "надеяться", что горутины завершатся.
Нужно мониторить их количество. Если график NumGoroutine постоянно ползет вверх
без падений — у тебя утечка (например, забыл закрыть канал или тело HTTP-ответа).
*/
func exampleLeakWatchdog() {
	// Имитируем утечку: горутина зависла на чтении из пустого канала
	go func() {
		leakChan := make(chan int)
		for i := 0; i < 10; i++ {
			go func() { <-leakChan }() // Эти горутины никогда не умрут
		}
	}()

	// Watchdog: в реальном приложении это отправляет метрики в Prometheus
	ticker := time.NewTicker(500 * time.Millisecond)
	go func() {
		for range ticker.C {
			count := runtime.NumGoroutine()
			fmt.Printf("[WATCHDOG] Текущее кол-во горутин: %d\n", count)
			if count > 15 {
				fmt.Println("!!! КРИТИЧЕСКАЯ УТЕЧКА: Горутин слишком много !!!")
			}
		}
	}()

	time.Sleep(2 * time.Second)
	ticker.Stop()
}

// ПРИМЕР 4: Тюнинг GOMAXPROCS (Параллельность в облаке)
/* Как это работает: В Kubernetes часто ограничивают CPU (например, 0.5 ядра).
Но runtime.NumCPU() вернет количество ядер ВСЕЙ ноды (например, 64).
В итоге Go создаст 64 потока (P), которые будут драться за 0.5 ядра, вызывая тормоза.
Библиотека "automaxprocs" от Uber решает это, подстраивая P под лимиты контейнера.
*/
func exampleTuning() {
	// Ручной тюнинг:
	// Если у нас I/O-bound приложение (много запросов в сеть),
	// иногда выгодно поставить P чуть больше ядер, чтобы быстрее переключаться.
	cores := runtime.NumCPU()
	runtime.GOMAXPROCS(cores * 2)

	fmt.Printf("Ядер на борту: %d. Установлено P: %d\n", cores, runtime.GOMAXPROCS(0))
}

// ПРИМЕР 5: Профилирование блокировок (Block Profile)
/* Как это работает: CPU профиль покажет, где мы работаем. Block профиль покажет,
где мы КУРИМ и ЖДЕМ. Если одна горутина держит Mutex слишком долго,
остальные 100 горутин будут в состоянии "blocked".
*/
func exampleBlockProfile() {
	// 1. Включаем сбор данных о блокировках (фиксируем 1 из 1 событий)
	runtime.SetBlockProfileRate(1)

	var mu sync.Mutex
	// 2. Создаем "узкое горлышко"
	go func() {
		for {
			mu.Lock()
			time.Sleep(100 * time.Millisecond) // Захватили и спим
			mu.Unlock()
			time.Sleep(10 * time.Millisecond)
		}
	}()

	// 3. Толпа горутин, которые будут страдать
	for i := 0; i < 5; i++ {
		go func(id int) {
			for {
				mu.Lock()
				_ = id
				mu.Unlock()
			}
		}(i)
	}

	fmt.Println("Запусти сервер pprof и посмотри /debug/pprof/block")
	fmt.Println("Там будет видно, что горутины тратят 90% времени на ожидание этого мьютекса")
}
