package gmp

/*
NOTES (Block 1):

1. M:N планирование: Многие (N) горутины работают на нескольких (M) потоках ОС.
2. User Space (Пространство пользователя): Go сам решает, когда остановить
   горутину, не спрашивая Windows или Linux. Это экономит кучу ресурсов.
3. Кооперативность: Раньше горутина должна была сама "отдать" управление
   (например, при вызове функции), но сейчас Go умеет прерывать их
   принудительно (вытеснение/preemption).
4. Зачем нужен P?: Это прослойка для эффективного распределения задач.
   Если бы M брали задачи из одной очереди, они бы постоянно блокировали
   друг друга (lock contention). P дает каждому потоку свою локальную очередь.
*/

/*
NOTES (Block 2):

1. Выбор: Если нужно защитить данные внутри структуры — бери Mutex.
   Если нужно координировать работу разных частей программы — бери Channel.
2. Копирование мьютекса: НИКОГДА не передавай структуру с мьютексом по значению
   `func(s MyStruct)`. Мьютекс скопируется в заблокированном/разблокированном
   состоянии, и ты получишь дедлок. Передавай только по указателю.
3. p (Processor) и память: Каждый p имеет свой кэш аллокации. Это минимизирует
   борьбу за общую кучу (heap) между ядрами процессора.
4. Велосипеды: Не изобретай свои способы синхронизации на флагах или циклах `for {}`.
   Стандартные пакеты sync и atomic отлажены и работают быстрее.
*/

/*
NOTES (Block 3):

1. Избегай утечек (Leaks): Горутина, которая заблокирована на чтении из канала,
   в который никто не пишет — это утечка памяти. Она никогда не завершится.
2. GC Pacing: Мусорщик (GC) запускается чаще, когда куча растет быстро.
   Снижая аллокации через sync.Pool, ты делаешь паузы GC короче.
3. Локальность: Планировщик старается запускать горутину на том же ядре,
   где она работала раньше, чтобы данные оставались в кэше CPU.
4. Инструментарий: Всегда начинай оптимизацию с pprof. Не гадай, где тормозит —
   смотри графики.
*/

/*
NOTES (Block 4):

1. False Sharing: Всегда помни про кэш-линии процессора. Масштабируемость падает,
   если ядра постоянно "дергают" одну и ту же область памяти.
2. Order of Locks: Если в системе больше одного мьютекса, определи и задокументируй
   порядок их захвата (Hierarchy), чтобы избежать дедлоков.
3. Network Poller: Помни, что Go не блокирует поток m на сетевом вводе-выводе.
   g просто переходит в состояние ожидания, а m берет другую задачу.
4. Finalizers: Используй runtime.SetFinalizer осторожно для очистки не-Go ресурсов
   (например, дескрипторов файлов из C-кода).
*/
