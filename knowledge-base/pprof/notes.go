package pprof

/*
NOTES (BLOCK 1):

1. pprof встроен в go. runtime/pprof для cli, net/http/pprof для http сервисов.

2. cpu профиль сэмплирует стеки каждые 10ms. снимай под нагрузкой, иначе бесполезен.

3. heap профиль показывает живые объекты. перед записью вызови runtime.GC().

4. goroutine профиль показывает стеки всех горутин и их статусы (waiting, running).

5. allocs показывает все аллокации (включая временные) — помогает снизить нагрузку на gc.

6. профиль без нагрузки не имеет смысла — всегда снимай под реальным сценарием.

7. не держи cpu профиль включённым в проде постоянно — он жрёт 5-10% cpu.

8. основные профили: cpu, heap, goroutine, allocs, block, mutex.
*/

/*
NOTES (BLOCK 2):

1. net/http/pprof подключается одной строкой: import _ "net/http/pprof".
   автоматически регистрирует эндпоинты на /debug/pprof/.

2. cpu профиль через http: go tool pprof localhost:6060/debug/pprof/cpu?seconds=30.
   без параметра seconds профиль будет пустым.

3. heap профиль: go tool pprof localhost:6060/debug/pprof/heap.
   полезные флаги: -inuse_space (живая память), -alloc_space (все аллокации).

4. веб-интерфейс: go tool pprof -http=:8081 profile.prof.
   вкладки: top, graph, flame, source — очень удобно для анализа.

5. сравнение профилей: go tool pprof -base before.prof after.prof.
   показывает разницу: что утекло или что замедлилось.

6. для прода: pprof лучше вешать на отдельный порт, не на основной.
   чтобы профилирование не влияло на бизнес-трафик.

7. при панике можно снять профиль через recover и понять причину.
   особенно полезно для heap и goroutine профилей.

8. в проде не держи cpu профиль включённым постоянно — он жрёт 5-10% cpu.
   включай только на время снятия профиля.
*/
