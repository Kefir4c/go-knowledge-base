// 1. ЧТО ТАКОЕ СТРУКТУРЫ?
/*
ЧТО ЭТО:
- Структура — это **composite type**, объединяющий несколько полей в один тип.
- Аналог классов в ООП, но без наследования и методов по умолчанию.

ПОЧЕМУ ЭТО ВАЖНО:
- Структуры — основной способ создания пользовательских типов в Go.
- Позволяют группировать связанные данные и добавлять методы.

ПРИМЕР БАЗОВОГО ИСПОЛЬЗОВАНИЯ:
*/
type User struct {
	Name string
	Age  int
}

func demStatreBasicStruct() {
	u1 := User{Name: "ivan", Age: 18}

	u2 := new(User)
	u2.Name = "Petr"
	u2.Age = 32

	fmt.Printf("user: %s, %d years old\n", u1.Name, u1.Age)
	fmt.Printf("user: %s, %d years old\n", u2.Name, u2.Age)
}

// 2. ВСТРАИВАНИЕ, РЕСИВЕРЫ И ПРИВАТНЫЕ ПОЛЯ В GO
/*
ВСТРАИВАНИЕ (EMBEDDING):
- Встраивание позволяет включить одну структуру в другую без наследования.
- Встраиваемая структура становится полем без имени в родительской структуре.

ПОЧЕМУ ЭТО ВАЖНО:
- Go предпочитает композицию вместо наследования.
- Позволяет переиспользовать функциональность без дублирования кода.
- Создаёт иерархию объектов, которая легко масштабируется.
*/
type Address struct {
	City    string
	Country string
}

type Person struct {
	Name    string
	Age     int
	Address // Встраивание структуры Address
}

func demEvbeddibg() {
	p := Person{
		Name: "Oleg",
		Age:  18,
		Address: Address{
			City:    "Mosckow",
			Country: "Russia",
		},
	}
	fmt.Printf("Person: %s, %d years old, from %s, %s\n",
		p.Name, p.Age, p.City, p.Country)
}

/*
КАК ЭТО РАБОТАЕТ:
- При встраивании структура Address становится частью Person
- Поля City и Country становятся доступными через Person
- Это не наследование, а композиция — структура Person содержит структуру Address

ВАЖНОЕ ПРИМЕЧАНИЕ:
- Если две структуры имеют поля с одинаковыми именами, доступ может быть неоднозначным

КОНФЛИКТЫ ИМЕН И НЕОДНОЗНАЧНЫЙ ДОСТУП
ПРИМЕР КОНФЛИКТА ИМЕН:
*/
type A struct {
	Value int
}

type B struct {
	Value int
}

type C struct {
	A
	B
}

func demNameConfig() {
	c := C{}
	c.A.Value = 1
	c.B.Value = 2

	// c.Value = 3 // ОШИБКА: неоднозначный доступ к Value
	// Нужно явно указать, какую структуру использовать
	fmt.Println("A.Value:", c.A.Value)
	fmt.Println("B.Value:", c.B.Value)
}

/*
КАК РЕШАТЬ КОНФЛИКТЫ:
1. Использовать явные имена для полей
2. Избегать встраивания структур с одинаковыми полями
3. Использовать методы доступа вместо прямого доступа к полям
*/

/*
РЕСИВЕР (RECEIVER):
ЧТО ЭТО:
- Ресивер — это специальный параметр, который связывает метод с конкретным типом.
- Синтаксис: `func (r ReceiverType) MethodName() {}`

ПОЧЕМУ ЭТО ВАЖНО:
- Позволяет добавлять методы к любому типу (даже встроенным).
- Создаёт ООП-подобное поведение без наследования.
ПРИМЕР БАЗОВОГО РЕСИВЕРА:
*/
type User struct {
	Name string
	Age  int
}

func (u User) Greet() string {
	return "Привет" + u.Name
}

func (u User) SetAge(age int) (age int) {
	u.Age = age
}

