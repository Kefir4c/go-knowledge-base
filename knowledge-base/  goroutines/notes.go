package __goroutines

/*
NOTES (block 1):

1. Что внутри структуры G:
   В исходниках Go (runtime/runtime2.go) горутина — это структура `g`.
   В ней хранятся: указатель на стек, состояние (статус), контекст выполнения (registers).

2. Почему стек растет?
   Изначально 2КБ. Если функция вызывает много подфункций и места мало,
   вызывается runtime.morestack, который выделяет новый кусок памяти в 2 раза больше
   и переносит туда данные. Это называется Stack Segmenting (раньше) или Stack Copying (сейчас).

3. Нельзя убить горутину:
   В Go нет метода `goroutine.Kill()`. Это сделано специально.
   Чтобы остановить горутину, ты должен сам предусмотреть механизм:
   через канал или context.

4. Блокировки:
   Если горутина блокируется (например, делает сетевой запрос), планировщик
   Go понимает это и переключает поток ОС (M) на другую горутину.

5. Замыкание
   При работе с замыканиями и горутинами важно соблюдать осторожность, особенно
   при захвате переменных в циклах и при одновременном доступе к общим данным,
   чтобы избежать ошибок и проблем с производительностью.
*/

/*
NOTES (block 2):

1. Work Stealing: Если одно ядро (P) закончило свои задачи, оно "крадет"
   половину горутин из очереди другого ядра. Это база балансировки в Go.

2. Вытеснение (Preemption): До версии 1.14 горутина в бесконечном цикле
   `for {}` могла повесить поток навсегда. Сейчас планировщик умеет
   прерывать их принудительно (через сигналы).

3. Выбор между Mutex и Channel:
   - Если это внутреннее состояние объекта (кэш, счетчик) — Mutex.
   - Если это координация, передача данных или тайм-ауты — Channel.

4. Не копируй Mutex: Если передать структуру с Mutex по значению,
   скопируется его текущее состояние (заблокирован/разблокирован),
   что приведет к дедлоку. Только указатели!
*/

/*
NOTES (block 3):

1. errgroup vs WaitGroup: Забудь про WaitGroup, если тебе нужно обрабатывать ошибки.
   errgroup делает это из коробки и умеет в контексты.

2. Направление каналов: Всегда пиши `chan<-` или `<-chan` в параметрах функций.
   Это документация кода, которая проверяется компилятором.

3. Паника — это смерть: recover() работает только в той горутине, где был вызван.
   Если ты запустил 10 горутин, и одна паникует без recover — весь сервис ложится.

4. Замыкания в циклах: В Go 1.22+ проблема с `i := i` решена на уровне компилятора,
   но на старых версиях (или если ты передаешь указатель) всё еще можно выстрелить в ногу.
*/

/*
NOTES (block 4):

1. PPROF ЭНДПОИНТЫ:
   - /debug/pprof/goroutine?debug=2 — вывалит полный stack trace всех G.
   - /debug/pprof/heap — анализ аллокаций.
   - /debug/pprof/profile — CPU профиль (30 секунд).

2. ПЛАНИРОВЩИК И CACHE LOCALITY:
   - Локальные очереди (LRQ) у каждого P нужны, чтобы избежать глобальной
     блокировки (Lock Contention) при выборе следующей задачи.
     Это позволяет эффективно использовать L1/L2 кэши процессора.

3. BALLAST (ДО GO 1.19):
   - Раньше создавали огромный слайс (`make([]byte, 10<<30)`), чтобы
     обмануть GC и заставить его работать реже. В новых версиях лучше
     использовать GOMEMLIMIT.

4. СТАТУСЫ ГОРУТИН:
   - _Gidle, _Grunnable (ждет P), _Grunning (на M), _Gsyscall, _Gwaiting.
     Понимание этих статусов критично при чтении дампов pprof.
*/
