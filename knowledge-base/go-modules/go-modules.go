package gomodules

// 1. GO MODULES: СОЗДАНИЕ И СМЫСЛ
/*
ТЕОРЕТИЧЕСКАЯ СПРАВКА:

1. ЗАЧЕМ НУЖНО УПРАВЛЕНИЕ ЗАВИСИМОСТЯМИ?
   Представь, что твой проект зависит от библиотеки "A". Библиотека "A" обновилась
   и удалила функцию, которую ты использовал. Без модулей твой проект просто
   перестанет собираться. Модули фиксируют конкретную версию кода, гарантируя
   воспроизводимость сборки (Reproducible Builds) — проект соберется одинаково
   и у тебя, и у коллеги, и на сервере через 5 лет.

2. ЧТО ТАКОЕ МОДУЛЬ?
   Это коллекция пакетов Go, которые выпускаются вместе. Файл go.mod в корне
   проекта определяет путь к модулю и его зависимости.

3. КОМАНДА `go mod init`:
   Создает новый файл go.mod. Путь модуля обычно совпадает с адресом репозитория
   (например, github.com/username/project).
*/

// ПРИМЕР 1: Создание модуля в пустой папке
/*
$ mkdir my-awesome-app
$ cd my-awesome-app
$ go mod init github.com/user/my-awesome-app

Результат (файл go.mod):
module github.com/user/my-awesome-app

go 1.23.0  <- Версия Go, установленная в системе
*/

// ПРИМЕР 2: Структура go.mod после добавления первой зависимости
/*
После выполнения команды `go get github.com/google/uuid` файл изменится:

module github.com/user/my-awesome-app

go 1.23.0

require github.com/google/uuid v1.6.0  <- Четкая версия
*/

// ПРИМЕР 3: Инициализация модуля для локальной разработки
/*
Если ты не планируешь выкладывать код в сеть (просто учишься),
можно назваться просто:
$ go mod init my-local-test

Cтандарт индустрии используют полный путь (github.com/...),
*/

// ПРИМЕР 4: Команда `go mod tidy` (Самая частая команда)
/*
Представь, что ты написал в коде: import "github.com/sirupsen/logrus".
Но ты его не скачивал.
Команда:
$ go mod tidy

Она просканирует код, скачает нужные модули, пропишет их в go.mod
и удалит те, которые ты больше не используешь.
*/

// ПРИМЕР 5: Проверка модуля `go mod verify`
/*
Команда проверяет, что скачанные зависимости в твоем кэше
совпадают с контрольными суммами в go.sum. Это защита от того,
что кто-то изменил код библиотеки после того, как ты её скачал.
$ go mod verify
all modules verified
*/

// 2. УПРАВЛЕНИЕ ЗАВИСИМОСТЯМИ И CLI (GRADE 2)
/*
ТЕОРЕТИЧЕСКАЯ СПРАВКА:

1. СТРУКТУРА GO.MOD:
   - require: список зависимостей. Если стоит // indirect — значит, твой код
     не импортирует этот пакет напрямую, но он нужен одной из твоих библиотек.
   - exclude: запрещает использовать конкретную версию библиотеки (если там баг).
   - replace: подменяет один модуль другим (полезно для локальной правки либ).

2. КОМАНДА GO GET:
   Это не просто "скачать". Она обновляет go.mod.
   - go get path@v1.2.3 (конкретная версия)
   - go get path@latest (последняя стабильная)
   - go get path@master (последний коммит из ветки)

3. ВТОРОСТЕПЕННЫЕ, НО ВАЖНЫЕ КОМАНДЫ:
   - go list -m all: показывает все зависимости, которые сейчас участвуют в сборке.
   - go mod graph: строит дерево (кто от кого зависит).
*/

