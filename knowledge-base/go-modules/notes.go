package gomodules

/*
NOTES (block 1):

1. Module Path: Это не просто имя, это префикс для всех внутренних импортов.
   Если модуль называется `github.com/me/app`, то пакет `auth` внутри
   будет импортироваться как `import "github.com/me/app/internal/auth"`.

2. go.mod vs go.sum:
   go.mod — это список "покупок" (что нам нужно).
   go.sum — это "чек" с уникальными подписями (гарантия, что привезли именно то).

3. Эволюция: До Go 1.11 мы жили в $GOPATH. Модули убили зависимость от
   конкретного расположения папок. Теперь проект может лежать на рабочем столе.

4. Запуск без init: Если ты попробуешь запустить `go run main.go` в папке
   без go.mod (и вне $GOPATH), Go выдаст ошибку: "go: go.mod file not found".
*/

/*
NOTES (block 2):

1. "Что произойдет, если удалить go.sum?"
   Ответ: При следующей сборке или `go mod tidy` Go создаст его заново,
   скачав модули. Но это небезопасно, так как мы теряем гарантию, что
   код библиотек не был изменен (Man-in-the-Middle).

2. "Чем `go get` отличается от `go install`?"
   Ответ: `go get` добавляет зависимость в проект (меняет go.mod).
   `go install` компилирует и устанавливает исполняемый файл (бинарник)
   в $GOPATH/bin, не меняя текущий проект.

3. "Зачем нужен // indirect?"
   Ответ: Чтобы `go.mod` был полным снимком всех зависимостей.
   Если зависимость транзитивная (через другую либу) и её версия не зафиксирована
   в `go.mod` другого модуля, Go выносит её в основной файл.

4. "Что делать, если библиотека переехала на новый URL?"
   Ответ: Использовать директиву `replace` в go.mod, чтобы временно
   перенаправить старый путь на новый.
*/

/*
NOTES (block 3):

1. "Почему Go выбирает минимальную версию (MVS)?"
   Ответ: Чтобы избежать неожиданных поломок от "слишком новых" версий.
   Это дает предсказуемость: если ты указал v1.2.0, Go не обновит её до v1.3.0
   сам по себе, пока ты не попросишь.

2. "Зачем нужен GOPRIVATE?"
   Ответ: Без него Go Proxy попытается скачать твой приватный код,
   получит ошибку 404, а SumDB не сможет проверить хеш, так как у него
   нет доступа к твоему репозиторию.

3. "В чем минус папки vendor?"
   Ответ: Она сильно раздувает размер репозитория (Git становится тяжелым).
   В современном мире с надежными прокси (типа Athens) вендоринг используют
   реже, в основном в финтехе или в жестких закрытых контурах.

4. "Как обновить все зависимости до минорных версий разом?"
   Ответ: go get -u ./...
*/

/*
NOTES (block 4):

1. "Почему добавление метода в интерфейс — это Breaking Change, а в структуру — нет?"
   Ответ: Структура реализует интерфейс неявно. Если мы добавили метод в
   интерфейс, все структуры, которые "обещали" его реализовать, перестают
   ему соответствовать. Это ломает компиляцию кода клиента.

2. "Как работает SumDB (Checksum Database)?"
   Ответ: Это Read-only дерево Меркла, поддерживаемое Google. Оно хранит
   хэши всех версий всех модулей. Это защищает от подмены кода на
   стороне GitHub/GitLab. Если хэш не совпал — Go выдаст "SECURITY ERROR".

3. "Vulnerability Management":
   Используй команду `govulncheck ./...`. Она анализирует твой go.mod и
   код на предмет использования библиотек с известными уязвимостями (CVE).
   Эксперт внедряет это в CI/CD пайплайн.

4. "Что такое Orphaned Dependencies?"
   Ответ: Зависимости, которые остались в go.mod, но не используются в коде.
   Лечится через `go mod tidy`. Оставлять их — значит увеличивать
   размер бинарника и поверхность атаки.
*/
