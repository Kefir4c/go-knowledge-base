package gomodules

/*
NOTES (block 1):

1. Module Path: Это не просто имя, это префикс для всех внутренних импортов.
   Если модуль называется `github.com/me/app`, то пакет `auth` внутри
   будет импортироваться как `import "github.com/me/app/internal/auth"`.

2. go.mod vs go.sum:
   go.mod — это список "покупок" (что нам нужно).
   go.sum — это "чек" с уникальными подписями (гарантия, что привезли именно то).

3. Эволюция: До Go 1.11 мы жили в $GOPATH. Модули убили зависимость от
   конкретного расположения папок. Теперь проект может лежать на рабочем столе.

4. Запуск без init: Если ты попробуешь запустить `go run main.go` в папке
   без go.mod (и вне $GOPATH), Go выдаст ошибку: "go: go.mod file not found".
*/

/*
NOTES (block 2):

1. "Что произойдет, если удалить go.sum?"
   Ответ: При следующей сборке или `go mod tidy` Go создаст его заново,
   скачав модули. Но это небезопасно, так как мы теряем гарантию, что
   код библиотек не был изменен (Man-in-the-Middle).

2. "Чем `go get` отличается от `go install`?"
   Ответ: `go get` добавляет зависимость в проект (меняет go.mod).
   `go install` компилирует и устанавливает исполняемый файл (бинарник)
   в $GOPATH/bin, не меняя текущий проект.

3. "Зачем нужен // indirect?"
   Ответ: Чтобы `go.mod` был полным снимком всех зависимостей.
   Если зависимость транзитивная (через другую либу) и её версия не зафиксирована
   в `go.mod` другого модуля, Go выносит её в основной файл.

4. "Что делать, если библиотека переехала на новый URL?"
   Ответ: Использовать директиву `replace` в go.mod, чтобы временно
   перенаправить старый путь на новый.
*/
