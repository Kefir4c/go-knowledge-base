/*
  УРОК 9.1: ОСНОВЫ DOCKER — ОБРАЗ, КОНТЕЙНЕР, СЛОИ
  "У меня локально работает" — фраза, которая стоила индустрии
  миллиарды долларов. Разные версии go, разные библиотеки,
  разные переменные окружения, разный Linux. Docker решает эту
  проблему раз и навсегда: приложение упаковывается вместе со
  всем своим окружением в неизменяемый артефакт.

  Но прежде чем писать Dockerfile, нужно понять три базовые
  концепции: образ (image), контейнер (container) и слои (layers).
  Без этого Docker превращается в набор магических команд,
  которые "почему-то работают" или "почему-то не работают".

  СОДЕРЖАНИЕ:
    1.  Проблема: почему без Docker — боль
    2.  Образ (Image) — что это
    3.  Контейнер (Container) — что это
    4.  Слои (Layers) — как работает кэш
    5.  Жизненный цикл контейнера
    6.  Основные команды — шпаргалка
    7.  Registry — откуда берутся образы
    8.  Go-специфика: как это применимо к нашим сервисам
    9.  Антипаттерны
    10. Финальные выводы

  1. ПРОБЛЕМА: ПОЧЕМУ БЕЗ DOCKER — БОЛЬ
  Представь классический день разработчика до Docker.

  Ты пишешь Go-сервис. У тебя на ноутбуке macOS с Go 1.22,
  PostgreSQL 16, Redis 7. Всё работает. Ты коммитишь.

  Коллега подтягивает изменения. У него Ubuntu, Go 1.21,
  PostgreSQL 14, Redis 6. Ничего не работает. Он час ставит
  новые версии, ломает существующие проекты, в итоге сносит
  всё и переустанавливает с нуля.

  Девопс деплоит на прод. Там CentOS 7, Go 1.20, PostgreSQL 13.
  Сервис падает при старте, потому что использует фичу из 1.22.

  QA поднимает staging. Там вообще Windows Server. Программа
  не собирается из-за различий в путях.

  Классическая шутка: "работает на моей машине". Реальность:
  работает на МОЕЙ машине, а у вас своя.

  Docker решает это радикально: приложение упаковывается вместе
  со всем своим окружением — ОС, библиотеками, зависимостями,
  переменными — в один неизменяемый артефакт. Этот артефакт
  работает одинаково везде, где есть Docker.
  "Build once, run anywhere."

  2. ОБРАЗ (IMAGE) — ЧТО ЭТО

  2.1. ОПРЕДЕЛЕНИЕ
  Образ — это неизменяемый шаблон (blueprint), из которого
  создаются контейнеры. В ООП это класс. В рецепте — рецепт.
  В чертеже — чертёж.

  Образ содержит:
    • Файловую систему (бинарники, библиотеки, конфиги).
    • Метаданные (какая команда запускать, какой порт слушать).
    • Переменные окружения.
    • Точку входа (entrypoint).

  Образ НЕЛЬЗЯ ИЗМЕНИТЬ. После сборки он заморожен. Хочешь
  что-то поменять — собираешь новый образ.

  2.2. ОТКУДА БЕРУТСЯ ОБРАЗЫ
  Три источника:
    • Скачал из registry (Docker Hub, GHCR, ECR).
    • Собрал сам из Dockerfile.
    • Создал из запущенного контейнера (docker commit — плохая
      практика, но технически возможно).

  2.3. КЛЮЧЕВЫЕ СВОЙСТВА
  ИММУТАБЕЛЬНОСТЬ. Образ — read-only. Если контейнер что-то
  меняет в файловой системе — изменения идут в отдельный слой
  поверх образа. Сам образ остаётся нетронутым.

  ДЕТЕРМИНИРОВАННОСТЬ. Один и тот же образ везде даёт одинаковый
  результат. Это фундамент воспроизводимости.

  ВЕРСИОНИРОВАНИЕ. У образа есть тег (my-app:1.2.3). Тег —
  изменяемая ссылка. Есть digest (sha256:...) — неизменяемый
  хеш. Для прода используй digest, а не тег.

  2.4. СЛОИ ВНУТРИ ОБРАЗА
  Образ — это не монолит. Это стек слоёв. Каждая инструкция
  в Dockerfile (FROM, RUN, COPY, ADD) создаёт новый слой.
  Схема:
    ┌─────────────────────────────┐
    │  Layer 5: COPY . .          │ ← код приложения
    ├─────────────────────────────┤
    │  Layer 4: RUN go build      │ ← скомпилированный бинарник
    ├─────────────────────────────┤
    │  Layer 3: RUN go mod download│ ← зависимости
    ├─────────────────────────────┤
    │  Layer 2: COPY go.mod       │ ← манифесты
    ├─────────────────────────────┤
    │  Layer 1: FROM golang:1.22  │ ← базовый образ
    └─────────────────────────────┘

  Каждый слой — это diff от предыдущего. Слои — read-only
  и переиспользуются между разными образами.

  3. КОНТЕЙНЕР (CONTAINER) — ЧТО ЭТО

  3.1. ОПРЕДЕЛЕНИЕ
  Контейнер — это запущенный экземпляр образа. В ООП это объект.
  В рецепте — приготовленное блюдо. В чертеже — построенное здание.

  Контейнер = образ + тонкий записываемый слой сверху.

  Схема:
    ┌─────────────────────────────┐
    │  Container layer (RW)       │ ← сюда пишутся изменения
    ├─────────────────────────────┤
    │  Image layers (RO)          │ ← неизменяемые слои образа
    │  ...                        │
    └─────────────────────────────┘

  Всё, что контейнер записывает во время работы, идёт в RW-слой.
  Образ остаётся нетронутым. Именно поэтому один образ может
  использоваться для запуска N контейнеров одновременно.

  3.2. ЧТО ТАКОЕ КОНТЕЙНЕР "ПОД КАПОТОМ"
  Контейнер — это НЕ виртуальная машина. Это обычный процесс
  Linux, изолированный с помощью двух механизмов ядра:

    • NAMESPACES — изоляция видимости. Процесс видит только
      свою сеть, свои процессы, свою файловую систему, свой
      hostname.

    • CGROUPS — ограничение ресурсов. Сколько CPU, памяти,
      дисковых операций может потратить процесс.

  Изоляция на уровне ядра — вот почему контейнеры такие лёгкие.
  Запуск занимает миллисекунды (у VM — минуты). Памяти едят
  мегабайты (у VM — гигабайты).

  Три ключевых следствия:
    • Контейнеры на одном хосте делят ядро.
    • Контейнер НЕ может быть Windows на Linux-хосте
      (нужна виртуализация).
    • Контейнер — это процесс. Убили процесс — умер контейнер.

  3.3. КОНТЕЙНЕР И FILESYSTEM
  Важно понять: контейнер не копирует образ. Он использует
  OverlayFS — механизм, который накладывает друг на друга
  read-only слои образа и один writable слой сверху.

  Читаешь файл — он берётся из верхнего слоя, где он есть.
  Пишешь файл — он уходит в writable слой (copy-on-write).
  Удаляешь файл из образа — в writable слое создаётся "whiteout"
  (маркер удаления), сам файл остаётся в образе.

  Именно поэтому:
    • Запуск контейнера мгновенный — не нужно копировать ФС.
    • Удаление контейнера = удаление RW-слоя. Образ цел.
    • Данные в контейнере теряются при удалении — для
      постоянного хранения нужны volumes.

  4. СЛОИ (LAYERS) — КАК РАБОТАЕТ КЭШ

  4.1. ГЛАВНОЕ ПРАВИЛО
  Каждая инструкция RUN/COPY/ADD в Dockerfile создаёт новый слой.
  Слой — неизменяемый. Если содержимое слоя не изменилось —
  Docker берёт его из кэша. Если изменилось — пересобирает этот
  слой и все последующие.
  Это ключ к быстрой сборке.

  4.2. КАК ЭТО РАБОТАЕТ НА ПРАКТИКЕ
  Плохой Dockerfile:
    FROM golang:1.22
    WORKDIR /app
    COPY . .                    ← копируем ВСЁ
    RUN go mod download         ← зависимости
    RUN go build -o app         ← сборка
    CMD ["./app"]

  Что происходит: разработчик поменял один символ в main.go.
  Docker видит — слой COPY . . изменился. Кэш инвалидируется.
  Все последующие слои (go mod download, go build) пересобираются
  с нуля. Качает зависимости заново. Сборка занимает 2 минуты
  вместо 5 секунд.

  Хороший Dockerfile:
    FROM golang:1.22
    WORKDIR /app
    COPY go.mod go.sum ./       ← сначала манифесты
    RUN go mod download         ← этот слой кэшируется надолго
    COPY . .                    ← потом код
    RUN go build -o app
    CMD ["./app"]

  Что происходит: разработчик поменял один символ в main.go.
  Docker видит — слой COPY go.mod не изменился. Слой go mod
  download берётся из кэша. Пересобирается только COPY . . и
  go build. Сборка занимает 5 секунд.
  Разница в 24 раза. На больших проектах — в 50.

  4.3. ПРАВИЛА РАБОТЫ СО СЛОЯМИ
  ПРАВИЛО 1: СНАЧАЛА СТАБИЛЬНОЕ, ПОТОМ ИЗМЕНЯЕМОЕ.
  Зависимости меняются редко. Код — часто. Копируй зависимости
  раньше кода. Это классический паттерн из примера выше.
  ПРАВИЛО 2: ОБЪЕДИНЯЙ RUN-КОМАНДЫ.
  Каждая инструкция RUN создаёт отдельный слой. Слои накапливаются.
  `RUN apt-get install x` + `RUN apt-get install y` = два слоя.
  `RUN apt-get install x && apt-get install y` = один слой.

  Правильно:
    RUN apt-get update && \
        apt-get install -y curl && \
        rm -rf /var/lib/apt/lists/*

  Здесь три команды — один слой. Плюс чистка кэша apt в том же
  слое — иначе мусор останется в предыдущем слое.

  ПРАВИЛО 3: .DOCKERIGNORE — ТВОЙ ДРУГ.
  Перед COPY . . Docker отправляет весь build context в демон.
  Если в папке .git, node_modules, тестовые данные — всё это
  летит в демон. Медленно и бессмысленно.
  .dockerignore:
    .git
    .gitignore
    *.md
    tmp/
    .env
    bin/
    coverage.out
  Это уменьшает контекст с гигабайтов до килобайтов.

  ПРАВИЛО 4: НЕ МЕНЯЙ РАННИЕ СЛОИ БЕЗ ПРИЧИНЫ.
  Если ты изменил версию базового образа (FROM) — весь кэш
  инвалидируется. То же с WORKDIR, если он создаёт директории.

  4.4. КАК ПОСМОТРЕТЬ СЛОИ
  У любого образа можно посмотреть историю слоёв:
    docker history my-app:latest

  Покажет: какая инструкция создала слой, размер, команда.
  Очень полезно для отладки "почему образ весит 800 МБ".

  Классический пример: `RUN apt-get install` + `RUN apt-get clean`
  в разных слоях. Второй слой ничего не удаляет — файлы остались
  в первом. Вес образа не меняется.

  5. ЖИЗНЕННЫЙ ЦИКЛ КОНТЕЙНЕРА
  Контейнер — это процесс. У него есть состояния.

    CREATED  → создан, но не запущен (docker create)
       ↓
    RUNNING  → работает (docker run)
       ↓
    PAUSED   → приостановлен (docker pause, редко используется)
       ↓
    STOPPED  → остановлен, но существует (docker stop)
       ↓
    REMOVED  → удалён, RW-слой уничтожен (docker rm)

  КЛЮЧЕВОЙ МОМЕНТ: docker stop ≠ docker rm.
    • docker stop — посылает SIGTERM, ждёт 10 секунд, потом
      SIGKILL. Контейнер переходит в STOPPED. Файловая система
      сохраняется. Можно запустить снова.

    • docker rm — удаляет контейнер полностью. RW-слой исчезает.
      Всё, что было записано — потеряно (если не было volumes).

  Из этого правила следует: НЕ ХРАНИ ДАННЫЕ В КОНТЕЙНЕРЕ.
  Данные должны быть в volumes или во внешней БД. Контейнер —
  временный, эфемерный. Его могут убить в любой момент.

  Restart policies определяют, что делать при падении процесса:
    • no             — не перезапускать (дефолт).
    • always         — всегда перезапускать.
    • on-failure     — перезапускать только при ненулевом exit code.
    • unless-stopped — перезапускать, но не после явного stop.
  Для прода: unless-stopped. Для одноразовых задач (миграции): no.

  6. ОСНОВНЫЕ КОМАНДЫ — ШПАРГАЛКА
  РАБОТА С ОБРАЗАМИ:
    docker pull <image>       — скачать из registry.
    docker images             — список локальных образов.
    docker rmi <image>        — удалить образ.
    docker history <image>    — история слоёв.
    docker inspect <image>    — вся мета-информация.
    docker build -t name:tag . — собрать из Dockerfile.

  РАБОТА С КОНТЕЙНЕРАМИ:
    docker run <image>        — создать + запустить.
    docker ps                 — список запущенных.
    docker ps -a              — список всех (включая остановленные).
    docker start <id>         — запустить остановленный.
    docker stop <id>          — остановить (SIGTERM + 10 сек).
    docker kill <id>          — принудительно (SIGKILL).
    docker rm <id>            — удалить контейнер.
    docker rm -f <id>         — force: stop + rm.
    docker logs <id>          — логи.
    docker logs -f <id>       — логи в реальном времени.
    docker exec -it <id> sh   — зайти внутрь работающего.
    docker inspect <id>       — мета-информация (IP, volumes, env).
    docker stats              — потребление ресурсов.

  ПОЛЕЗНЫЕ ФЛАГИ ДЛЯ run:
    -d                        — detached (в фоне).
    -it                       — interactive + tty (для shell).
    -p 8080:8080              — публикация порта (хост:контейнер).
    -e KEY=value              — переменная окружения.
    -v /host:/container       — bind mount.
    --name my-container       — имя.
    --rm                      — удалить после остановки.
    --restart unless-stopped  — restart policy.

  КОМБИНАЦИЯ, КОТОРУЮ БУДЕШЬ ИСПОЛЬЗОВАТЬ ЧАЩЕ ВСЕГО:
    docker run -d -p 8080:8080 --name app --rm my-app:latest

  Запустить my-app в фоне, опубликовать порт 8080, назвать "app",
  удалить автоматически при остановке.

  7. REGISTRY — ОТКУДА БЕРУТСЯ ОБРАЗЫ
  Registry — это хранилище образов. Аналог GitHub для кода.

  Основные публичные registry:
    • DOCKER HUB (hub.docker.com) — дефолт, самый большой.
    • GHCR (ghcr.io) — GitHub Container Registry.
    • QUAY (quay.io) — Red Hat.
    • ECR (AWS), GCR (Google), ACR (Azure) — облачные.

  Публичные образы — бесплатно. Приватные — по подписке.

  Полное имя образа:
    registry.example.com/namespace/name:tag
    • registry.example.com — registry.
    • namespace — владелец (обычно username или org).
    • name — имя образа.
    • tag — версия (latest, 1.2.3, sha-abc123).

  Если registry не указан — по умолчанию Docker Hub.
  Если tag не указан — по умолчанию latest.

  ВАЖНО ПРО latest:
  latest — это НЕ "последняя версия". Это просто дефолтный тег.
  Он может указывать на что угодно и меняется без предупреждения.

  Никогда не используй latest в проде. Зафиксируй конкретную
  версию: my-app:1.2.3 или my-app@sha256:abc123...

  8. GO-СПЕЦИФИКА
  Как эти концепции применяются к нашим Go-сервисам.

  8.1. ОДИН ОБРАЗ — N РЕПЛИК
  Ты собрал образ order-service:v1.2.3. В проде запускаешь
  не один контейнер, а 5-10 реплик за балансировщиком.
  Все они используют один и тот же образ. Обновление —
  собираешь новый образ, деплоишь, старые контейнеры
  гасятся, новые поднимаются.
  Это и есть горизонтальное масштабирование.

  8.2. ПОРЯДОК СЛОЁВ ДЛЯ GO
  Классический паттерн:
    FROM golang:1.22-alpine AS builder
    WORKDIR /app

    COPY go.mod go.sum ./       ← слой 1: манифесты
    RUN go mod download         ← слой 2: зависимости

    COPY . .                    ← слой 3: код
    RUN CGO_ENABLED=0 go build -o /app/server ./cmd/server

    FROM alpine:3.19            ← новый stage
    COPY --from=builder /app/server /server
    ENTRYPOINT ["/server"]

  Слои 1 и 2 кэшируются надолго. При изменении кода пересобирается
  только слой 3 и последующие. Экономия времени — гигантская.

  8.3. ГОТОВНОСТЬ К ПЕРЕЗАПУСКУ
  Контейнеры — временные. Kubernetes может убить под в любой
  момент. Go-сервис должен уметь корректно завершаться:

    • Слушать SIGTERM (signal.Notify).
    • Дождаться текущих запросов (srv.Shutdown).
    • Закрыть соединения с БД.
    • Сбросить буферы.
    • Выйти с кодом 0.

  Без этого SIGKILL через 10 секунд (по умолчанию) убьёт
  сервис жёстко. В проде настраивают stop_grace_period: 30s,
  чтобы дать время на graceful shutdown.

  8.4. СТАТИЧЕСКИЕ БИНАРНИКИ
  Go компилируется в статический бинарник (CGO_ENABLED=0).
  Это значит:
    • Не нужны glibc, musl и другие системные библиотеки.
    • Работает на scratch (пустой образ).
    • Образ может быть 10-20 МБ вместо 800 МБ.

  Это одна из главных причин, почему Go так хорошо ложится
  в контейнеры.

  9. АНТИПАТТЕРНЫ

  9.1. ХРАНИТЬ ДАННЫЕ В КОНТЕЙНЕРЕ
    Контейнер удалили — данные потеряны. Все данные — в volumes,
    в БД, в S3. Контейнер — эфемерный.
  9.2. ИСПОЛЬЗОВАТЬ latest В ПРОДЕ
    latest меняется без предупреждения. Сегодня работает,
    завтра после docker pull — сломалось. Фиксируй версии.
  9.3. КОПИРОВАТЬ ВЕСЬ КОНТЕКСТ БЕЗ .DOCKERIGNORE
    .git, node_modules, temp-файлы улетают в build context.
    Сборка медленная, образ раздутый.
  9.4. RUN КОМАНДЫ В РАЗНЫХ СЛОЯХ
    `RUN apt-get install` + `RUN apt-get clean` — чистка
    в другом слое не уменьшает образ. Объединяй.
  9.5. COPY . . ПЕРЕД GO MOD DOWNLOAD
    Любое изменение кода = пересборка всех зависимостей.
    Сначала go.mod, потом код.
  9.6. ЗАПУСК ПОД ROOT
    По умолчанию контейнер работает под root. Пробили сервис —
    root внутри. Используй USER 1000:1000.
  9.7. ЗАБЫТЬ ПРО GRACEFUL SHUTDOWN
    SIGKILL через 10 секунд убьёт сервис жёстко. Незакрытые
    транзакции, потерянные данные, ошибки у клиентов. Слушай
    SIGTERM.
  9.8. ПИСАТЬ В КОРЕНЬ ФС
    Read-only root fs — стандарт безопасности. Всё, что нужно
    писать, — в volumes или /tmp.

  10. ФИНАЛЬНЫЕ ВЫВОДЫ

  1.  Образ — неизменяемый шаблон. Контейнер — запущенный
      экземпляр. Один образ → N контейнеров.
  2.  Контейнер — это процесс Linux с изоляцией через
      namespaces и cgroups. Не VM.
  3.  Слои — основа кэша. Каждая RUN/COPY создаёт слой.
      Порядок инструкций влияет на скорость сборки.
  4.  Сначала стабильное (go.mod), потом изменяемое (код).
      Классический паттерн для Go.
  5.  Объединяй RUN-команды. Одна команда — один слой.
  6.  .dockerignore обязателен. Уменьшает build context
      и ускоряет сборку.
  7.  docker stop ≠ docker rm. Данные в контейнере — эфемерны.
      Для постоянных данных — volumes.
  8.  Restart policy: unless-stopped для сервисов, no для
      одноразовых задач.
  9.  Registry — хранилище образов. Не используй latest в проде.
  10. Go + Docker = идеальная пара. CGO_ENABLED=0 даёт статический
      бинарник, который работает на scratch. Образ — 10-20 МБ.
  11. Go-сервис должен корректно обрабатывать SIGTERM для
      graceful shutdown.
  12. Антипаттерны: root, latest, данные в контейнере, отсутствие
      .dockerignore, COPY . . перед go mod download.
  13. На собеседовании важно понимать не только команды,
      но и "почему": зачем слои, зачем .dockerignore,
      зачем non-root.
  14. Начинай с простого Dockerfile. Дальше оптимизируй:
      multi-stage, .dockerignore, non-root, distroless.
  15. Docker — это навык, а не теория. Прочитал — пошёл
      собрал. Через 5 образов всё закрепится.
*/

func main() {
	// Порт берём из env, чтобы в контейнере легко переопределить.
	port := os.Getenv("PORT")
	if port == "" {
		port = "8080"
	}

	http.HandleFunc("/", func(w http.ResponseWriter, r *http.Request) {
		fmt.Fprintf(w, "Hello from container!\nPID: %d\nTime: %s\n",
			os.Getpid(), time.Now().Format(time.RFC3339))
	})

	http.HandleFunc("/health", func(w http.ResponseWriter, r *http.Request) {
		w.WriteHeader(http.StatusOK)
		fmt.Fprintln(w, "ok")
	})

	log.Printf("listening on :%s", port)
	log.Fatal(http.ListenAndServe(":"+port, nil))
}
