//1. СТЕК VS КУЧА
/*
Стек:
 - Автоматическая память каждой горутины (по умолч. ~2 КБ, растёт при необходимости)
 - LIFO (последний пришёл — первый ушёл)
 - Выделение: просто сдвиг указателя (быстро)
 - Освобождение: при выходе из функции (мгновенно)
 - Ограничение: нельзя вернуть адрес переменной стека наружу

Куча:
 - Глобальная память всего процесса
 - Выделение: сложный алгоритм (переиспользование, фрагментация)
 - Освобождение: сборщиком мусора (GC) — STW, параллельная маркировка и очистка
 - Требуется, когда переменная переживает область существования (scope) функции

Правила побега (escape):
 1. Адрес локальной переменной возвращается наружу
 2. Адрес локальной переменной присваивается глобальному указателю
 3. Локальная переменная захватывается замыканием (closure)
 4. Переменная помещается в интерфейс (any), если компилятор не может доказать, что он не убежит
 5. Приём fmt-функциями (Println, Sprintf) — аргументы any
 6. Слайс переменной длины (make([]int, n)) с n неконстантой — убегает
 7. Слайс с capacity больше маленького порога (иногда)

Полезные флаги:
 go build -gcflags="-m"    базовый вывод escape & inlining
 go build -gcflags="-m -m" подробный
 go build -gcflags="-m=2"  аналогично
 go build -gcflags="-m -l" отключить inlining (чтобы не мешал)
*/

//2. КАКИЕ ДАННЫЕ ИДУТ В СТЕК, А КАКИЕ В КУЧУ — И ПОЧЕМУ
/*
Решение принимает escape analysis на этапе компиляции. Ниже — общие правила
 и исключения. Помни: даже большой объект может остаться на стеке, если не убегает.

Escape analysis — это процесс, который компилятор использует для определения
размещения значений, созданных вашей программой. В частности, компилятор выполняет
статический анализ кода, чтобы определить, может ли значение быть помещено в
стековый фрейм для функции, которая его строит, или значение должно «сбежать» в кучу.

НА СТЕК (быстро, автоматически):
 • Локальные переменные простых типов (int, float, bool, byte)
 • слайсы (заголовок: указатель + длина — сам указатель на стеке, но данные строки
	могут быть в куче, если строка большая или сгенерирована динамически)
 • Массивы фиксированного размера, не выходящие за пределы функции
 • Структуры (по значению), не содержащие указателей на убегающие данные
 • Аргументы функций (копии, если не берётся адрес)
 • Маленькие слайсы, созданные через make с константным размером (зависит от версии Go)

В КУЧУ (медленнее, требует GC):
 • Любые данные, адрес которых возвращается из функции (даже int)
 • Переменные, захваченные замыканием (closure)
 • Данные, присвоенные глобальному указателю
 • Данные, переданные в функцию через интерфейс any (если компилятор не может доказать
	что интерфейс временный)
 • Слайсы и карты, созданные с неконстантным размером
 • Данные, переданные в fmt.Println, fmt.Sprintf и подобные (аргументы -> any)
 • Большие объекты, которые компилятор считает небезопасными для стека (чтобы избежать
	stack overflow — точный порог зависит от версии, обычно > 64–128 КБ)
 • Все данные, на которые есть ссылки извне (например, добавление в глобальный слайс)

ПОЧЕМУ ТАК ПРОИСХОДИТ — ПРИЧИНЫ:
 • Стек — LIFO, дешёвый, но локальный. Нельзя сохранить адрес переменной стека после
	выхода из функции — память перезапишется. Компилятор перемещает такие переменные в кучу.
 • Куча — глобальная, ссылки на неё можно хранить где угодно. Цена — сборка мусора.
 • Замыкания: внутренняя функция ссылается на переменную внешней → та должна жить дольше,
	чем внешняя функция → перемещение в кучу.
 • Интерфейсы: any не даёт компилятору гарантий о реальном типе и времени жизни,
	поэтому часто (не всегда) вызывает escape.
 • Слайсы переменной длины: размер неизвестен на этапе компиляции, компилятор не может
	выделить место на стеке → в кучу.

ПРИМЕРЫ (мысленные, не код):
 - x := 42; return &x                 x в куче (нужен после выхода)
 - y := make([]int, n)                данные слайса в куче (n неизвестно)
 - z := [3]int{1,2,3}; return         z на стеке (возврат копии)
 - f := func() { fmt.Println(z) }     z в куче (захвачено замыканием)
 - var i any = 42                     42 в куче (интерфейс)

ПРОВЕРКА:
 go build -gcflags="-m"     увидишь "escapes to heap" или "moved to heap"
 go build -gcflags="-m -l"  отключить inlining для чистоты
*/

// 1. Присваивание глобальному указателю — куча
var global *int

func store() {
	x := 100
	global = &x
}

func example1() {
	store()
}

// 2. Слайс переменной длины vs фиксированный
func variableSlice(n int) []int {
	return make([]int, n)
}

func constantSlice() []int {
	return make([]int, 3)
}

func example2() {
	_ = variableSlice(5)
	_ = constantSlice()
}

// 3. Сравнение: возврат значения vs указателя
type user struct {
	name string
	age  int
}

func returnValue() user {
	u := user{
		name: "KokoKeke",
		age:  663,
	}
	return u
}

func returnPointer() *user {
	u := user{"Bob", 125}
	return &u
}

func example3() {
	_ = returnValue()
	_ = returnPointer()
}

//4. Захват переменной в цикле (ловушка) — куча

func example4() {
	var funcs []func()
	for i := 0; i < 3; i++ {
		funcs = append(funcs, func() { _ = i })
	}
	for _, f := range funcs {
		f()
	}
}

// 5. Фабрика с конфигом (возврат указателя + передача в интерфейс)
type Config struct {
	Timeout int
	Debug   bool
}

type Server struct {
	cfg *Config // указатель — значит, Config убежит
}

func NewServer(debug bool) *Server {
	cfg := Config{Timeout: 30, Debug: debug} // локальная структура
	return &Server{cfg: &cfg}                // берём адрес cfg — убегает
}

//6. Парсинг JSON (интерфейс + любой тип)

type User struct {
	Name string
	Age  int
}

func parseUser(data []byte) (*User, error) {
	var u *User

	if err := json.Unmarshal(data, u); err != nil {
		return nil, err
	}
	return u, nil
}

//7. Сортировка с замыканием (переменная итерации + передача в sort.Slice)

func sortUserByName(users []User) {
	sort.Slice(users, func(i, j int) bool {
		return users[i].Name < users[j].Name
	})
}

// 8. Worker pool с каналом (слайс переменной длины + захват)

func workerPool(n int) {
	var wg sync.WaitGroup
	jobs := make([]int, n)
	for i := range jobs {
		jobs[i] = i
	}

	for _, job := range jobs {
		wg.Add(1)
		go func(j int) {
			defer wg.Done()
			process(j)
		}(job)
	}
	wg.Wait()
}

func process(val int) int {
	return val * val
}

