package __two_pointers

/*
  АЛГОРИТМЫ 3: TWO POINTERS
  Two pointers — это не «алгоритм», а паттерн. Ты держишь два индекса и двигаешь их по массиву или строке.
  Вместо двух вложенных циклов (O(n²)) ты получаешь один проход (O(n)).
  Паттерн применяется в 20-30% задач на массивы и строки. Без него ты будешь решать O(n²), когда есть O(n).

  СОДЕРЖАНИЕ:
    1.  Зачем нужен two pointers
    2.  Три вида two pointers
    3.  Сходящиеся указатели (left/right)
    4.  Пример: Container With Most Water
    5.  Быстрый и медленный указатели (fast/slow)
    6.  Пример: Move Zeroes
    7.  Три указателя (Dutch National Flag)
    8.  Пример: Sort Colors
    9.  Общие правила
    10. Сложность и сравнение
    11. Связь с Go
    12. Что спрашивают на собесе
    13. Антипаттерны
    14. Финальные выводы

  1. ЗАЧЕМ НУЖЕН TWO POINTERS
  ПРОБЛЕМА: многие задачи просят «найти пару», «проверить на палиндром», «сжать массив», «убрать дубликаты».
  Наивное решение — два вложенных цикла: O(n²).
  Для n = 10^5 это 10 миллиардов операций. Не пройдёт.

  РЕШЕНИЕ: two pointers.
  Ты двигаешь два индекса по массиву за один проход. O(n).
  Часто это работает потому, что задача имеет монотонность — если одно условие выполнено, можно двигать указатель, не проверяя всё заново.

  ЧТО ЭТО ДАЁТ:
    • O(n²) → O(n) на многих задачах.
    • O(n) памяти → O(1) памяти (in-place).
    • Простота кода: один цикл вместо двух.
    • Работает и на массивах, и на строках, и на связных списках.

  КОГДА ВИДИШЬ TWO POINTERS:
    • Задача про пару (сумма, разность, произведение).
    • Задача про палиндром.
    • Задача «in-place» (убрать дубликаты, сжать, переместить).
    • Массив отсортирован (или можно отсортировать).
    • Задача про подотрезок или подмассив.
    • Нужно найти середину списка/массива.

  ПРАВИЛО: если задача про «пару» или «in-place» и есть монотонность — думай про two pointers.

  2. ТРИ ВИДА TWO POINTERS
  Паттерн имеет три основных варианта. Каждый для своих задач.

  СХОДЯЩИЕСЯ УКАЗАТЕЛИ (left/right):
    • Один указатель в начале, другой в конце.
    • Двигаются навстречу друг другу.
    • Когда left >= right — стоп.
    • Для задач: pair sum в отсортированном массиве, палиндром, container with most water.

  БЫСТРЫЙ И МЕДЛЕННЫЙ (fast/slow):
    • Оба в начале.
    • Fast двигается на 2 шага, slow на 1.
    • Или fast ищет, slow записывает.
    • Для задач: убрать дубликаты, move zeroes, cycle detection, middle of list.

  ТРИ УКАЗАТЕЛЯ (Dutch National Flag):
    • left, mid, right.
    • Используется для разделения массива на 3 части.
    • Для задач: sort colors, partition.

  ЧТО ВАЖНО:
    • Указатели — это индексы (для массивов) или ссылки на узлы (для списков).
    • «Указатель» — не обязательно указатель в смысле Go. Это просто индекс.

  ПРАВИЛО: определи, какой вид подходит к задаче. Сходящиеся — для пары. Fast/slow — для in-place. Три — для разбиения.

  3. СХОДЯЩИЕСЯ УКАЗАТЕЛИ (LEFT/RIGHT)

  ИДЕЯ:
    • left = 0, right = n-1.
    • Смотрим на arr[left] и arr[right].
    • Если нужно увеличить сумму — двигаем left вправо.
    • Если нужно уменьшить — двигаем right влево.

  ШАБЛОН:
    func twoPointers(arr []int) int {
        left, right := 0, len(arr)-1
        for left < right {
            // логика
            if condition {
                left++
            } else {
                right--
            }
        }
        return result
    }

  ПОЧЕМУ ЭТО РАБОТАЕТ:
    • Если массив отсортирован, то arr[left] — минимум, arr[right] — максимум.
    • Сумма arr[left] + arr[right] монотонно зависит от того, что двигаем.
    • Один проход — O(n).

  КОГДА ПРИМЕНЯТЬ:
    • Пара с заданной суммой в отсортированном массиве.
    • Палиндром.
    • Container with most water.
    • Trapping rain water.
    • Reverse string.

  ЧЕГО НЕ ДЕЛАТЬ:
    • Не двигай оба указателя одновременно без причины.
    • Не забывай про условие left < right.
    • Не двигай указатель, если не уверен, что это не пропустит ответ.

  ПРАВИЛО: сходящиеся указатели работают, когда есть монотонность — двигая один указатель, ты знаешь, в какую сторону меняется ответ.

  4. ПРИМЕР: CONTAINER WITH MOST WATER
  ЗАДАЧА: дан массив высот. Найди две линии, которые с осью X образуют контейнер с максимальной площадью.

  ФОРМУЛА: area = min(h[left], h[right]) * (right - left).

  BRUTE FORCE: два цикла, O(n²).

  TWO POINTERS: O(n).

  ИДЕЯ:
    • left = 0, right = n-1.
    • Площадь = min(h[l], h[r]) * (r - l).
    • Чтобы увеличить площадь, надо увеличить min.
    • Значит, двигаем тот указатель, у которого высота меньше.
    • Если равны — двигаем любой.

  КОД:
    func maxArea(height []int) int {
        left, right := 0, len(height)-1
        maxA := 0
        for left < right {
            h := height[left]
            if height[right] < h {
                h = height[right]
            }
            area := h * (right - left)
            if area > maxA {
                maxA = area
            }
            if height[left] < height[right] {
                left++
            } else {
                right--
            }
        }
        return maxA
    }

  ПОЧЕМУ РАБОТАЕТ:
    • Если двигать более высокую сторону, min не увеличится, а ширина уменьшится. Площадь только уменьшится.
    • Значит, всегда выгодно двигать более низкую сторону.
    • Мы не пропускаем оптимум.

  СЛОЖНОСТЬ: O(n) time, O(1) space.

  ЧТО ЗДЕСЬ ВАЖНО:
    • Монотонность: двигая короткую сторону, мы гарантированно исследуем все потенциальные улучшения.
    • Каждый указатель двигается максимум n раз.
    • Никаких вложенных циклов.

  ПРАВИЛО: если задача про «максимум площади/суммы/чего-то» с двумя границами — двигай указатель, который ограничивает результат.

  5. БЫСТРЫЙ И МЕДЛЕННЫЙ УКАЗАТЕЛИ (FAST/SLOW)

  ИДЕЯ:
    • Оба указателя в начале.
    • fast двигается быстрее (обычно на 2 шага).
    • slow двигается медленнее (обычно на 1 шаг).
    • Или: fast сканирует, slow записывает.

  ШАБЛОН:
    func fastSlow(arr []int) int {
        slow := 0
        for fast := 0; fast < len(arr); fast++ {
            if condition(arr[fast]) {
                arr[slow] = arr[fast]
                slow++
            }
        }
        return slow
    }

  КОГДА ПРИМЕНЯТЬ:
    • In-place модификация массива (убрать дубликаты, move zeroes).
    • Проверка на цикл в связном списке (Floyd's).
    • Поиск середины списка.
    • Сжатие массива.

  ЧТО ЭТО ДАЁТ:
    • O(n) time, O(1) space.
    • Не нужно создавать новый массив.
    • Один проход.

  ПРАВИЛО: fast/slow — для in-place модификаций и задач, где важен порядок элементов.

  6. ПРИМЕР: MOVE ZEROES
  ЗАДАЧА: дан массив. Перемести все нули в конец, сохранив порядок ненулевых элементов. In-place.
  ПРИМЕР: [0, 1, 0, 3, 12] → [1, 3, 12, 0, 0].

  ИДЕЯ:
    • slow указывает на позицию для следующего ненулевого.
    • fast идёт по массиву.
    • Если arr[fast] != 0, копируем в arr[slow] и увеличиваем slow.
    • После прохода всё после slow заполняем нулями.

  КОД:
    func moveZeroes(nums []int) {
        slow := 0
        for fast := 0; fast < len(nums); fast++ {
            if nums[fast] != 0 {
                nums[slow] = nums[fast]
                slow++
            }
        }
        for i := slow; i < len(nums); i++ {
            nums[i] = 0
        }
    }

  ПОЧЕМУ РАБОТАЕТ:
    • Ненулевые элементы сдвигаются в начало.
    • Порядок сохраняется.
    • Нули заполняются в конце.
    • In-place, O(1) памяти.

  СЛОЖНОСТЬ: O(n) time, O(1) space.

  ЧТО ЗДЕСЬ ВАЖНО:
    • slow — «куда писать».
    • fast — «что читать».
    • Указатели не обязательно сходятся, они могут двигаться в одну сторону.

  ПРАВИЛО: fast/slow хорошо работает, когда нужно «сжать» данные, убрав что-то ненужное.

  7. ТРИ УКАЗАТЕЛЯ (DUTCH NATIONAL FLAG)

  ИДЕЯ:
    • left, mid, right.
    • left — граница «маленьких» элементов.
    • right — граница «больших» элементов.
    • mid — текущий элемент.
    • Разбиваем массив на три части: < pivot, == pivot, > pivot.

  ШАБЛОН:
    func threePointers(arr []int, pivot int) {
        left, mid, right := 0, 0, len(arr)-1
        for mid <= right {
            if arr[mid] < pivot {
                arr[left], arr[mid] = arr[mid], arr[left]
                left++
                mid++
            } else if arr[mid] > pivot {
                arr[mid], arr[right] = arr[right], arr[mid]
                right--
            } else {
                mid++
            }
        }
    }

  КОГДА ПРИМЕНЯТЬ:
    • Sort Colors (Dutch National Flag).
    • Partition для quick sort.
    • Разбиение массива на 3 группы.

  ЧТО ЭТО ДАЁТ:
    • O(n) time, O(1) space.
    • Один проход.
    • In-place.

  ПРАВИЛО: три указателя — для задач, где нужно разбить массив на 3 категории.

  8. ПРИМЕР: SORT COLORS

  ЗАДАЧА: дан массив из 0, 1, 2. Отсортируй его in-place за один проход.

  ПРИМЕР: [2, 0, 2, 1, 1, 0] → [0, 0, 1, 1, 2, 2].

  ИДЕЯ:
    • pivot = 1 (середина).
    • left, mid, right.
    • 0 — двигаем влево.
    • 2 — двигаем вправо.
    • 1 — оставляем.

  КОД:
    func sortColors(nums []int) {
        left, mid, right := 0, 0, len(nums)-1
        for mid <= right {
            if nums[mid] == 0 {
                nums[left], nums[mid] = nums[mid], nums[left]
                left++
                mid++
            } else if nums[mid] == 2 {
                nums[mid], nums[right] = nums[right], nums[mid]
                right--
            } else {
                mid++
            }
        }
    }

  ПОЧЕМУ РАБОТАЕТ:
    • Всё, что меньше 1, уходит в начало.
    • Всё, что больше 1, уходит в конец.
    • mid не увеличивается при обмене с right (там может быть 0, нужно проверить).

  СЛОЖНОСТЬ: O(n) time, O(1) space.

  ЧТО ЗДЕСЬ ВАЖНО:
    • mid++ только когда обработали nums[mid] == 0 или nums[mid] == 1.
    • При nums[mid] == 2 мы обменяли, но не знаем, что пришло с конца. Поэтому mid не двигаем.

  ПРАВИЛО: three pointers — это Dutch National Flag. Используй для задач с тремя категориями.

  9. ОБЩИЕ ПРАВИЛА

  КОГДА ИСПОЛЬЗОВАТЬ:
    • Массив или строка.
    • Задача про пару, палиндром, in-place, подотрезок.
    • Вход отсортирован или можно отсортировать.
    • Есть монотонность (двигая указатель, знаешь, как меняется ответ).

  КАК ВЫБРАТЬ ВИД:
    • Пара с суммой → сходящиеся.
    • In-place, убрать дубликаты → fast/slow.
    • Три категории → three pointers (Dutch).
    • Палиндром → сходящиеся.
    • Цикл в списке → fast/slow.

  TWO POINTERS + СОРТИРОВКА:
    • Многие задачи требуют отсортировать массив перед two pointers.
    • Сортировка даёт монотонность. На отсортированном массиве two pointers работает.
    • Стоимость сортировки: O(n log n). Итоговая сложность: O(n log n) + O(n) = O(n log n).
    • Пример: 3Sum — сортируем, потом для каждого i запускаем two pointers.
    • Пример: Boats to Save People — сортируем, потом сходящиеся указатели.
    • Когда сортировка не нужна: палиндром, move zeroes, squares of sorted array (вход уже отсортирован).

  НА ЧТО ОБРАЩАТЬ ВНИМАНИЕ:
    • Условие выхода из цикла (left < right или left <= right).
    • Какой указатель двигать и когда.
    • Не пропустить оптимум.
    • In-place: не потерять данные при записи.
    • Граничные случаи: пустой массив, 1 элемент, все одинаковые.

  ПРАВИЛО: two pointers — это всегда один проход. Если два прохода или вложенные циклы — скорее всего ты делаешь что-то не то.

  10. СЛОЖНОСТЬ И СРАВНЕНИЕ

  СЛОЖНОСТЬ TWO POINTERS:
    • Time: O(n) или O(n log n), если нужна сортировка.
    • Space: O(1) или O(n), если строится новый массив.

  СРАВНЕНИЕ С BRUTE FORCE:
    • Пара с суммой: O(n²) → O(n) (если отсортирован) или O(n) с hash map.
    • Палиндром: O(n²) → O(n).
    • Убрать дубликаты: O(n²) → O(n).
    • Sort colors: O(n log n) → O(n).

  СРАВНЕНИЕ С HASH MAP:
    • Two pointers: O(n), O(1) space, работает на отсортированном.
    • Hash map: O(n), O(n) space, работает без сортировки.
    • Two pointers часто предпочтительнее, если массив уже отсортирован или можно отсортировать.

  ПРАВИЛО: если массив отсортирован — two pointers. Если нет и порядок не важен — hash map.

  11. СВЯЗЬ С GO

  ОСОБЕННОСТИ GO:
    • Массивы и слайсы — индексация через [].
    • Указатели — индексы, не *int.
    • Строки — []rune для корректной работы с Unicode.
    • sort.Slice — для сортировки.
    • sort.Ints — для чисел.

  ПРИМЕР С RUNE:
    func isPalindrome(s string) bool {
        runes := []rune(s)
        left, right := 0, len(runes)-1
        for left < right {
            if runes[left] != runes[right] {
                return false
            }
            left++
            right--
        }
        return true
    }

    Если работаешь с []byte — то же, но для ASCII. Для Unicode — только []rune.

  ПРИМЕР С СОРТИРОВКОЙ:
    sort.Ints(nums)   // для []int
    sort.Slice(people, func(i, j int) bool {
        return people[i] < people[j]
    })

  ОБМЕН ЭЛЕМЕНТОВ:
    nums[i], nums[j] = nums[j], nums[i]

  В GO ЭТО ИДИОМАТИЧНО. Один statement, без временной переменной.

  СВЯЗНЫЙ СПИСОК:
    type ListNode struct {
        Val  int
        Next *ListNode
    }

    slow, fast := head, head
    for fast != nil && fast.Next != nil {
        slow = slow.Next
        fast = fast.Next.Next
    }

  ПРАВИЛО: в Go two pointers — это индексы. Для строк — []rune. Обмен через множественное присваивание.

  12. АНТИПАТТЕРНЫ
  12.1. TWO POINTERS БЕЗ МОНОТОННОСТИ.
    Если нет монотонности, two pointers не работает. Нужен hash map.
  12.2. ЗАБЫТЬ ПРО СОРТИРОВКУ.
    Многие задачи требуют сортировки перед two pointers. Без неё — не работает.
  12.3. ПОТЕРЯТЬ ДАННЫЕ ПРИ IN-PLACE.
    Записывая в arr[slow], не перезапиши то, что ещё не прочитано. В fast/slow это норм, потому что slow <= fast.
  12.4. НЕ ПРОВЕРИТЬ ГРАНИЦЫ.
    Пустой массив, 1 элемент, all equal — везде нужны проверки.
  12.5. РАБОТАТЬ С []BYTE ВМЕСТО []RUNE.
    Unicode символы занимают 1-4 байта. []byte сломает палиндром на кириллице, emoji, акцентах.
  12.6. НЕ ПРОВЕРЯТЬ УСЛОВИЕ ЦИКЛА.
    left < right или left <= right — выбирай под задачу.
  12.7. ДВИГАТЬ ОБА УКАЗАТЕЛЯ ОДНОВРЕМЕННО.
    Без причины — почти всегда ошибка. Двигай один указатель за итерацию.
  12.8. НЕ НАЗЫВАТЬ СЛОЖНОСТЬ.
    Каждое решение заканчивай «O(n) time, O(1) space».
  12.9. ИСПОЛЬЗОВАТЬ TWO POINTERS ДЛЯ ПОДСТРОКИ.
    Для подстроки обычно нужен sliding window, а не two pointers.
  12.10. ЗАБЫТЬ ПРО СВЯЗНЫЕ СПИСКИ.
    Two pointers работает и там. Это классика для cycle detection и middle.

  13. ФИНАЛЬНЫЕ ВЫВОДЫ
  1.  Two pointers — паттерн для O(n) на массивах и строках.
  2.  Три вида: сходящиеся (left/right), fast/slow, three pointers.
  3.  Сходящиеся: пара с суммой, палиндром, container with most water.
  4.  Fast/slow: in-place модификация, cycle detection, middle of list.
  5.  Three pointers: Dutch National Flag, partition.
  6.  Монотонность — ключевое условие. Без неё two pointers не работает.
  7.  Часто нужна сортировка (O(n log n)) перед two pointers.
  8.  В Go: индексы, []rune для Unicode, sort.Ints, sort.Slice, обмен через множественное присваивание.
  9.  Сложность: O(n) time, O(1) space (или O(n log n) с сортировкой).
  10. Антипаттерны: без монотонности, без сортировки, []byte для Unicode, одновременное движение указателей, забыть границы.
*/
