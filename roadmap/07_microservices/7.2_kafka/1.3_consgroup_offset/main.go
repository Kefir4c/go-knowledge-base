/*
  БЛОК 1.3: CONSUMER GROUPS И СМЕЩЕНИЯ
  Consumer Groups и смещения (offsets) — это механизм, который делает Kafka
  не просто очередью, а платформой для распределённой обработки данных.
  Именно здесь происходит магия: консюмеры работают параллельно,
  запоминают свою позицию и могут восстановиться после сбоев.

  СОДЕРЖАНИЕ:
    1.  Что такое Consumer Group
    2.  Правило: одна партиция → один консюмер
    3.  Перебалансировка (Rebalance) — как она работает
    4.  Смещения (Offsets) — позиция консюмера
    5.  Автоматический коммит смещений
    6.  Ручной коммит смещений
    7.  Стратегии коммита: at-least-once и exactly-once
    8.  Хранение смещений в топике __consumer_offsets
    9.  Consumer Lag — главная метрика здоровья
    10. Ключевые выводы для собеседования

  1.  ЧТО ТАКОЕ CONSUMER GROUP
  Consumer Group — это группа консюмеров, которые совместно читают сообщения
  из одного или нескольких топиков.

  КЛЮЧЕВЫЕ ПРИНЦИПЫ:
    • Все консюмеры в группе имеют одинаковый group.id.
    • Каждая партиция топика назначается ТОЛЬКО ОДНОМУ консюмеру в группе.
    • Каждый консюмер может обслуживать несколько партиций.
    • Количество консюмеров в группе не может превышать количество партиций
      (избыточные консюмеры будут простаивать).

  ПРЕИМУЩЕСТВА CONSUMER GROUPS:
    • Параллельная обработка: несколько консюмеров читают разные партиции
      одновременно.
    • Отказоустойчивость: при падении одного консюмера его партиции
      перераспределяются между оставшимися.
    • Масштабируемость: можно добавлять консюмеров для увеличения
      пропускной способности.
    • Управление позицией: группа хранит общее смещение (offset) для каждой
      партиции.

  2.  ПРАВИЛО: ОДНА ПАРТИЦИЯ → ОДИН КОНСЮМЕР
  Это фундаментальное правило Kafka.

  КАК ЭТО РАБОТАЕТ:
    • Когда консюмер подключается к группе, Kafka назначает ему одну или
      несколько партиций.
    • Одна партиция никогда не назначается двум консюмерам в одной группе.
    • Если консюмеров больше, чем партиций, часть консюмеров остаётся
      без назначенных партиций (простаивает).

  ПРИМЕРЫ:
    ┌─────────────────────────────────────────────────────────────────────┐
    │ Топик orders (3 партиции: P0, P1, P2)                               │
    │ Consumer Group: order-processors                                    │
    ├─────────────────────────────────────────────────────────────────────┤
    │ Консюмер A → P0, P1                                                 │
    │ Консюмер B → P2                                                     │
    │ Консюмер C → простаивает (нет свободных партиций)                   │
    └─────────────────────────────────────────────────────────────────────┘

    ┌─────────────────────────────────────────────────────────────────────┐
    │ Топик orders (3 партиции: P0, P1, P2)                               │
    │ Consumer Group: order-processors                                    │
    ├─────────────────────────────────────────────────────────────────────┤
    │ Консюмер A → P0                                                     │
    │ Консюмер B → P1                                                     │
    │ Консюмер C → P2                                                     │
    └─────────────────────────────────────────────────────────────────────┘

  ВЫВОД: чтобы эффективно использовать консюмеров, количество партиций
  должно быть не меньше максимального ожидаемого количества консюмеров.

  3.  ПЕРЕБАЛАНСИРОВКА (REBALANCE) — КАК ОНА РАБОТАЕТ
  Rebalance — это процесс перераспределения партиций между консюмерами
  в группе при изменении её состава.

  КОГДА ПРОИСХОДИТ REBALANCE:
    • Добавление нового консюмера в группу.
    • Удаление консюмера из группы (по инициативе или из-за сбоя).
    • Изменение подписки на топики (добавление/удаление топиков).
    • Изменение количества партиций в топике.

  СТРАТЕГИИ РАСПРЕДЕЛЕНИЯ ПАРТИЦИЙ:

    • RANGE (по умолчанию) — партиции делятся на диапазоны между
      консюмерами. Хорошо для однородных топиков.
    • ROUNDROBIN — партиции распределяются по кругу. Даёт более
      равномерное распределение при большом количестве топиков.
    • STICKY — минимизирует перемещение партиций при перебалансировке.
      Сохраняет существующие назначения, перемещая только необходимые.
    • COOPERATIVE (Incremental Cooperative Rebalancing) — позволяет
      переназначать только те партиции, которые реально меняют владельца,
      не останавливая работу остальной группы. Это значительно улучшает
      производительность при частых перебалансировках.

  ВЛИЯНИЕ REBALANCE:
    • Во время ребалансировки потребление сообщений ОСТАНАВЛИВАЕТСЯ
      (stop-the-world для группы, кроме Cooperative).
    • Это может привести к задержкам в обработке.
    • Частые ребалансировки — признак проблемы (например, консюмеры
      слишком долго обрабатывают сообщения или часто падают).

  КАК УМЕНЬШИТЬ ВЛИЯНИЕ REBALANCE:
    • Увеличить session.timeout.ms и heartbeat.interval.ms.
    • Использовать Static Membership (group.instance.id).
    • Использовать Cooperative Rebalance.
    • Увеличить max.poll.interval.ms для долгих обработок.

  4.  СМЕЩЕНИЯ (OFFSETS) — ПОЗИЦИЯ КОНСЮМЕРА
  Смещение (Offset) — это номер последнего прочитанного сообщения в партиции.
  Консюмеры используют смещения, чтобы знать, с какого места продолжать
  чтение после перезапуска.

  КЛЮЧЕВЫЕ МОМЕНТЫ:
    • Смещение уникально в пределах одной партиции.
    • Смещение строго возрастает.
    • Консюмер решает, какое смещение закоммитить (подтвердить).
    • При старте консюмер читает последнее закоммиченное смещение.

  5.  АВТОМАТИЧЕСКИЙ КОММИТ СМЕЩЕНИЙ
  enable.auto.commit = true (по умолчанию)

  КАК ЭТО РАБОТАЕТ:
    • Kafka сама коммитит смещения через заданный интервал времени
      (auto.commit.interval.ms, по умолчанию 5 секунд).
    • Коммит происходит на основе последнего прочитанного сообщения.
    • Консюмер не управляет коммитом вручную.

  ПРЕИМУЩЕСТВА:
    • Простота — не нужно писать код для коммита.
    • Подходит для простых сценариев.

  НЕДОСТАТКИ:
    • Возможна потеря сообщений (при сбое между чтением и коммитом).
    • Возможны дубли (при сбое после коммита, но до обработки).
    • Не подходит для точно-once обработки.
    • Не подходит для долгих обработок (коммит может произойти раньше,
      чем обработка завершится).

  КОГДА ИСПОЛЬЗОВАТЬ:
    • Некритичные данные.
    • Быстрая обработка (< 5 секунд).
    • At-most-once или at-least-once с допустимыми дублями.

  6.  РУЧНОЙ КОММИТ СМЕЩЕНИЙ
  enable.auto.commit = false

  КАК ЭТО РАБОТАЕТ:
    • Консюмер явно вызывает commitSync() или commitAsync().
    • Коммит происходит ПОСЛЕ обработки сообщения.

  ПРЕИМУЩЕСТВА:
    • Полный контроль над коммитом.
    • Гарантирует, что сообщение обработано до коммита.
    • Подходит для at-least-once и exactly-once.
    • Позволяет коммитить после успешной обработки (не после чтения).

  НЕДОСТАТКИ:
    • Сложнее в реализации.
    • commitSync() блокирует выполнение.
    • commitAsync() может завершиться ошибкой, которую нужно обрабатывать.

  6.1. Синхронный коммит (commitSync)
    consumer.commitSync() // блокирует поток до завершения

  ПРЕИМУЩЕСТВА:
    • Гарантирует, что смещение закоммичено.
    • При ошибке можно повторить.

  НЕДОСТАТКИ:
    • Блокирует обработку.
    • Может снизить пропускную способность.

  6.2. Асинхронный коммит (commitAsync)
    consumer.commitAsync() // не блокирует поток

  ПРЕИМУЩЕСТВА:
    • Не блокирует обработку.
    • Выше пропускная способность.

  НЕДОСТАТКИ:
    • Не гарантирует, что смещение закоммичено.
    • Ошибки нужно обрабатывать в колбеке.

  6.3. Комбинированный подход
    try {
        // Обработка сообщения
        consumer.commitSync() // финальный коммит для гарантии
    } catch (Exception e) {
        consumer.commitAsync() // асинхронный коммит для быстрых операций
    }

  7.  СТРАТЕГИИ КОММИТА: AT-LEAST-ONCE И EXACTLY-ONCE
  ВЫБОР СТРАТЕГИИ ЗАВИСИТ ОТ ТРЕБОВАНИЙ К ДАННЫМ.

  7.1. At-least-once (минимум один раз)
    • Смещение коммитится ПОСЛЕ обработки сообщения.
    • При сбое после обработки, но до коммита, сообщение будет прочитано
      повторно (дублирование).
    • Требует идемпотентной обработки на стороне консюмера.

  ПРИМЕР:
    while (true) {
        records = consumer.poll()
        for (record : records) {
            process(record)        // обработка
        }
        consumer.commitSync()      // коммит после обработки
    }

  7.2. Exactly-once (ровно один раз)
    • Комбинирует ручной коммит и транзакции продюсера.
    • Смещение консюмера коммитится в той же транзакции, что и отправка
      результата в другой топик.
    • Требует transactional.id для продюсера.

  ПРИМЕР:
    producer.beginTransaction()
    records = consumer.poll()
    for (record : records) {
        result = process(record)
        producer.send(result)      // отправка результата
    }
    producer.sendOffsetsToTransaction(offsets, consumerGroup)
    producer.commitTransaction()   // атомарный коммит

  8.  ХРАНЕНИЕ СМЕЩЕНИЙ В ТОПИКЕ __CONSUMER_OFFSETS
  Kafka хранит смещения консюмеров во внутреннем топике __consumer_offsets.

  КЛЮЧЕВЫЕ ХАРАКТЕРИСТИКИ:
    • Создаётся автоматически при первом коммите смещения.
    • Количество партиций = 50 по умолчанию.
    • Ключ: group-id + topic + partition.
    • Значение: последний закоммиченный offset + метаданные.

  ПРИМЕР ЗАПИСИ:
    Key:   group_id="order-group", topic="orders", partition=0
    Value: offset=1234, metadata="processed"

  ВАЖНО:
    • Этот топик тоже надо мониторить (как и любой другой).
    • При больших группах он может стать узким местом.
    • Можно настроить retention для __consumer_offsets.

  9.  CONSUMER LAG — ГЛАВНАЯ МЕТРИКА ЗДОРОВЬЯ
  Consumer Lag — это разница между последним смещением в партиции
  (Log End Offset) и текущим закоммиченным смещением консюмера.

  ФОРМУЛА:
    lag = log_end_offset - current_offset

  ЧТО ОЗНАЧАЕТ:
    • lag = 0 → консюмер полностью синхронизирован.
    • lag > 0 → консюмер отстаёт.
    • Постоянно растущий lag → консюмер не успевает обрабатывать сообщения.

  КАК МОНИТОРИТЬ:
    • kafka-consumer-groups.sh --describe --group <group-id>
    • Confluent Control Center
    • Prometheus + JMX exporter
    • Burrow (LinkedIn) — специализированный инструмент для мониторинга lag

  ПРИЧИНЫ РОСТА LAG:
    • Медленная обработка сообщений.
    • Слишком мало консюмеров.
    • Слишком мало партиций.
    • Сбой в консюмере.
    • Внешние зависимости (БД, API) медленные.

  ЧТО ДЕЛАТЬ ПРИ РОСТЕ LAG:
    1. Увеличить количество консюмеров (если есть свободные партиции).
    2. Увеличить количество партиций (требуется пересоздание топика).
    3. Оптимизировать обработку сообщений.
    4. Увеличить batch size для потребителя.
    5. Увеличить fetch.max.bytes и max.poll.records.

  10. КЛЮЧЕВЫЕ ВЫВОДЫ ДЛЯ СОБЕСЕДОВАНИЯ
  1. Consumer Group — группа консюмеров, совместно читающих топики.
     Все консюмеры в группе имеют одинаковый group.id.
  2. Правило: одна партиция → один консюмер в группе.
     Количество партиций определяет максимальный параллелизм.
  3. Rebalance — перераспределение партиций при изменении состава группы.
     Может быть stop-the-world (Range, RoundRobin, Sticky)
     или cooperative (Cooperative Sticky).
  4. Смещение (offset) — позиция консюмера в партиции.
     Консюмер коммитит смещение, чтобы запомнить прогресс.
  5. Автоматический коммит (enable.auto.commit=true) — Kafka коммитит
     смещения автоматически. Просто, но возможны потери или дубли.
  6. Ручной коммит (enable.auto.commit=false) — консюмер сам коммитит
     смещения. Даёт полный контроль, подходит для at-least-once
     и exactly-once.
  7. commitSync() — синхронный коммит, блокирует поток.
     commitAsync() — асинхронный коммит, не блокирует.
  8. Смещения хранятся в топике __consumer_offsets.
     Ключ: group-id + topic + partition. Значение: offset.
  9. Consumer Lag — разница между последним смещением в партиции
     и текущим смещением консюмера. Главная метрика здоровья.
  10. При росте lag: добавляйте консюмеров, увеличивайте партиции,
      оптимизируйте обработку.
*/
