var (
	acksMode  = flag.String("acks", "all", "Режим acks: 0, 1, all")
	broker    = flag.String("broker", "localhost:9092", "Адрес брокера")
	topic     = flag.String("topic", "acks-test", "Топик")
	count     = flag.Int("count", 100, "Количество сообщений")
	asyncMode = flag.Bool("async", false, "Использовать AsyncProducer (по умолчанию Sync)")
)

//МЕТРИКИ

type Metrics struct {
	sent      int64
	success   int64
	failures  int64
	totalTime int64 // наносекунды
	mu        sync.Mutex
}

func (m *Metrics) AddSent(n int64) {
	atomic.AddInt64(&m.sent, n)
}

func (m *Metrics) AddSuccess(n int64) {
	atomic.AddInt64(&m.success, n)
}

func (m *Metrics) AddFailure(n int64) {
	atomic.AddInt64(&m.failures, n)
}

func (m *Metrics) AddLatency(d time.Duration) {
	atomic.AddInt64(&m.totalTime, int64(d))
}

func (m *Metrics) Print() {
	sent := atomic.LoadInt64(&m.sent)
	success := atomic.LoadInt64(&m.success)
	failures := atomic.LoadInt64(&m.failures)
	totalTime := atomic.LoadInt64(&m.totalTime)
	avg := time.Duration(0)
	if success > 0 {
		avg = time.Duration(totalTime / success)
	}
	log.Printf("Статистика: отправлено=%d, успешно=%d, ошибок=%d, средняя задержка=%v",
		sent, success, failures, avg)
}

//ПРОДЮСЕРЫ

// newProducerConfig возвращает конфиг для продюсера с нужным acks.
func newProducerConfig(mode string) (*sarama.Config, error) {
	config := sarama.NewConfig()
	config.Version = sarama.V3_0_0_0
	config.Producer.Return.Successes = true
	config.Producer.Return.Errors = true

	// Настройка retries
	config.Producer.Retry.Max = 3
	config.Producer.Retry.Backoff = 100 * time.Millisecond

	// Устанавливаем acks
	switch mode {
	case "0":
		config.Producer.RequiredAcks = sarama.NoResponse
		log.Println("🔓 Режим acks=0: Fire-and-forget")
	case "1":
		config.Producer.RequiredAcks = sarama.WaitForLocal
		log.Println("🔒 Режим acks=1: подтверждение от лидера")
	case "all":
		config.Producer.RequiredAcks = sarama.WaitForAll
		log.Println("🔐 Режим acks=all: подтверждение от всех ISR")
		config.Producer.Idempotent = true
	default:
		return nil, fmt.Errorf("неизвестный режим acks: %s", mode)
	}
	return config, nil
}

// RunSyncProducer запускает синхронного продюсера.
func RunSyncProducer(ctx context.Context, acks string, topic string, broker string, count int) error {
	config, err := newProducerConfig(acks)
	if err != nil {
		return err
	}
	producer, err := sarama.NewSyncProducer([]string{broker}, config)
	if err != nil {
		return err
	}
	defer producer.Close()

	metrics := &Metrics{}

	log.Printf("Запуск SyncProducer (acks=%s, сообщений=%d)", acks, count)

	for i := 0; i < count; i++ {
		select {
		case <-ctx.Done():
			log.Println("Прервано по контексту")
			return nil
		default:
		}

		key := fmt.Sprintf("key-%d", i)
		value := fmt.Sprintf("msg-%d", i)
		msg := &sarama.ProducerMessage{
			Topic: topic,
			Key:   sarama.StringEncoder(key),
			Value: sarama.StringEncoder(value),
		}

		start := time.Now()
		partition, offset, err := producer.SendMessage(msg)
		latency := time.Since(start)

		metrics.AddSent(1)

		if err != nil {
			metrics.AddFailure(1)
			log.Printf("Ошибка отправки (i=%d): %v", i, err)
			continue
		}
		metrics.AddSuccess(1)
		metrics.AddLatency(latency)
		if i%10 == 0 {
			log.Printf("Отправлено: key=%s, partition=%d, offset=%d, latency=%v",
				key, partition, offset, latency)
		}
	}

	metrics.Print()
	return nil
}

// RunAsyncProducer запускает асинхронного продюсера.
func RunAsyncProducer(ctx context.Context, acks string, topic string, broker string, count int) error {
	config, err := newProducerConfig(acks)
	if err != nil {
		return err
	}
	// Для AsyncProducer тоже нужны каналы
	producer, err := sarama.NewAsyncProducer([]string{broker}, config)
	if err != nil {
		return err
	}
	defer producer.Close()

	metrics := &Metrics{}
	var wg sync.WaitGroup
	wg.Add(2)

	// Обработка успешных отправок
	go func() {
		defer wg.Done()
		for msg := range producer.Successes() {
			metrics.AddSuccess(1)
			log.Printf("Доставлено: topic=%s, partition=%d, offset=%d",
				msg.Topic, msg.Partition, msg.Offset)
		}
	}()

	// Обработка ошибок
	go func() {
		defer wg.Done()
		for err := range producer.Errors() {
			metrics.AddFailure(1)
			log.Printf("Ошибка доставки: %v", err)
		}
	}()

	log.Printf("Запуск AsyncProducer (acks=%s, сообщений=%d)", acks, count)

	// Отправка сообщений
	for i := 0; i < count; i++ {
		select {
		case <-ctx.Done():
			log.Println("⏳ Прервано по контексту")
			producer.AsyncClose()
			wg.Wait()
			return nil
		default:
		}

		key := fmt.Sprintf("async-key-%d", i)
		value := fmt.Sprintf("async-msg-%d", i)
		msg := &sarama.ProducerMessage{
			Topic: topic,
			Key:   sarama.StringEncoder(key),
			Value: sarama.StringEncoder(value),
		}

		start := time.Now()
		producer.Input() <- msg
		// Для AsyncProducer задержку считаем приблизительно: время до отправки в канал
		metrics.AddLatency(time.Since(start))
		metrics.AddSent(1)
		if i%10 == 0 {
			log.Printf("Отправлено в канал: key=%s", key)
		}
	}

	// Закрываем продюсера и ждём завершения обработчиков
	producer.AsyncClose()
	wg.Wait()

	metrics.Print()
	return nil
}

//MAIN

func main() {
	flag.Parse()

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	// Graceful shutdown
	sigCh := make(chan os.Signal, 1)
	signal.Notify(sigCh, os.Interrupt, os.Kill)
	go func() {
		<-sigCh
		log.Println("Получен сигнал завершения...")
		cancel()
	}()

	var err error
	if *asyncMode {
		err = RunAsyncProducer(ctx, *acksMode, *topic, *broker, *count)
	} else {
		err = RunSyncProducer(ctx, *acksMode, *topic, *broker, *count)
	}
	if err != nil {
		log.Fatalf("Ошибка: %v", err)
	}

	log.Println("Программа завершена")
}
